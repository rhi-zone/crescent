/* The shape that actually blocked libressl: a long comma-separated .value
   list as a read-only lookup table, from crypto/modes/ghash-elf-x86_64.S's
   .Lrem_8bit. Without the directive the assembler fell through to opcode
   parsing and reported "incorrect number of operands". */
