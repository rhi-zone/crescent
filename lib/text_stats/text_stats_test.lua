T.describe("analyze", function()
	local result = ts.analyze(EASY_TEXT)

	T.it("returns char_count", function()
		T.ok(result.char_count > 0)
	end)
	T.it("returns letter_count", function()
		T.ok(result.letter_count > 0)
	end)
	T.it("returns word_count", function()
		T.ok(result.word_count > 0)
	end)
	T.it("returns sentence_count", function()
		T.ok(result.sentence_count > 0)
	end)
	T.it("returns paragraph_count", function()
		T.ok(result.paragraph_count >= 0)
	end)
	T.it("returns syllable_count", function()
		T.ok(result.syllable_count > 0)
	end)
	T.it("returns avg_words_per_sentence", function()
		T.ok(result.avg_words_per_sentence > 0)
	end)
	T.it("returns avg_syllables_per_word", function()
		T.ok(result.avg_syllables_per_word > 0)
	end)
	T.it("returns flesch_reading_ease", function()
		T.ok(type(result.flesch_reading_ease) == "number")
	end)
	T.it("returns flesch_kincaid_grade", function()
		T.ok(type(result.flesch_kincaid_grade) == "number")
	end)
	T.it("returns gunning_fog", function()
		T.ok(type(result.gunning_fog) == "number")
	end)
	T.it("returns smog_grade", function()
		T.ok(type(result.smog_grade) == "number")
	end)
	T.it("returns automated_readability_index", function()
		T.ok(type(result.automated_readability_index) == "number")
	end)
	T.it("returns coleman_liau_index", function()
		T.ok(type(result.coleman_liau_index) == "number")
	end)
	T.it("returns reading_level string", function()
		T.ok(type(result.reading_level) == "string")
		T.ok(result.reading_level ~= "")
	end)
	T.it("reading_level is a valid category", function()
		local valid = {
			["very easy"]=true, ["easy"]=true, ["fairly easy"]=true,
			["standard"]=true, ["fairly hard"]=true, ["hard"]=true,
			["very hard"]=true,
		}
		T.ok(valid[result.reading_level], "unknown level: " .. result.reading_level)
	end)
	T.it("empty string returns zero-valued table", function()
		local r = ts.analyze("")
		T.eq(r.char_count, 0)
		T.eq(r.word_count, 0)
		T.eq(r.syllable_count, 0)
		T.eq(r.flesch_reading_ease, 0)
	end)
end)

