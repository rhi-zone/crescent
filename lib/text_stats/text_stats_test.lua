T.describe("word_frequency", function()
	T.it("counts each word correctly", function()
		local freq = ts.word_frequency("the cat sat on the mat")
		T.eq(freq["the"], 2)
		T.eq(freq["cat"], 1)
		T.eq(freq["sat"], 1)
		T.eq(freq["on"], 1)
		T.eq(freq["mat"], 1)
	end)
	T.it("lowercases words", function()
		local freq = ts.word_frequency("Cat CAT cat")
		T.eq(freq["cat"], 3)
	end)
	T.it("empty string returns empty table", function()
		local freq = ts.word_frequency("")
		T.eq(next(freq), nil)
	end)
	T.it("ignores punctuation as word boundaries", function()
		local freq = ts.word_frequency("hello, world! hello.")
		T.eq(freq["hello"], 2)
		T.eq(freq["world"], 1)
	end)
end)

T.describe("top_words", function()
	T.it("returns top n words by frequency", function()
		local top = ts.top_words("the cat sat on the mat the cat", 2)
		T.eq(#top, 2)
		T.eq(top[1].word, "the")
		T.eq(top[1].count, 3)
		T.eq(top[2].word, "cat")
		T.eq(top[2].count, 2)
	end)
	T.it("n larger than unique words returns all", function()
		local top = ts.top_words("one two three", 10)
		T.eq(#top, 3)
	end)
	T.it("empty string returns empty list", function()
		local top = ts.top_words("", 5)
		T.eq(#top, 0)
	end)
	T.it("first element is most frequent", function()
		local top = ts.top_words("a a a b b c", 3)
		T.eq(top[1].count, 3)
		T.eq(top[2].count, 2)
		T.eq(top[3].count, 1)
	end)
end)

T.describe("unique_words", function()
	T.it("counts distinct words", function()
		T.eq(ts.unique_words("the cat sat on the mat"), 5)
	end)
	T.it("case-insensitive", function()
		T.eq(ts.unique_words("Cat cat CAT"), 1)
	end)
	T.it("empty string returns 0", function()
		T.eq(ts.unique_words(""), 0)
	end)
	T.it("all unique", function()
		T.eq(ts.unique_words("one two three four"), 4)
	end)
end)

