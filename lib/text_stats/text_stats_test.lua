-- ---------------------------------------------------------------------------
-- Readability scores
-- ---------------------------------------------------------------------------

-- Simple test text: short, common words, short sentences
local EASY_TEXT = "The cat sat on the mat. The dog ran far. The sun was hot."

-- Complex text: longer sentences, polysyllabic words
local HARD_TEXT =
	"The implementation of sophisticated computational algorithms " ..
	"requires considerable understanding of mathematical fundamentals. " ..
	"Professionals must demonstrate comprehensive knowledge of theoretical " ..
	"foundations and practical applications simultaneously."

T.describe("flesch_reading_ease", function()
	T.it("simple text scores higher than complex text", function()
		local easy = ts.flesch_reading_ease(EASY_TEXT)
		local hard = ts.flesch_reading_ease(HARD_TEXT)
		T.ok(easy > hard, "easy (" .. easy .. ") should be > hard (" .. hard .. ")")
	end)
	T.it("returns a number", function()
		T.ok(type(ts.flesch_reading_ease(EASY_TEXT)) == "number")
	end)
	T.it("empty string returns 0", function()
		T.eq(ts.flesch_reading_ease(""), 0)
	end)
	T.it("simple text scores above 60", function()
		local score = ts.flesch_reading_ease(EASY_TEXT)
		T.ok(score > 60, "expected > 60, got " .. score)
	end)
	T.it("complex text scores below 60", function()
		local score = ts.flesch_reading_ease(HARD_TEXT)
		T.ok(score < 60, "expected < 60, got " .. score)
	end)
end)

T.describe("flesch_kincaid_grade", function()
	T.it("returns a number", function()
		T.ok(type(ts.flesch_kincaid_grade(EASY_TEXT)) == "number")
	end)
	T.it("empty string returns 0", function()
		T.eq(ts.flesch_kincaid_grade(""), 0)
	end)
	T.it("simple text has lower grade than complex", function()
		local easy = ts.flesch_kincaid_grade(EASY_TEXT)
		local hard = ts.flesch_kincaid_grade(HARD_TEXT)
		T.ok(easy < hard, "easy grade (" .. easy .. ") should be < hard (" .. hard .. ")")
	end)
	T.it("complex text grade is above 10", function()
		local grade = ts.flesch_kincaid_grade(HARD_TEXT)
		T.ok(grade > 10, "expected > 10, got " .. grade)
	end)
end)

