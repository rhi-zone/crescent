-- ---------------------------------------------------------------------------
-- Lexical diversity
-- ---------------------------------------------------------------------------

T.describe("avg_word_length", function()
	T.it("correct average for known input", function()
		-- "cat"=3, "dog"=3, "bird"=4 → avg = 10/3 ≈ 3.333
		local avg = ts.avg_word_length("cat dog bird")
		T.ok(avg > 3.3 and avg < 3.4, "expected ~3.33, got " .. avg)
	end)
	T.it("empty string returns 0", function()
		T.eq(ts.avg_word_length(""), 0)
	end)
	T.it("single word", function()
		T.eq(ts.avg_word_length("hello"), 5)
	end)
end)

T.describe("type_token_ratio", function()
	T.it("all unique words → ratio = 1.0", function()
		T.eq(ts.type_token_ratio("one two three"), 1.0)
	end)
	T.it("all same word → ratio = 1/n", function()
		local r = ts.type_token_ratio("cat cat cat cat")
		T.ok(r > 0.24 and r < 0.26, "expected 0.25, got " .. r)
	end)
	T.it("empty string returns 0", function()
		T.eq(ts.type_token_ratio(""), 0)
	end)
	T.it("partial repetition", function()
		-- "the the cat" → 2 unique / 3 total ≈ 0.667
		local r = ts.type_token_ratio("the the cat")
		T.ok(r > 0.66 and r < 0.68, "expected ~0.667, got " .. r)
	end)
end)

T.describe("lexical_density", function()
	T.it("returns a number between 0 and 1", function()
		local d = ts.lexical_density(EASY_TEXT)
		T.ok(d >= 0 and d <= 1, "expected 0-1, got " .. d)
	end)
	T.it("empty string returns 0", function()
		T.eq(ts.lexical_density(""), 0)
	end)
	T.it("all stopwords → low density", function()
		local d = ts.lexical_density("the and or but")
		T.ok(d < 0.1, "expected near 0, got " .. d)
	end)
	T.it("content-heavy text → high density", function()
		local d = ts.lexical_density("sophisticated algorithms generate beautiful mathematics")
		T.ok(d > 0.8, "expected > 0.8, got " .. d)
	end)
end)

-- ---------------------------------------------------------------------------
-- Frequency analysis
