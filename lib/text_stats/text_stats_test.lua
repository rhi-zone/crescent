-- lib/text_stats/text_stats_test.lua
-- Tests for text readability and statistics library.

if not package.path:find("./?/init.lua", 1, true) then
	package.path = "./?/init.lua;" .. package.path
end

local T = require("lib.test.assert")
local ts = require("lib.text_stats")

-- ---------------------------------------------------------------------------
-- Basic statistics
-- ---------------------------------------------------------------------------

T.describe("char_count", function()
	T.it("counts all characters including spaces", function()
		T.eq(ts.char_count("hello world"), 11)
	end)
	T.it("empty string returns 0", function()
		T.eq(ts.char_count(""), 0)
	end)
	T.it("counts newlines and punctuation", function()
		T.eq(ts.char_count("Hi!\nBye."), 8)
	end)
end)

T.describe("letter_count", function()
	T.it("counts only alphabetic characters", function()
		T.eq(ts.letter_count("hello world"), 10)
	end)
	T.it("excludes digits and punctuation", function()
		T.eq(ts.letter_count("abc 123 !@#"), 3)
	end)
	T.it("empty string returns 0", function()
		T.eq(ts.letter_count(""), 0)
	end)
	T.it("mixed case counts all letters", function()
		T.eq(ts.letter_count("Hello World"), 10)
	end)
end)

T.describe("word_count", function()
	T.it("counts simple space-separated words", function()
		T.eq(ts.word_count("one two three"), 3)
	end)
	T.it("handles multiple spaces", function()
		T.eq(ts.word_count("one  two   three"), 3)
	end)
	T.it("handles punctuation boundaries", function()
		T.eq(ts.word_count("Hello, world! How are you?"), 5)
	end)
	T.it("empty string returns 0", function()
		T.eq(ts.word_count(""), 0)
	end)
	T.it("single word", function()
		T.eq(ts.word_count("word"), 1)
	end)
end)

T.describe("sentence_count", function()
	T.it("counts period-terminated sentences", function()
		T.eq(ts.sentence_count("Hello. World."), 2)
	end)
	T.it("counts exclamation marks", function()
		T.eq(ts.sentence_count("Hi! Bye!"), 2)
	end)
	T.it("counts question marks", function()
		T.eq(ts.sentence_count("How are you? I am fine."), 2)
	end)
	T.it("ellipsis counts as one sentence terminator", function()
		T.eq(ts.sentence_count("Wait... okay."), 2)
	end)
	T.it("mixed punctuation", function()
		T.eq(ts.sentence_count("Really?! Yes! No."), 3)
	end)
	T.it("returns at least 1 for non-empty text without punctuation", function()
		T.eq(ts.sentence_count("no punctuation here"), 1)
	end)
	T.it("empty string returns 1 (minimum)", function()
		T.eq(ts.sentence_count(""), 1)
	end)
end)

T.describe("paragraph_count", function()
	T.it("single paragraph returns 1", function()
		T.eq(ts.paragraph_count("Hello world."), 1)
	end)
	T.it("two paragraphs separated by blank line", function()
		T.eq(ts.paragraph_count("Para one.\n\nPara two."), 2)
	end)
	T.it("three paragraphs", function()
		T.eq(ts.paragraph_count("A.\n\nB.\n\nC."), 3)
	end)
	T.it("empty string returns 0", function()
		T.eq(ts.paragraph_count(""), 0)
	end)
	T.it("whitespace-only returns 0", function()
		T.eq(ts.paragraph_count("   \n  "), 0)
	end)
end)

