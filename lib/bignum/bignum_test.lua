local T = require("lib.test.assert")
local bignum = require("lib.bignum")

-- ── Construction from string ──────────────────────────────────────────────────

T.describe("bignum.new from string", function()
  T.it("integer string", function()
    T.eq(bignum.new("42"):to_string(), "42")
  end)
  T.it("negative integer string", function()
    T.eq(bignum.new("-7"):to_string(), "-7")
  end)
  T.it("decimal string", function()
    T.eq(bignum.new("3.14"):to_string(), "3.14")
  end)
  T.it("negative decimal", function()
    T.eq(bignum.new("-0.001"):to_string(), "-0.001")
  end)
  T.it("leading zeros stripped in integer part", function()
    T.eq(bignum.new("007"):to_string(), "7")
  end)
  T.it("trailing zeros stripped in fractional part", function()
    T.eq(bignum.new("1.50000"):to_string(), "1.5")
  end)
  T.it("zero", function()
    T.eq(bignum.new("0"):to_string(), "0")
  end)
  T.it("negative zero normalizes to zero", function()
    T.eq(bignum.new("-0"):to_string(), "0")
    T.eq(bignum.new("-0"):sign(), 0)
  end)
  T.it("scientific notation positive exponent", function()
    T.eq(bignum.new("1e10"):to_string(), "10000000000")
  end)
  T.it("scientific notation negative exponent", function()
    T.eq(bignum.new("1e-3"):to_string(), "0.001")
  end)
  T.it("scientific notation with decimal", function()
    T.eq(bignum.new("1.5e2"):to_string(), "150")
  end)
  T.it("scientific notation 1.5e-2", function()
    T.eq(bignum.new("1.5e-2"):to_string(), "0.015")
  end)
  T.it("large integer string", function()
    local s = "12345678901234567890123456789012345678901234567890"
    T.eq(bignum.new(s):to_string(), s)
  end)
  T.it("very small number", function()
    T.eq(bignum.new("1e-20"):to_string(), "0." .. ("0"):rep(19) .. "1")
  end)
  T.it("pi digits", function()
    T.eq(bignum.new("3.14159265358979323846"):to_string(), "3.14159265358979323846")
  end)
  T.it("error on empty string", function()
    local v, err = bignum.new("")
    T.eq(v, nil)
    T.ok(err)
  end)
  T.it("error on non-numeric string", function()
    local v, err = bignum.new("abc")
    T.eq(v, nil)
    T.ok(err)
  end)
  T.it("error on bad type", function()
    local v, err = bignum.new(true)
    T.eq(v, nil)
    T.ok(err)
  end)
end)

