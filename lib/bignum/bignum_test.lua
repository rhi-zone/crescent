-- ── Edge cases ────────────────────────────────────────────────────────────────

T.describe("edge cases", function()
  T.it("1e50 round-trips", function()
    local s = bignum.new("1e50"):to_string()
    T.eq(s, "1" .. ("0"):rep(50))
  end)
  T.it("1e-20 round-trips", function()
    local s = bignum.new("1e-20"):to_string()
    T.eq(s, "0." .. ("0"):rep(19) .. "1")
  end)
  T.it("add two high-precision values", function()
    local a = bignum.new("3.14159265358979323846")
    local b = bignum.new("2.71828182845904523536")
    local s = (a + b):to_string()
    T.eq(s, "5.85987448204883847382")
  end)
  T.it("multiply then check identity: a*1=a", function()
    local a = bignum.new("3.14159265358979323846")
    T.eq((a * bignum.new("1")):to_string(), a:to_string())
  end)
  T.it("a - a = 0", function()
    local a = bignum.new("3.14159265358979323846")
    T.eq((a - a):to_string(), "0")
  end)
  T.it("a / a = 1 (to many places)", function()
    local a = bignum.new("3.14")
    local result = a:div(a, 10):to_string()
    T.ok(result:sub(1, 1) == "1", "got: " .. result)
  end)
  T.it("ZERO constant is zero", function()
    T.ok(bignum.ZERO:is_zero())
  end)
  T.it("ONE constant is one", function()
    T.eq(bignum.ONE:to_string(), "1")
  end)
  T.it("parse is alias for new", function()
    T.eq(bignum.parse("42"):to_string(), "42")
  end)
  T.it("clone via new(bignum)", function()
    local a = bignum.new("3.14")
    local b = bignum.new(a)
    T.eq(b:to_string(), "3.14")
  end)
