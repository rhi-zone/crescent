T.describe("V.record()", function()
  local schema = V.record({
    name  = V.string():min(1),
    age   = V.number():int():min(0),
    email = V.string():email():optional(),
  })

  T.it("valid record passes", function()
    T.ok(schema:check({ name = "Alice", age = 30 }))
  end)
  T.it("valid record with optional email passes", function()
    T.ok(schema:check({ name = "Alice", age = 30, email = "a@b.com" }))
  end)
  T.it("missing required field fails", function()
    local ok, err = schema:check({ age = 30 })
    T.fail(ok)
    T.ok(#err.errors > 0)
    local found_name = false
    for _, e in ipairs(err.errors) do
      if e.path == "name" then found_name = true end
    end
    T.ok(found_name)
  end)
  T.it("wrong field type fails", function()
    local ok, err = schema:check({ name = "Alice", age = "old" })
    T.fail(ok)
    local found_age = false
    for _, e in ipairs(err.errors) do
      if e.path:find("age") then found_age = true end
    end
    T.ok(found_age)
  end)
  T.it("extra keys are ignored", function()
    T.ok(schema:check({ name = "Alice", age = 1, extra = "ignored" }))
  end)
  T.it("non-table fails", function()
    local ok, _ = schema:check("not a table")
    T.fail(ok)
  end)
  T.it("parse: returns parsed values", function()
    local v, err = V.record({ x = V.number():coerce() }):parse({ x = "7" })
    T.eq(err, nil)
    T.eq(v.x, 7)
  end)
end)

