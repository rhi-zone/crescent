    T.eq(v, true)
  end)
  T.it("boolean:coerce: '1' → true", function()
    local v, err = V.boolean():coerce():parse("1")
    T.eq(err, nil)
    T.eq(v, true)
  end)
  T.it("boolean:coerce: 'yes' → true", function()
    local v, err = V.boolean():coerce():parse("yes")
    T.eq(err, nil)
    T.eq(v, true)
