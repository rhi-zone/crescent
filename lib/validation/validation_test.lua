T.describe("V.union()", function()
  local schema = V.union(V.string(), V.number())

  T.it("string matches", function()
    T.ok(schema:check("hello"))
  end)
  T.it("number matches", function()
    T.ok(schema:check(42))
  end)
  T.it("boolean fails", function()
    local ok, err = schema:check(true)
    T.fail(ok)
    T.ok(err)
  end)
  T.it("first match wins in parse", function()
    -- string coerce comes first — 42 will be valid number
    local v, err = V.union(V.number(), V.string()):parse(42)
    T.eq(err, nil)
    T.eq(v, 42)
  end)
end)

