T.describe("nested error paths", function()
  T.it("record within record has dotted path", function()
    local schema = V.record({
      address = V.record({
        zip = V.string():pattern("^%d%d%d%d%d$", "must be 5 digits"),
      }),
    })
    local ok, err = schema:check({ address = { zip = "bad" } })
    T.fail(ok)
    local found = false
    for _, e in ipairs(err.errors) do
      if e.path == "address.zip" then found = true end
    end
    T.ok(found)
  end)
  T.it("array element has indexed path", function()
    local schema = V.record({
      tags = V.array(V.string()),
    })
    local ok, err = schema:check({ tags = {"ok", 99, "also ok"} })
    T.fail(ok)
    local found = false
    for _, e in ipairs(err.errors) do
      if e.path:find("tags") and e.path:find("%[2%]") then found = true end
    end
    T.ok(found)
  end)
end)

