T.describe("V.custom()", function()
  local even = V.custom(function(v)
    if type(v) ~= "number" then return "must be a number" end
    if v % 2 ~= 0 then return "must be even" end
  end)

  T.it("passes for even number", function()
    T.ok(even:check(4))
  end)
  T.it("fails for odd number with custom message", function()
    local ok, err = even:check(3)
    T.fail(ok)
    T.eq(err.errors[1].message, "must be even")
  end)
  T.it("fails for wrong type with custom message", function()
    local ok, err = even:check("x")
    T.fail(ok)
    T.eq(err.errors[1].message, "must be a number")
  end)
end)

