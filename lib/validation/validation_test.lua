local T = require("lib.test.assert")
local V = require("lib.validation")

T.describe("V.string()", function()
  T.it("passes for strings", function()
    T.ok(V.string():check("hello"))
  end)
  T.it("fails for non-strings", function()
    local ok, err = V.string():check(42)
    T.fail(ok)
    T.ok(err)
    T.eq(err.errors[1].message, "expected string, got number")
  end)
  T.it("min: too short", function()
    local ok, err = V.string():min(3):check("ab")
    T.fail(ok)
    T.ok(err.errors[1].message:find("min 3"))
  end)
  T.it("min: exact length passes", function()
    T.ok(V.string():min(3):check("abc"))
  end)
  T.it("max: too long", function()
    local ok, err = V.string():max(5):check("toolong")
    T.fail(ok)
    T.ok(err.errors[1].message:find("max 5"))
  end)
  T.it("max: exact length passes", function()
    T.ok(V.string():max(5):check("hello"))
  end)
  T.it("pattern: match passes", function()
    T.ok(V.string():pattern("^%a+$"):check("abc"))
  end)
  T.it("pattern: mismatch fails", function()
    local ok, err = V.string():pattern("^%a+$", "only letters"):check("abc123")
    T.fail(ok)
    T.eq(err.errors[1].message, "only letters")
  end)
  T.it("email: valid", function()
    T.ok(V.string():email():check("user@example.com"))
  end)
  T.it("email: invalid", function()
    local ok, err = V.string():email():check("notanemail")
    T.fail(ok)
    T.ok(err.errors[1].message:find("email"))
  end)
  T.it("url: valid", function()
    T.ok(V.string():url():check("https://example.com/path"))
  end)
  T.it("url: invalid", function()
    local ok, err = V.string():url():check("notaurl")
    T.fail(ok)
    T.ok(err.errors[1].message:find("URL"))
  end)
  T.it("non_empty: non-empty passes", function()
    T.ok(V.string():non_empty():check("x"))
  end)
  T.it("non_empty: empty fails", function()
    local ok, err = V.string():non_empty():check("")
    T.fail(ok)
    T.ok(err.errors[1].message:find("empty"))
  end)
  T.it("required by default: nil fails", function()
    local ok, err = V.string():check(nil)
    T.fail(ok)
    T.eq(err.errors[1].message, "required")
  end)
end)

