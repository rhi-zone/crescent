T.describe("coercion", function()
  T.it("string:coerce: tostrings value", function()
    local v, err = V.string():coerce():parse(42)
    T.eq(err, nil)
    T.eq(v, "42")
  end)
  T.it("number:coerce: parses string", function()
    local v, err = V.number():coerce():parse("3.14")
    T.eq(err, nil)
    T.eq(v, 3.14)
  end)
  T.it("number:coerce: fails on non-numeric string", function()
    local v, err = V.number():coerce():parse("abc")
    T.eq(v, nil)
    T.ok(err)
  end)
  T.it("boolean:coerce: 'true' → true", function()
    local v, err = V.boolean():coerce():parse("true")
