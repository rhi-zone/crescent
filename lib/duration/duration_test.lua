-- ---------------------------------------------------------------------------
-- Arithmetic
-- ---------------------------------------------------------------------------

T.describe("arithmetic", function()
  T.it("add", function()
    T.eq(D.new(30):add(D.new(60)):total_seconds(), 90)
  end)
  T.it("sub", function()
    T.eq(D.new(90):sub(D.new(30)):total_seconds(), 60)
  end)
  T.it("mul", function()
    T.eq(D.new(60):mul(3):total_seconds(), 180)
  end)
  T.it("div", function()
    T.eq(D.new(180):div(3):total_seconds(), 60)
  end)
  T.it("neg", function()
    T.eq(D.new(30):neg():total_seconds(), -30)
  end)
  T.it("abs of negative", function()
    T.eq(D.new(-30):abs():total_seconds(), 30)
  end)
  T.it("abs of positive unchanged", function()
    T.eq(D.new(30):abs():total_seconds(), 30)
  end)
  T.it("add negative", function()
    T.eq(D.new(60):add(D.new(-30)):total_seconds(), 30)
  end)
  T.it("chained arithmetic", function()
    T.eq(D.new(60):mul(2):add(D.new(30)):total_seconds(), 150)
  end)
end)

-- ---------------------------------------------------------------------------
-- Comparison
-- ---------------------------------------------------------------------------

T.describe("comparison", function()
  T.it("eq same", function()
    T.ok(D.new(60):eq(D.new(60)))
  end)
  T.it("eq different is false", function()
    T.fail(D.new(60):eq(D.new(61)))
  end)
  T.it("lt", function()
    T.ok(D.new(30):lt(D.new(60)))
  end)
  T.it("lt false when equal", function()
    T.fail(D.new(60):lt(D.new(60)))
  end)
  T.it("lte equal", function()
    T.ok(D.new(60):lte(D.new(60)))
  end)
  T.it("lte less", function()
    T.ok(D.new(30):lte(D.new(60)))
  end)
  T.it("lte false when greater", function()
    T.fail(D.new(61):lte(D.new(60)))
  end)
  T.it("gt", function()
    T.ok(D.new(60):gt(D.new(30)))
  end)
  T.it("gt false when equal", function()
    T.fail(D.new(60):gt(D.new(60)))
  end)
  T.it("gte equal", function()
    T.ok(D.new(60):gte(D.new(60)))
  end)
  T.it("gte greater", function()
    T.ok(D.new(61):gte(D.new(60)))
  end)
  T.it("gte false when less", function()
    T.fail(D.new(59):gte(D.new(60)))
  end)
  T.it("negative vs positive", function()
    T.ok(D.new(-1):lt(D.new(1)))
  end)
end)

