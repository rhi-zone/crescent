  T.describe("mst", function()
    T.it("Kruskal MST on weighted triangle", function()
      local g = graph.new()
      g:add_node("a"); g:add_node("b"); g:add_node("c")
      g:add_edge("a", "b", {weight = 3})
      g:add_edge("b", "c", {weight = 1})
      g:add_edge("a", "c", {weight = 2})
      local mst = graph.mst(g)
      T.ok(mst)
      -- MST of triangle has 2 edges
      T.eq(#mst, 2)
      -- Smallest edges are b-c (1) and a-c (2) — total weight 3
      local total = 0
      for i = 1, #mst do
        local w = mst[i][3] and mst[i][3].weight or 1
        total = total + w
      end
      T.eq(total, 3)
    end)
