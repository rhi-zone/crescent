-- Sort an array for deterministic comparison
local function sorted(arr)
  local cp = {}
  for i = 1, #arr do cp[i] = arr[i] end
  table.sort(cp, function(a, b) return tostring(a) < tostring(b) end)
  return cp
end

-- Check whether arr contains val
local function has(arr, val)
  for i = 1, #arr do if arr[i] == val then return true end end
  return false
end

-- Find which component (index) contains vertex v
local function comp_of(comps, v)
  for i = 1, #comps do
    for j = 1, #comps[i] do
      if comps[i][j] == v then return i end
    end
  end
  return nil
end

