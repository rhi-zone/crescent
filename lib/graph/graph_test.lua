      g:add_node("a"); g:add_node("b"); g:add_node("c"); g:add_node("d")
      g:add_edge("a", "b", {weight = 1})
      g:add_edge("b", "c", {weight = 2})
      g:add_edge("c", "d", {weight = 3})
      g:add_edge("a", "d", {weight = 4})
      local mst = graph.mst(g)
      T.eq(#mst, 3)  -- V-1 edges for connected graph
      local total = 0
      for i = 1, #mst do
        local w = mst[i][3] and mst[i][3].weight or 1
        total = total + w
      end
      T.eq(total, 6)  -- 1+2+3
    end)
