    T.it("large chain traversal", function()
      local g = graph.new({directed = true})
      local N = 50
      for i = 1, N do g:add_node(i) end
      for i = 1, N-1 do g:add_edge(i, i+1, {weight = 1}) end
      local order = graph.bfs(g, 1)
      T.eq(#order, N)
      T.eq(order[1], 1); T.eq(order[N], N)
      local dist, path = graph.shortest_path(g, 1, N)
      T.eq(dist[N], N-1)
      T.eq(#path, N)
    end)
