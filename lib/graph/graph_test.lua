      dg:add_node("a"); dg:add_node("b"); dg:add_node("c")
      dg:add_edge("a", "b"); dg:add_edge("b", "c")
      local tt = graph.transpose(graph.transpose(dg))
      T.ok(tt:has_edge("a", "b"))
      T.ok(tt:has_edge("b", "c"))
      T.eq(tt:has_edge("b", "a"), false)
    end)
  end)

