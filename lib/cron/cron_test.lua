T.describe("edge cases", function()
  T.it("handles midnight boundary", function()
    local expr = cron.parse("0 0 * * *")
    T.ok(expr:matches(mktime(2026, 4, 11, 0, 0)))
    T.eq(expr:matches(mktime(2026, 4, 11, 0, 1)), false)
    T.eq(expr:matches(mktime(2026, 4, 11, 23, 59)), false)
  end)

  T.it("handles day-of-week wrapping (Sun=0 and Sun=7)", function()
    local expr0 = cron.parse("0 0 * * 0")
    local expr7 = cron.parse("0 0 * * 7")
    -- 2026-04-12 is Sunday
    local sunday = mktime(2026, 4, 12, 0, 0)
    T.ok(expr0:matches(sunday))
    T.ok(expr7:matches(sunday))
  end)

  T.it("handles all-stars with matches", function()
    local expr = cron.parse("* * * * *")
    -- Should match literally any time
    T.ok(expr:matches(mktime(2026, 1, 1, 0, 0)))
    T.ok(expr:matches(mktime(2026, 12, 31, 23, 59)))
    T.ok(expr:matches(mktime(2026, 6, 15, 12, 30)))
  end)

  T.it("handles month range with names", function()
    local expr = cron.parse("0 0 1 jan-mar *")
    T.ok(expr)
    T.ok(expr.months[1])
    T.ok(expr.months[2])
    T.ok(expr.months[3])
    T.eq(expr.months[4], nil)
  end)

  T.it("trims whitespace in expression", function()
    local expr = cron.parse("  0 0 * * *  ")
    T.ok(expr)
    T.ok(expr:matches(mktime(2026, 4, 11, 0, 0)))
  end)
end)
