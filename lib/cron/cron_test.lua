T.describe("expr:next_n", function()
  T.it("returns correct count", function()
    local expr = cron.parse("0 * * * *")
    local base = mktime(2026, 4, 11, 14, 0)
    local times = expr:next_n(base, 5)
    T.eq(#times, 5)
  end)

  T.it("returns sequential times", function()
    local expr = cron.parse("0 * * * *")
    local base = mktime(2026, 4, 11, 14, 0)
    local times = expr:next_n(base, 3)
    T.eq(#times, 3)
    -- Each should be 1 hour apart
    for i = 2, #times do
      T.ok(times[i] > times[i - 1], "times should be ascending")
    end
    local t1 = os.date("*t", times[1])
    local t2 = os.date("*t", times[2])
    local t3 = os.date("*t", times[3])
    T.eq(t1.hour, 15)
    T.eq(t2.hour, 16)
    T.eq(t3.hour, 17)
  end)

  T.it("all results match the expression", function()
    local expr = cron.parse("*/10 9-17 * * 1-5")
    local base = mktime(2026, 4, 11, 0, 0)
    local times = expr:next_n(base, 10)
    T.eq(#times, 10)
    for i = 1, #times do
      T.ok(expr:matches(times[i]), "result " .. i .. " should match")
    end
  end)
end)

