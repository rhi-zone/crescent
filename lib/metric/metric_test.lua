-- ── render() ─────────────────────────────────────────────────────────────────

T.describe("render", function()
  T.it("counter emits HELP and TYPE lines", function()
    local reg = M.registry()
    local c = reg:counter("req_total", "Total HTTP requests", {"method"})
    c:inc({method="GET"})
    local text = reg:render()
    T.ok(text:find("# HELP req_total Total HTTP requests", 1, true), "HELP line")
    T.ok(text:find("# TYPE req_total counter", 1, true), "TYPE line")
  end)

  T.it("counter emits label=value pairs", function()
    local reg = M.registry()
    local c = reg:counter("req_total", "help", {"method", "status"})
    c:inc({method="GET", status="200"})
    local text = reg:render()
    T.ok(text:find('method="GET"', 1, true), "method label")
    T.ok(text:find('status="200"', 1, true), "status label")
    T.ok(text:find("req_total{", 1, true), "metric name with labels")
  end)

  T.it("counter value is correct in output", function()
    local reg = M.registry()
    local c = reg:counter("req_total", "help", {"method"})
    c:inc({method="GET"}, 7)
    local text = reg:render()
    T.ok(text:find("} 7", 1, true), "value 7 in output")
  end)

  T.it("gauge emits TYPE gauge", function()
    local reg = M.registry()
    local g = reg:gauge("queue_depth", "help", {"queue"})
    g:set({queue="main"}, 42)
    local text = reg:render()
    T.ok(text:find("# TYPE queue_depth gauge", 1, true), "TYPE gauge")
    T.ok(text:find("} 42", 1, true), "value 42")
  end)

  T.it("histogram emits _bucket, _sum, _count", function()
    local reg = M.registry()
    local h = reg:histogram("latency", "help", {"method"}, {0.1, 0.5})
    h:observe({method="GET"}, 0.05)
    local text = reg:render()
    T.ok(text:find("# TYPE latency histogram", 1, true), "TYPE histogram")
    T.ok(text:find("latency_bucket{", 1, true), "_bucket lines")
    T.ok(text:find("latency_sum{", 1, true), "_sum line")
    T.ok(text:find("latency_count{", 1, true), "_count line")
  end)

  T.it("histogram bucket has le label", function()
    local reg = M.registry()
    local h = reg:histogram("latency", "help", {"method"}, {0.1, 0.5})
    h:observe({method="GET"}, 0.05)
    local text = reg:render()
    T.ok(text:find('le="0.1"', 1, true), "le=0.1 bucket")
    T.ok(text:find('le="0.5"', 1, true), "le=0.5 bucket")
    T.ok(text:find('le="+Inf"', 1, true), "+Inf bucket")
  end)

  T.it("summary emits _sum and _count", function()
    local reg = M.registry()
    local s = reg:summary("resp_size", "help", {"endpoint"})
    s:observe({endpoint="/api"}, 512)
    local text = reg:render()
    T.ok(text:find("# TYPE resp_size summary", 1, true), "TYPE summary")
    T.ok(text:find("resp_size_sum{", 1, true), "_sum line")
    T.ok(text:find("resp_size_count{", 1, true), "_count line")
  end)

  T.it("no-label metric renders without braces", function()
    local reg = M.registry()
    local c = reg:counter("simple_total", "help", {})
    c:inc({})
    local text = reg:render()
    T.ok(text:find("simple_total 1", 1, true), "no-label counter line")
  end)

  T.it("multiple metrics rendered in registration order", function()
    local reg = M.registry()
    reg:counter("aaa", "help", {})
    reg:gauge("bbb", "help", {})
    local text = reg:render()
    local pos_a = text:find("aaa", 1, true)
    local pos_b = text:find("bbb", 1, true)
    T.ok(pos_a ~= nil, "aaa present")
    T.ok(pos_b ~= nil, "bbb present")
    T.ok(pos_a < pos_b, "aaa before bbb")
  end)

  T.it("labels are sorted alphabetically in output", function()
    local reg = M.registry()
    local c = reg:counter("req_total", "help", {"z_label", "a_label"})
    c:inc({z_label="Z", a_label="A"})
    local text = reg:render()
    -- a_label should appear before z_label in the label string
    local pa = text:find('a_label="A"', 1, true)
    local pz = text:find('z_label="Z"', 1, true)
    T.ok(pa ~= nil, "a_label present")
    T.ok(pz ~= nil, "z_label present")
    T.ok(pa < pz, "a_label before z_label (sorted)")
  end)

  T.it("render ends with newline", function()
    local reg = M.registry()
    reg:counter("x", "h", {})
    local text = reg:render()
    T.eq(text:sub(-1), "\n", "ends with newline")
  end)
end)

-- ── reset() ───────────────────────────────────────────────────────────────────

T.describe("reset", function()
  T.it("counter values cleared after reset", function()
    local reg = M.registry()
    local c = reg:counter("req_total", "help", {"method"})
    c:inc({method="GET"}, 10)
    reg:reset()
    T.eq(c:get({method="GET"}), 0)
  end)

  T.it("gauge values cleared after reset", function()
    local reg = M.registry()
    local g = reg:gauge("q", "help", {})
    g:set({}, 99)
    reg:reset()
    T.eq(g:get({}), 0)
  end)

  T.it("histogram cleared after reset", function()
    local reg = M.registry()
    local h = reg:histogram("lat", "help", {}, {1})
    h:observe({}, 0.5)
    reg:reset()
    T.eq(h:count({}), 0)
    T.eq(h:sum({}), 0)
  end)

  T.it("summary cleared after reset", function()
    local reg = M.registry()
    local s = reg:summary("sz", "help", {})
    s:observe({}, 100)
    reg:reset()
    T.eq(s:count({}), 0)
    T.eq(s:sum({}), 0)
  end)

  T.it("metrics still registered (name/type intact) after reset", function()
    local reg = M.registry()
    reg:counter("req_total", "help", {"method"})
    reg:reset()
    -- registering the same name again should fail (still registered)
    T.throws(function() reg:counter("req_total", "help", {"method"}) end)
  end)
end)

