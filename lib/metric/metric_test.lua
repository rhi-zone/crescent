-- lib/metric/metric_test.lua
-- Tests for lib/metric: counter, gauge, histogram, summary, render, registry.

if not package.path:find("./?/init.lua", 1, true) then
  package.path = "./?/init.lua;" .. package.path
end

local T = require("lib.test.assert")
local M = require("lib.metric")

-- ── Counter ───────────────────────────────────────────────────────────────────

T.describe("counter", function()
  T.it("starts at zero for unseen label sets", function()
    local reg = M.registry()
    local c = reg:counter("req_total", "help", {"method"})
    T.eq(c:get({method="GET"}), 0)
    T.eq(c:get({method="POST"}), 0)
  end)

  T.it("inc by 1", function()
    local reg = M.registry()
    local c = reg:counter("req_total", "help", {"method"})
    c:inc({method="GET"})
    T.eq(c:get({method="GET"}), 1)
  end)

  T.it("inc by N", function()
    local reg = M.registry()
    local c = reg:counter("req_total", "help", {"method"})
    c:inc({method="GET"}, 5)
    T.eq(c:get({method="GET"}), 5)
  end)

  T.it("inc accumulates", function()
    local reg = M.registry()
    local c = reg:counter("req_total", "help", {"method"})
    c:inc({method="GET"})
    c:inc({method="GET"}, 3)
    T.eq(c:get({method="GET"}), 4)
  end)

  T.it("multi-label sets are independent", function()
    local reg = M.registry()
    local c = reg:counter("req_total", "help", {"method", "status"})
    c:inc({method="GET", status="200"})
    c:inc({method="POST", status="500"}, 3)
    T.eq(c:get({method="GET", status="200"}), 1)
    T.eq(c:get({method="POST", status="500"}), 3)
    T.eq(c:get({method="GET", status="500"}), 0)
  end)

  T.it("no labels counter works", function()
    local reg = M.registry()
    local c = reg:counter("simple_total", "help", {})
    c:inc({})
    c:inc({}, 9)
    T.eq(c:get({}), 10)
  end)

  T.it("errors on negative increment", function()
    local reg = M.registry()
    local c = reg:counter("req_total", "help", {"method"})
    T.throws(function() c:inc({method="GET"}, -1) end)
  end)

  T.it("errors on missing label", function()
    local reg = M.registry()
    local c = reg:counter("req_total", "help", {"method", "status"})
    T.throws(function() c:inc({method="GET"}) end)
  end)

  T.it("errors on extra label", function()
    local reg = M.registry()
    local c = reg:counter("req_total", "help", {"method"})
    T.throws(function() c:inc({method="GET", extra="bad"}) end)
  end)
end)

