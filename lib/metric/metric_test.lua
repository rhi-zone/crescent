-- ── Histogram ─────────────────────────────────────────────────────────────────

T.describe("histogram", function()
  T.it("observe increases count", function()
    local reg = M.registry()
    local h = reg:histogram("latency", "help", {"method"}, {0.1, 0.5, 1})
    h:observe({method="GET"}, 0.042)
    T.eq(h:count({method="GET"}), 1)
  end)

  T.it("observe accumulates sum", function()
    local reg = M.registry()
    local h = reg:histogram("latency", "help", {"method"}, {0.1, 0.5, 1})
    h:observe({method="GET"}, 0.1)
    h:observe({method="GET"}, 0.3)
    T.eq(h:sum({method="GET"}), 0.4)
  end)

  T.it("observe multiple times accumulates count", function()
    local reg = M.registry()
    local h = reg:histogram("latency", "help", {"method"}, {0.1, 0.5, 1})
    h:observe({method="GET"}, 0.05)
    h:observe({method="GET"}, 0.2)
    h:observe({method="GET"}, 0.8)
    T.eq(h:count({method="GET"}), 3)
  end)

  T.it("bucket distribution is cumulative", function()
    local reg = M.registry()
    local h = reg:histogram("latency", "help", {"method"}, {0.1, 0.5, 1})
    h:observe({method="GET"}, 0.05)  -- fits in 0.1, 0.5, 1, +Inf
    h:observe({method="GET"}, 0.2)   -- fits in 0.5, 1, +Inf
    h:observe({method="GET"}, 0.8)   -- fits in 1, +Inf
    local bkts = h:buckets({method="GET"})
    T.eq(bkts[0.1], 1)
    T.eq(bkts[0.5], 2)
    T.eq(bkts[1],   3)
    T.eq(bkts[math.huge], 3)  -- +Inf always equals count
  end)

  T.it("+Inf bucket always equals total count", function()
    local reg = M.registry()
    local h = reg:histogram("latency", "help", {}, {0.1})
    h:observe({}, 1000)
    h:observe({}, 2000)
    local bkts = h:buckets({})
    T.eq(bkts[math.huge], 2)
    T.eq(h:count({}), 2)
  end)

  T.it("zero for unseen label set (count/sum)", function()
    local reg = M.registry()
    local h = reg:histogram("latency", "help", {"method"}, {0.1})
    T.eq(h:count({method="GET"}), 0)
    T.eq(h:sum({method="GET"}), 0)
  end)

  T.it("zero for unseen label set (buckets)", function()
    local reg = M.registry()
    local h = reg:histogram("latency", "help", {"method"}, {0.1, 0.5})
    local bkts = h:buckets({method="GET"})
    T.eq(bkts[0.1], 0)
    T.eq(bkts[0.5], 0)
    T.eq(bkts[math.huge], 0)
  end)

  T.it("uses default buckets when none provided", function()
    local reg = M.registry()
    local h = reg:histogram("latency", "help", {})
    h:observe({}, 0.003)
    local bkts = h:buckets({})
    -- default has 0.005 as first bucket
    T.eq(bkts[0.005], 1)
    T.eq(bkts[0.01],  1)
    T.eq(bkts[10],    1)
    T.eq(bkts[math.huge], 1)
  end)

  T.it("multi-label sets are independent", function()
    local reg = M.registry()
    local h = reg:histogram("latency", "help", {"method"}, {0.5})
    h:observe({method="GET"}, 0.1)
    h:observe({method="POST"}, 0.9)
    T.eq(h:count({method="GET"}), 1)
    T.eq(h:count({method="POST"}), 1)
    T.eq(h:sum({method="GET"}), 0.1)
    T.eq(h:sum({method="POST"}), 0.9)
  end)
end)

