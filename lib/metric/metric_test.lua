-- ── Global default registry convenience ──────────────────────────────────────

T.describe("global registry", function()
  T.it("M.counter/gauge/histogram/summary are functions", function()
    T.eq(type(M.counter), "function")
    T.eq(type(M.gauge), "function")
    T.eq(type(M.histogram), "function")
    T.eq(type(M.summary), "function")
    T.eq(type(M.render), "function")
  end)

  T.it("M.render returns a string", function()
    -- reset default registry to known state
    M._reset_default()
    local text = M.render()
    T.eq(type(text), "string")
  end)

  T.it("M.counter adds to default registry and appears in M.render", function()
    M._reset_default()
    local c = M.counter("global_req", "help", {"method"})
    c:inc({method="GET"}, 2)
    local text = M.render()
    T.ok(text:find("global_req", 1, true), "metric in render output")
