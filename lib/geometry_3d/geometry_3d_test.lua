T.describe("mat4 transforms", function()
  T.it("identity leaves point unchanged", function()
    local m = G.mat4_identity()
    local v = G.vec3(3, 4, 5)
    local r = G.mat4_transform_point(m, v)
    T.ok(approx_vec3(r, v))
  end)

  T.it("translate moves point", function()
    local m = G.mat4_translate(1, 2, 3)
    local v = G.vec3(0, 0, 0)
    local r = G.mat4_transform_point(m, v)
    T.ok(approx(r.x, 1))
    T.ok(approx(r.y, 2))
    T.ok(approx(r.z, 3))
  end)

  T.it("translate does not move direction", function()
    local m = G.mat4_translate(10, 10, 10)
    local v = G.vec3(1, 0, 0)
    local r = G.mat4_transform_dir(m, v)
    T.ok(approx_vec3(r, v))
  end)

  T.it("rotate_x: y-axis → z-axis", function()
    local m = G.mat4_rotate_x(math.pi / 2)
    local v = G.vec3(0, 1, 0)
    local r = G.mat4_transform_dir(m, v)
    T.ok(approx(r.x, 0, 1e-5))
    T.ok(approx(r.y, 0, 1e-5))
    T.ok(approx(r.z, 1, 1e-5))
  end)

  T.it("rotate_z: x-axis → y-axis", function()
    local m = G.mat4_rotate_z(math.pi / 2)
    local v = G.vec3(1, 0, 0)
    local r = G.mat4_transform_dir(m, v)
    T.ok(approx(r.x, 0, 1e-5))
    T.ok(approx(r.y, 1, 1e-5))
    T.ok(approx(r.z, 0, 1e-5))
  end)

  T.it("scale", function()
    local m = G.mat4_scale(2, 3, 4)
    local v = G.vec3(1, 1, 1)
    local r = G.mat4_transform_point(m, v)
    T.ok(approx(r.x, 2))
    T.ok(approx(r.y, 3))
    T.ok(approx(r.z, 4))
  end)

  T.it("mat4_mul: translate then scale", function()
    -- translate by (1,0,0), then scale by 2 → point (0,0,0) → (1,0,0) → (2,0,0)
    local t = G.mat4_translate(1, 0, 0)
    local s = G.mat4_scale(2, 2, 2)
    local m = G.mat4_mul(s, t)
    local r = G.mat4_transform_point(m, G.vec3(0,0,0))
    T.ok(approx(r.x, 2, 1e-5))
    T.ok(approx(r.y, 0, 1e-5))
    T.ok(approx(r.z, 0, 1e-5))
  end)

  T.it("mat4_mul: identity * M = M", function()
    local id = G.mat4_identity()
    local t = G.mat4_translate(3, 4, 5)
    local m = G.mat4_mul(id, t)
    local v = G.vec3(0,0,0)
    local r1 = G.mat4_transform_point(m, v)
    local r2 = G.mat4_transform_point(t, v)
    T.ok(approx_vec3(r1, r2))
  end)
end)

T.describe("quaternion", function()
  T.it("quat_from_axis_angle 90° around Z", function()
    local q = G.quat_from_axis_angle(G.vec3(0,0,1), math.pi/2)
    local cos45 = math.cos(math.pi/4)
    local sin45 = math.sin(math.pi/4)
    T.ok(approx(q.w, cos45, 1e-6))
    T.ok(approx(q.x, 0,    1e-6))
    T.ok(approx(q.y, 0,    1e-6))
    T.ok(approx(q.z, sin45,1e-6))
  end)

  T.it("quat_rotate: (1,0,0) by 90° around Z = (0,1,0)", function()
    local q = G.quat_from_axis_angle(G.vec3(0,0,1), math.pi/2)
    local r = G.quat_rotate(q, G.vec3(1,0,0))
    T.ok(approx(r.x, 0, 1e-5))
    T.ok(approx(r.y, 1, 1e-5))
    T.ok(approx(r.z, 0, 1e-5))
  end)

  T.it("quat_rotate: (0,1,0) by 90° around Z = (-1,0,0)", function()
    local q = G.quat_from_axis_angle(G.vec3(0,0,1), math.pi/2)
    local r = G.quat_rotate(q, G.vec3(0,1,0))
    T.ok(approx(r.x, -1, 1e-5))
    T.ok(approx(r.y, 0,  1e-5))
    T.ok(approx(r.z, 0,  1e-5))
  end)

  T.it("quat_normalize", function()
    local q = G.quat(2, 0, 0, 0)
    local n = G.quat_normalize(q)
    T.ok(approx(n.w, 1))
    T.ok(approx(n.x, 0))
  end)

  T.it("quat_conjugate", function()
    local q = G.quat(0.5, 0.1, 0.2, 0.3)
    local c = G.quat_conjugate(q)
    T.eq(c.w,  0.5)
    T.eq(c.x, -0.1)
    T.eq(c.y, -0.2)
    T.eq(c.z, -0.3)
  end)

  T.it("quat_mul: identity * q = q", function()
    local id = G.quat(1, 0, 0, 0)
    local q  = G.quat_from_axis_angle(G.vec3(1,0,0), math.pi/3)
    local r  = G.quat_mul(id, q)
    T.ok(approx(r.w, q.w, 1e-10))
    T.ok(approx(r.x, q.x, 1e-10))
    T.ok(approx(r.y, q.y, 1e-10))
    T.ok(approx(r.z, q.z, 1e-10))
  end)

  T.it("quat_mul: q * conjugate = identity", function()
    local q = G.quat_normalize(G.quat_from_axis_angle(G.vec3(1,1,0), math.pi/4))
    local c = G.quat_conjugate(q)
    local r = G.quat_mul(q, c)
    T.ok(approx(r.w, 1, 1e-10))
    T.ok(approx(r.x, 0, 1e-10))
    T.ok(approx(r.y, 0, 1e-10))
    T.ok(approx(r.z, 0, 1e-10))
  end)

  T.it("quat_slerp t=0 returns a", function()
    local a = G.quat_from_axis_angle(G.vec3(0,1,0), 0)
    local b = G.quat_from_axis_angle(G.vec3(0,1,0), math.pi/2)
    local r = G.quat_slerp(a, b, 0)
    T.ok(approx(r.w, a.w, 1e-6))
    T.ok(approx(r.y, a.y, 1e-6))
  end)

  T.it("quat_slerp t=1 returns b", function()
    local a = G.quat_from_axis_angle(G.vec3(0,1,0), 0)
    local b = G.quat_from_axis_angle(G.vec3(0,1,0), math.pi/2)
    local r = G.quat_slerp(a, b, 1)
    T.ok(approx(r.w, b.w, 1e-6))
    T.ok(approx(r.y, b.y, 1e-6))
  end)

  T.it("quat_slerp t=0.5 midpoint (unit length)", function()
    local a = G.quat_from_axis_angle(G.vec3(0,1,0), 0)
    local b = G.quat_from_axis_angle(G.vec3(0,1,0), math.pi/2)
    local r = G.quat_slerp(a, b, 0.5)
    local len = math.sqrt(r.w*r.w + r.x*r.x + r.y*r.y + r.z*r.z)
    T.ok(approx(len, 1, 1e-6))
    -- midpoint is 45° rotation around Y
    local expected = G.quat_from_axis_angle(G.vec3(0,1,0), math.pi/4)
    T.ok(approx(math.abs(r.w), math.abs(expected.w), 1e-5))
    T.ok(approx(math.abs(r.y), math.abs(expected.y), 1e-5))
  end)
end)

T.describe("primitives", function()
  T.it("cube_mesh has 8 vertices and 12 faces", function()
    local mesh = G.cube_mesh()
    T.eq(#mesh.vertices, 8)
    T.eq(#mesh.faces, 12)
  end)

  T.it("sphere_mesh vertex count", function()
    local mesh = G.sphere_mesh(1, 4, 8)
    -- poles (2) + (lat_segs-1)*lon_segs rings = 2 + 3*8 = 26
    T.eq(#mesh.vertices, 26)
  end)

  T.it("sphere_mesh face count", function()
    local mesh = G.sphere_mesh(1, 4, 8)
    -- top cap: 8 + bottom cap: 8 + middle: (lat_segs-2)*lon_segs*2 = 2*8*2=32 → 8+8+16=32
    -- lat_segs=4: top_cap=8, bot_cap=8, middle=(4-2)*8*2=32 → total=48
    T.eq(#mesh.faces, 48)
  end)

  T.it("sphere_mesh with more segments", function()
    local mesh = G.sphere_mesh(1, 8, 16)
    -- 2 + 7*16 = 114 vertices
    T.eq(#mesh.vertices, 114)
    -- top: 16, bot: 16, middle: 6*16*2 = 192 → total = 224
    T.eq(#mesh.faces, 224)
  end)

  T.it("plane_mesh vertex count", function()
    local mesh = G.plane_mesh(1, 1, 2, 3)
    -- (w_segs+1)*(h_segs+1) = 3*4 = 12
    T.eq(#mesh.vertices, 12)
  end)

  T.it("plane_mesh face count", function()
    local mesh = G.plane_mesh(1, 1, 2, 3)
    -- w_segs*h_segs*2 = 2*3*2 = 12
