T.describe("ray_triangle (Möller-Trumbore)", function()
  local v0 = G.vec3(0,0,0)
  local v1 = G.vec3(1,0,0)
  local v2 = G.vec3(0,1,0)

  T.it("hits triangle from front", function()
    local r = G.ray(G.vec3(0.2, 0.2, -1), G.vec3(0,0,1))
    local t, u, v = G.ray_triangle(r, v0, v1, v2)
    T.ok(t ~= nil)
    T.ok(approx(t, 1))
    T.ok(u >= 0 and v >= 0 and u+v <= 1)
  end)

  T.it("misses triangle (off to side)", function()
    local r = G.ray(G.vec3(2, 0, -1), G.vec3(0,0,1))
    local t = G.ray_triangle(r, v0, v1, v2)
    T.eq(t, nil)
  end)

  T.it("parallel ray returns nil", function()
    local r = G.ray(G.vec3(0,0,1), G.vec3(1,0,0))
    local t = G.ray_triangle(r, v0, v1, v2)
    T.eq(t, nil)
  end)

  T.it("ray behind triangle returns nil", function()
    local r = G.ray(G.vec3(0.2, 0.2, 2), G.vec3(0,0,1))
    local t = G.ray_triangle(r, v0, v1, v2)
    T.eq(t, nil)
  end)
end)

T.describe("ray_sphere", function()
  local center = G.vec3(0,0,5)
  local radius = 1

  T.it("hits sphere (through center)", function()
    local r = G.ray(G.vec3(0,0,0), G.vec3(0,0,1))
    local t1, t2 = G.ray_sphere(r, center, radius)
    T.ok(t1 ~= nil)
    T.ok(approx(t1, 4))
    T.ok(approx(t2, 6))
  end)

  T.it("misses sphere", function()
    local r = G.ray(G.vec3(0,2,0), G.vec3(0,0,1))
    local t1 = G.ray_sphere(r, center, radius)
    T.eq(t1, nil)
  end)

  T.it("ray behind sphere returns negative t", function()
    local r = G.ray(G.vec3(0,0,10), G.vec3(0,0,1))
    local t1, t2 = G.ray_sphere(r, center, radius)
    -- t1 and t2 are both negative (sphere behind origin)
    T.ok(t1 ~= nil)
    T.ok(t2 < 0)
  end)
end)

T.describe("ray_aabb", function()
  local aabb = {min = G.vec3(-1,-1,-1), max = G.vec3(1,1,1)}

  T.it("hits AABB from -X side", function()
    local r = G.ray(G.vec3(-5,0,0), G.vec3(1,0,0))
    local tn, tf = G.ray_aabb(r, aabb)
    T.ok(tn ~= nil)
    T.ok(approx(tn, 4))
    T.ok(approx(tf, 6))
  end)

  T.it("misses AABB", function()
    local r = G.ray(G.vec3(0, 5, 0), G.vec3(1,0,0))
    local tn = G.ray_aabb(r, aabb)
    T.eq(tn, nil)
  end)

  T.it("ray origin inside AABB", function()
    local r = G.ray(G.vec3(0,0,0), G.vec3(1,0,0))
    local tn, tf = G.ray_aabb(r, aabb)
    T.ok(tn ~= nil)
    T.ok(tn <= 0)   -- near plane is behind
    T.ok(tf >= 1)   -- far plane is in front
  end)
end)

