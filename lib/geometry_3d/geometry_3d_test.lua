local T  = require("lib.test.assert")
local G  = require("lib.geometry_3d")

local function approx(a, b, eps)
  eps = eps or 1e-6
  return math.abs(a - b) < eps
end

local function approx_vec3(a, b, eps)
  return approx(a.x, b.x, eps) and approx(a.y, b.y, eps) and approx(a.z, b.z, eps)
end

T.describe("vec3 basics", function()
  T.it("vec3 constructor", function()
    local v = G.vec3(1, 2, 3)
    T.eq(v.x, 1)
    T.eq(v.y, 2)
    T.eq(v.z, 3)
  end)

  T.it("add3", function()
    local v = G.add3(G.vec3(1,2,3), G.vec3(4,5,6))
    T.eq(v.x, 5) T.eq(v.y, 7) T.eq(v.z, 9)
  end)

  T.it("sub3", function()
    local v = G.sub3(G.vec3(4,5,6), G.vec3(1,2,3))
    T.eq(v.x, 3) T.eq(v.y, 3) T.eq(v.z, 3)
  end)

  T.it("scale3", function()
    local v = G.scale3(G.vec3(1,2,3), 2)
    T.eq(v.x, 2) T.eq(v.y, 4) T.eq(v.z, 6)
  end)

  T.it("dot3", function()
    T.eq(G.dot3(G.vec3(1,0,0), G.vec3(0,1,0)), 0)
    T.eq(G.dot3(G.vec3(1,2,3), G.vec3(4,5,6)), 32)
  end)

  T.it("cross3", function()
    local c = G.cross3(G.vec3(1,0,0), G.vec3(0,1,0))
    T.eq(c.x, 0) T.eq(c.y, 0) T.eq(c.z, 1)
    local c2 = G.cross3(G.vec3(0,1,0), G.vec3(1,0,0))
    T.eq(c2.z, -1)
  end)

  T.it("len3", function()
    T.ok(approx(G.len3(G.vec3(3,4,0)), 5))
    T.ok(approx(G.len3(G.vec3(1,0,0)), 1))
  end)

  T.it("norm3", function()
    local n = G.norm3(G.vec3(3,0,0))
    T.ok(approx(n.x, 1)) T.ok(approx(n.y, 0)) T.ok(approx(n.z, 0))
    local n2 = G.norm3(G.vec3(1,1,0))
    T.ok(approx(G.len3(n2), 1))
  end)

  T.it("norm3 of zero vector", function()
    local n = G.norm3(G.vec3(0,0,0))
    T.eq(n.x, 0) T.eq(n.y, 0) T.eq(n.z, 0)
  end)

  T.it("neg3", function()
    local v = G.neg3(G.vec3(1,-2,3))
    T.eq(v.x, -1) T.eq(v.y, 2) T.eq(v.z, -3)
  end)
end)

