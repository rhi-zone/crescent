if float_ffi_ok then
	T.describe("float tier parity (ffi vs pure)", function()
		local samples = {
			0, 1, -1, 0.5, -0.5, 3.14159, -3.14159, 100, -100,
			1e10, -1e10, 1e-10, -1e-10, 1e300, -1e300, 1e-300,
			123456789.123, 0.1, 0.2, 0.3, 1 / 3, 2 ^ 52, -(2 ^ 52),
		}
		for _, n in ipairs(samples) do
			T.it("float32 pack matches for " .. n, function()
				T.eq(float_ffi.pack_float32(n), float_pure.pack_float32(n))
			end)
			T.it("float64 pack matches for " .. n, function()
				T.eq(float_ffi.pack_float64(n), float_pure.pack_float64(n))
			end)
		end
		T.it("float32 unpack matches across tiers", function()
			for _, n in ipairs(samples) do
				local packed = float_ffi.pack_float32(n)
				local b0, b1, b2, b3 = packed:byte(1, 4)
				T.eq(float_ffi.unpack_float32(b0, b1, b2, b3), float_pure.unpack_float32(b0, b1, b2, b3))
			end
		end)
		T.it("float64 unpack matches across tiers", function()
			for _, n in ipairs(samples) do
				local packed = float_ffi.pack_float64(n)
				local b0, b1, b2, b3, b4, b5, b6, b7 = packed:byte(1, 8)
				T.eq(
					float_ffi.unpack_float64(b0, b1, b2, b3, b4, b5, b6, b7),
					float_pure.unpack_float64(b0, b1, b2, b3, b4, b5, b6, b7)
				)
			end
		end)
	end)
end

T.describe("write_any / read_any", function()
	T.it("round-trips undefined (nil)", function()
		local enc = encoding.encoder()
		enc:write_any(nil)
		local dec = encoding.decoder(enc:to_string())
		local v, err = dec:read_any()
		T.eq(v, nil)
		T.eq(err, nil)
	end)
	T.it("round-trips null sentinel", function()
		local enc = encoding.encoder()
		enc:write_any(encoding.null)
		local dec = encoding.decoder(enc:to_string())
		T.eq(dec:read_any(), encoding.null)
	end)
	T.it("round-trips true", function()
		local enc = encoding.encoder()
		enc:write_any(true)
		local dec = encoding.decoder(enc:to_string())
		T.eq(dec:read_any(), true)
	end)
	T.it("round-trips false", function()
		local enc = encoding.encoder()
		enc:write_any(false)
		local dec = encoding.decoder(enc:to_string())
		T.eq(dec:read_any(), false)
	end)
	T.it("round-trips small integer via varInt (tag 125)", function()
		local enc = encoding.encoder()
		enc:write_any(42)
		T.eq(hex(enc:to_string()), "7d2a") -- tag 125 = 0x7d, varint(42) = 0x2a
		local dec = encoding.decoder(enc:to_string())
		T.eq(dec:read_any(), 42)
	end)
	T.it("round-trips negative integer", function()
		local enc = encoding.encoder()
		enc:write_any(-42)
		local dec = encoding.decoder(enc:to_string())
		T.eq(dec:read_any(), -42)
	end)
	T.it("round-trips a float64 (non-integer)", function()
		local enc = encoding.encoder()
		enc:write_any(3.14159)
		local dec = encoding.decoder(enc:to_string())
		T.eq(dec:read_any(), 3.14159)
	end)
	T.it("round-trips a float32-exact fraction", function()
		local enc = encoding.encoder()
		enc:write_any(0.5)
		local dec = encoding.decoder(enc:to_string())
		local tag = enc:to_string():byte(1)
		T.eq(tag, 124) -- 0.5 is exactly representable in float32
		T.eq(dec:read_any(), 0.5)
	end)
	T.it("round-trips a string", function()
		local enc = encoding.encoder()
		enc:write_any("hello")
		local dec = encoding.decoder(enc:to_string())
		T.eq(dec:read_any(), "hello")
	end)
	T.it("round-trips an array", function()
		local enc = encoding.encoder()
		enc:write_any({ 1, 2, 3 })
		local dec = encoding.decoder(enc:to_string())
		local arr = dec:read_any()
		T.eq(arr[1], 1)
		T.eq(arr[2], 2)
		T.eq(arr[3], 3)
	end)
	T.it("round-trips an empty array", function()
		local enc = encoding.encoder()
		enc:write_any({})
		T.eq(hex(enc:to_string()), "7500") -- tag 117 (array), length 0
		local dec = encoding.decoder(enc:to_string())
		local arr = dec:read_any()
		T.eq(next(arr), nil)
	end)
	T.it("round-trips a map/object", function()
		local enc = encoding.encoder()
		enc:write_any({ a = 1, b = "two" })
		local dec = encoding.decoder(enc:to_string())
		local obj = dec:read_any()
		T.eq(obj.a, 1)
		T.eq(obj.b, "two")
	end)
	T.it("round-trips a Uint8Array-equivalent buffer via write_var_buffer tag", function()
		-- writeAny doesn't have a direct "give me a Uint8Array" input from
		-- plain Lua values (Lua has no separate binary-string type), so this
		-- exercises tag 116 by decoding a hand-built frame instead.
		local enc = encoding.encoder()
		enc:write_uint8(116)
		enc:write_var_buffer("\1\2\3")
		local dec = encoding.decoder(enc:to_string())
		T.eq(dec:read_any(), "\1\2\3")
	end)
	T.it("round-trips nested structures", function()
		local enc = encoding.encoder()
		enc:write_any({ list = { 1, 2, { x = true, y = encoding.null } }, name = "crdt" })
		local dec = encoding.decoder(enc:to_string())
		local obj = dec:read_any()
		T.eq(obj.name, "crdt")
		T.eq(obj.list[1], 1)
		T.eq(obj.list[2], 2)
		T.eq(obj.list[3].x, true)
		T.eq(obj.list[3].y, encoding.null)
	end)
	T.it("rejects a non-string map key", function()
		local enc = encoding.encoder()
		-- sparse/non-sequential integer-keyed table is neither a clean array
		-- nor string-keyed map by our rules once mixed with a non-integer
		-- numeric key: forces the map path, and 2.5 is not a string key either
		local t = { [1] = "a", [2.5] = "b" }
		local ok, err = enc:write_any(t)
		T.eq(ok, nil)
		T.ok(err)
	end)
	T.it("encodes unrecognized types (function) as undefined", function()
		local enc = encoding.encoder()
		enc:write_any(print)
		T.eq(hex(enc:to_string()), "7f") -- tag 127
	end)
end)

T.describe("decoder position tracking", function()
	T.it("has_content reflects remaining bytes", function()
		local enc = encoding.encoder()
		enc:write_uint8(1)
		enc:write_uint8(2)
		local dec = encoding.decoder(enc:to_string())
		T.ok(dec:has_content())
		T.eq(dec:remaining(), 2)
		dec:read_uint8()
		T.ok(dec:has_content())
		T.eq(dec:remaining(), 1)
		dec:read_uint8()
		T.fail(dec:has_content())
		T.eq(dec:remaining(), 0)
	end)
end)

T.describe("mixed-primitive stream", function()
	T.it("round-trips a sequence of heterogeneous writes in order", function()
		local enc = encoding.encoder()
		enc:write_var_uint(7)
		enc:write_var_string("clientID")
		enc:write_var_int(-3)
		enc:write_float64(2.5)
		enc:write_uint8(9)

		local dec = encoding.decoder(enc:to_string())
		T.eq(dec:read_var_uint(), 7)
		T.eq(dec:read_var_string(), "clientID")
		T.eq(dec:read_var_int(), -3)
		T.eq(dec:read_float64(), 2.5)
		T.eq(dec:read_uint8(), 9)
		T.fail(dec:has_content())
	end)
end)
