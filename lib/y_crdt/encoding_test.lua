-- lib/y_crdt/encoding_test.lua
-- Tests for the lib0-compatible binary encoding layer.

if not package.path:find("./?/init.lua", 1, true) then
	package.path = "./?/init.lua;" .. package.path
end

local T = require("lib.test.assert")
local encoding = require("lib.y_crdt.encoding")
local float_ffi_ok, float_ffi = pcall(require, "lib.y_crdt.float_ffi")
local float_pure = require("lib.y_crdt.float_pure")

--: (string) -> string
local function hex(s)
	local out = s:gsub(".", function(c) return ("%02x"):format(c:byte()) end)
	return out
end

T.describe("tier", function()
	T.it("_tier is ffi or pure", function()
		T.ok(encoding._tier == "ffi" or encoding._tier == "pure")
	end)
end)

T.describe("write_uint8 / read_uint8", function()
	local cases = { 0, 1, 127, 128, 255 }
	for _, n in ipairs(cases) do
		T.it("round-trips " .. n, function()
			local enc = encoding.encoder()
			enc:write_uint8(n)
			local dec = encoding.decoder(enc:to_string())
			T.eq(dec:read_uint8(), n)
		end)
	end
	T.it("encodes as exactly one byte", function()
		local enc = encoding.encoder()
		enc:write_uint8(200)
		T.eq(#enc:to_string(), 1)
		T.eq(hex(enc:to_string()), "c8")
	end)
	T.it("rejects out-of-range value", function()
		local enc = encoding.encoder()
		T.throws(function() enc:write_uint8(256) end)
	end)
	T.it("rejects negative value", function()
		local enc = encoding.encoder()
		T.throws(function() enc:write_uint8(-1) end)
	end)
	T.it("read past end of buffer returns (nil, errmsg)", function()
		local dec = encoding.decoder("")
		local n, err = dec:read_uint8()
		T.eq(n, nil)
		T.ok(err)
	end)
end)

