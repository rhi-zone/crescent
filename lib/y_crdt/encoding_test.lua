T.describe("write_var_uint / read_var_uint", function()
	local cases = { 0, 1, 127, 128, 255, 256, 2 ^ 14, 2 ^ 21, 2 ^ 28, 2 ^ 35, 2 ^ 49 }
	for _, n in ipairs(cases) do
		T.it("round-trips " .. n, function()
			local enc = encoding.encoder()
			enc:write_var_uint(n)
			local dec = encoding.decoder(enc:to_string())
			T.eq(dec:read_var_uint(), n)
		end)
	end
	T.it("0 encodes as a single zero byte", function()
		local enc = encoding.encoder()
		enc:write_var_uint(0)
		T.eq(hex(enc:to_string()), "00")
	end)
	T.it("127 encodes as a single byte (no continuation)", function()
		local enc = encoding.encoder()
		enc:write_var_uint(127)
		T.eq(hex(enc:to_string()), "7f")
	end)
	T.it("128 encodes as two bytes (continuation set)", function()
		local enc = encoding.encoder()
		enc:write_var_uint(128)
		T.eq(hex(enc:to_string()), "8001")
	end)
	T.it("known byte sequence: 300 -> ac 02", function()
		local enc = encoding.encoder()
		enc:write_var_uint(300)
		T.eq(hex(enc:to_string()), "ac02")
	end)
	T.it("rejects negative value", function()
		local enc = encoding.encoder()
		T.throws(function() enc:write_var_uint(-1) end)
	end)
	T.it("rejects non-integer value", function()
		local enc = encoding.encoder()
		T.throws(function() enc:write_var_uint(1.5) end)
	end)
	T.it("truncated buffer returns (nil, errmsg)", function()
		local enc = encoding.encoder()
		enc:write_var_uint(128) -- two bytes, continuation set on the first
		local truncated = enc:to_string():sub(1, 1)
		local dec = encoding.decoder(truncated)
		local n, err = dec:read_var_uint()
		T.eq(n, nil)
		T.ok(err)
	end)
end)

