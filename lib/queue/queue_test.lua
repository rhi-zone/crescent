T.describe("queue.new: push_front / pop_back", function()
  T.it("push_front adds to front", function()
    local q = queue.new()
    q:push(2)
    q:push(3)
    q:push_front(1)
    T.eq(q:pop(), 1)
    T.eq(q:pop(), 2)
    T.eq(q:pop(), 3)
  end)

  T.it("pop_back removes from back", function()
    local q = queue.new()
    q:push(1)
    q:push(2)
    q:push(3)
    T.eq(q:pop_back(), 3)
    T.eq(q:pop_back(), 2)
    T.eq(q:pop_back(), 1)
    T.eq(q:pop_back(), nil)
  end)

  T.it("pop_back on empty returns nil", function()
    local q = queue.new()
    T.eq(q:pop_back(), nil)
  end)

  T.it("deque pattern: push front + pop front", function()
    local q = queue.new()
    q:push_front(3)
    q:push_front(2)
    q:push_front(1)
    T.eq(q:pop(), 1)
    T.eq(q:pop(), 2)
    T.eq(q:pop(), 3)
  end)

  T.it("deque pattern: push back + pop back (stack)", function()
    local q = queue.new()
    q:push(1)
    q:push(2)
    q:push(3)
    T.eq(q:pop_back(), 3)
    T.eq(q:pop_back(), 2)
    T.eq(q:pop_back(), 1)
  end)
end)

