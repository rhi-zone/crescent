T.describe("queue: wrap", function()
	T.it("wraps existing db", function()
		local db, err = sqlite.open(":memory:")
		T.ok(db, "sqlite.open should succeed")
		local q, wrap_err = queue.wrap(db)
		T.ok(q, "wrap should succeed")
		T.eq(wrap_err, nil)
		local id = q:push("test", { x = 1 })
		T.ok(id)
		local job = q:pop("test")
		T.ok(job)
		T.eq(job.payload.x, 1)
		q:close()
	end)
end)
