T.describe("queue.new: growth (ring-buffer wrap-around)", function()
  T.it("handles many pushes beyond initial capacity", function()
    local q = queue.new()
    -- Push more than initial cap (8) to force growth
    for i = 1, 20 do q:push(i) end
    T.eq(q:size(), 20)
    for i = 1, 20 do
      T.eq(q:pop(), i)
    end
    T.ok(q:is_empty())
  end)

  T.it("interleaved push/pop with wrap-around", function()
    local q = queue.new()
    -- Fill nearly to initial capacity, drain halfway, then fill again
    for i = 1, 6 do q:push(i) end
    for i = 1, 3 do q:pop() end  -- head wraps
    for i = 7, 20 do q:push(i) end  -- forces growth across wrap
    T.eq(q:pop(), 4)
    T.eq(q:pop(), 5)
    T.eq(q:pop(), 6)
    T.eq(q:pop(), 7)
  end)

  T.it("push_front with growth preserves order", function()
    local q = queue.new()
    for i = 1, 8 do q:push(i) end  -- fill to initial cap
    q:push_front(0)  -- triggers growth; queue is now [0,1,2,3,4,5,6,7,8]
    T.eq(q:size(), 9)
    T.eq(q:pop(), 0)   -- front
    T.eq(q:pop(), 1)   -- next
    T.eq(q:pop(), 2)   -- next
    -- drain the rest
    for i = 3, 8 do q:pop() end
    T.eq(q:size(), 0)
    T.ok(q:is_empty())
  end)
end)

-- ============================================================================
-- Fixed-capacity Ring Buffer
-- ============================================================================

T.describe("ring_new: capacity and basic ops", function()
  T.it("capacity returns the configured capacity", function()
    local rb = queue.ring_new(4)
    T.eq(rb:capacity(), 4)
  end)

  T.it("is_empty and size on fresh buffer", function()
    local rb = queue.ring_new(4)
    T.ok(rb:is_empty())
    T.eq(rb:size(), 0)
    T.ok(not rb:is_full())
  end)

  T.it("push/pop in FIFO order", function()
    local rb = queue.ring_new(4)
    rb:push(1)
    rb:push(2)
    rb:push(3)
    T.eq(rb:pop(), 1)
    T.eq(rb:pop(), 2)
    T.eq(rb:pop(), 3)
    T.eq(rb:pop(), nil)
  end)

  T.it("pop on empty returns nil", function()
    local rb = queue.ring_new(3)
    T.eq(rb:pop(), nil)
  end)
end)

T.describe("ring_new: peek", function()
  T.it("peek returns oldest without removing", function()
    local rb = queue.ring_new(4)
    rb:push(10)
    rb:push(20)
    T.eq(rb:peek(), 10)
    T.eq(rb:size(), 2)
    T.eq(rb:peek(), 10)
  end)

  T.it("peek on empty returns nil", function()
    local rb = queue.ring_new(2)
    T.eq(rb:peek(), nil)
  end)
end)

T.describe("ring_new: is_full and overwrite", function()
  T.it("is_full when at capacity", function()
    local rb = queue.ring_new(3)
    rb:push(1)
    rb:push(2)
    T.ok(not rb:is_full())
    rb:push(3)
    T.ok(rb:is_full())
  end)

  T.it("push when full overwrites oldest", function()
    local rb = queue.ring_new(4)
    rb:push(1)
    rb:push(2)
    rb:push(3)
    rb:push(4)
    T.ok(rb:is_full())
    rb:push(5)  -- overwrites 1
    T.eq(rb:size(), 4)
    T.eq(rb:pop(), 2)
    T.eq(rb:pop(), 3)
    T.eq(rb:pop(), 4)
    T.eq(rb:pop(), 5)
  end)

  T.it("multiple overwrites keep correct oldest", function()
    local rb = queue.ring_new(3)
    rb:push(1)
    rb:push(2)
    rb:push(3)
    rb:push(4)  -- overwrites 1
    rb:push(5)  -- overwrites 2
    T.eq(rb:size(), 3)
    T.eq(rb:pop(), 3)
    T.eq(rb:pop(), 4)
    T.eq(rb:pop(), 5)
    T.ok(rb:is_empty())
  end)
end)

T.describe("ring_new: to_array", function()
  T.it("returns elements in oldest-to-newest order", function()
    local rb = queue.ring_new(4)
    rb:push(10)
    rb:push(20)
    rb:push(30)
    local arr = rb:to_array()
    T.eq(#arr, 3)
    T.eq(arr[1], 10)
    T.eq(arr[2], 20)
    T.eq(arr[3], 30)
  end)

  T.it("to_array after overflow shows correct order", function()
    local rb = queue.ring_new(4)
    rb:push(1)
    rb:push(2)
    rb:push(3)
    rb:push(4)
    rb:push(5)  -- overwrites 1
    local arr = rb:to_array()
    T.eq(#arr, 4)
    T.eq(arr[1], 2)
    T.eq(arr[2], 3)
    T.eq(arr[3], 4)
    T.eq(arr[4], 5)
  end)

  T.it("to_array does not consume the buffer", function()
    local rb = queue.ring_new(3)
    rb:push(1)
    rb:push(2)
    rb:to_array()
    T.eq(rb:size(), 2)
    T.eq(rb:pop(), 1)
  end)

  T.it("empty buffer returns empty array", function()
    local rb = queue.ring_new(4)
    local arr = rb:to_array()
    T.eq(#arr, 0)
  end)
end)

T.describe("ring_new: mixed push/pop with wrap-around", function()
  T.it("correct order after partial drain and refill", function()
    local rb = queue.ring_new(4)
    rb:push(1)
    rb:push(2)
    rb:push(3)
    rb:pop()   -- remove 1
    rb:push(4)
    rb:push(5)  -- full now: {2,3,4,5}
    rb:push(6)  -- overwrites 2: {3,4,5,6}
    local arr = rb:to_array()
    T.eq(arr[1], 3)
    T.eq(arr[2], 4)
    T.eq(arr[3], 5)
    T.eq(arr[4], 6)
  end)
end)

T.describe("ring_new: capacity-1 edge case", function()
  T.it("capacity 1: second push overwrites first", function()
    local rb = queue.ring_new(1)
    rb:push(1)
    T.ok(rb:is_full())
    rb:push(2)
    T.eq(rb:size(), 1)
    T.eq(rb:pop(), 2)
  end)
end)

T.describe("ring_new: error on bad capacity", function()
  T.it("returns nil, errmsg for zero capacity", function()
    local rb, err = queue.ring_new(0)
    T.eq(rb, nil)
    T.ok(err ~= nil)
  end)

  T.it("returns nil, errmsg for negative capacity", function()
    local rb, err = queue.ring_new(-1)
    T.eq(rb, nil)
    T.ok(err ~= nil)
  end)
end)
