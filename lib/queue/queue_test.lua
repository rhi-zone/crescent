local T = require("lib.test.assert")
local queue = require("lib.queue")

-- ============================================================================
-- Priority Queue (min-heap)
-- ============================================================================

T.describe("priority_new: basic push/pop order", function()
  T.it("pops in ascending order (min-heap)", function()
    local pq = queue.priority_new()
    pq:push(5)
    pq:push(3)
    pq:push(7)
    pq:push(1)
    pq:push(9)
    T.eq(pq:pop(), 1)
    T.eq(pq:pop(), 3)
    T.eq(pq:pop(), 5)
    T.eq(pq:pop(), 7)
    T.eq(pq:pop(), 9)
  end)

  T.it("pop on empty returns nil", function()
    local pq = queue.priority_new()
    T.eq(pq:pop(), nil)
  end)

  T.it("single element push/pop", function()
    local pq = queue.priority_new()
    pq:push(42)
    T.eq(pq:pop(), 42)
    T.eq(pq:pop(), nil)
  end)
end)

T.describe("priority_new: peek", function()
  T.it("peek returns top without removing", function()
    local pq = queue.priority_new()
    pq:push(10)
    pq:push(2)
    pq:push(8)
    T.eq(pq:peek(), 2)
    T.eq(pq:size(), 3)
    T.eq(pq:peek(), 2)  -- still there
  end)

  T.it("peek on empty returns nil", function()
    local pq = queue.priority_new()
    T.eq(pq:peek(), nil)
  end)
end)

T.describe("priority_new: size and is_empty", function()
  T.it("tracks size correctly", function()
    local pq = queue.priority_new()
    T.eq(pq:size(), 0)
    T.ok(pq:is_empty())
    pq:push(1)
    T.eq(pq:size(), 1)
    T.ok(not pq:is_empty())
    pq:push(2)
    T.eq(pq:size(), 2)
    pq:pop()
    T.eq(pq:size(), 1)
    pq:pop()
    T.eq(pq:size(), 0)
    T.ok(pq:is_empty())
  end)
end)

T.describe("priority_new: custom comparator (max-heap)", function()
  T.it("pops in descending order", function()
    local pq = queue.priority_new(function(a, b) return a > b end)
    pq:push(5)
    pq:push(3)
    pq:push(7)
    pq:push(1)
    pq:push(9)
    T.eq(pq:pop(), 9)
    T.eq(pq:pop(), 7)
    T.eq(pq:pop(), 5)
    T.eq(pq:pop(), 3)
    T.eq(pq:pop(), 1)
  end)
end)

T.describe("priority_new: priority pairs", function()
  T.it("sorts by first element of pair", function()
    local pq = queue.priority_new(function(a, b) return a[1] < b[1] end)
    pq:push({10, "high priority"})
    pq:push({1,  "low priority"})
    pq:push({5,  "mid priority"})
    local top = pq:pop()
    T.eq(top[1], 1)
    T.eq(top[2], "low priority")
    local mid = pq:pop()
    T.eq(mid[1], 5)
    local last = pq:pop()
    T.eq(last[1], 10)
  end)
end)

T.describe("priority_new: push_all", function()
  T.it("pushes all values and heap property holds", function()
    local pq = queue.priority_new()
    pq:push_all({8, 2, 4, 6, 1, 9, 3})
    T.eq(pq:size(), 7)
    local prev = -math.huge
    -- pop-all should give ascending order
    local ok = true
    for _ = 1, 7 do
      local v = pq:pop()
      if v < prev then ok = false end
      prev = v
    end
    T.ok(ok, "expected ascending order")
  end)

  T.it("push_all on empty array is a no-op", function()
    local pq = queue.priority_new()
    pq:push_all({})
    T.eq(pq:size(), 0)
  end)
end)

T.describe("priority_new: interleaved push/pop", function()
  T.it("heap property maintained across interleaved ops", function()
    local pq = queue.priority_new()
    pq:push(5)
    pq:push(3)
    T.eq(pq:pop(), 3)
    pq:push(1)
    pq:push(4)
    T.eq(pq:pop(), 1)
    T.eq(pq:pop(), 4)
    T.eq(pq:pop(), 5)
    T.ok(pq:is_empty())
  end)
end)

-- ============================================================================
-- heapify
-- ============================================================================

T.describe("heapify", function()
  T.it("builds correct min-heap from unsorted array", function()
    local pq = queue.heapify({5, 3, 7, 1, 9, 2})
    T.eq(pq:pop(), 1)
    T.eq(pq:pop(), 2)
    T.eq(pq:pop(), 3)
    T.eq(pq:pop(), 5)
    T.eq(pq:pop(), 7)
    T.eq(pq:pop(), 9)
  end)

  T.it("does not modify source array", function()
    local src = {5, 3, 7, 1}
    queue.heapify(src)
    T.eq(src[1], 5)
    T.eq(src[2], 3)
    T.eq(src[3], 7)
    T.eq(src[4], 1)
  end)

  T.it("single-element array", function()
    local pq = queue.heapify({42})
    T.eq(pq:pop(), 42)
    T.eq(pq:pop(), nil)
  end)

  T.it("empty array", function()
    local pq = queue.heapify({})
    T.ok(pq:is_empty())
    T.eq(pq:pop(), nil)
  end)

  T.it("custom comparator (max-heap)", function()
    local pq = queue.heapify({5, 3, 7, 1, 9}, function(a, b) return a > b end)
    T.eq(pq:pop(), 9)
    T.eq(pq:pop(), 7)
    T.eq(pq:pop(), 5)
  end)
end)

-- ============================================================================
-- heapsort
-- ============================================================================

T.describe("heapsort", function()
  T.it("sorts ascending by default", function()
    local sorted = queue.heapsort({5, 3, 7, 1, 9})
    T.eq(sorted[1], 1)
    T.eq(sorted[2], 3)
    T.eq(sorted[3], 5)
    T.eq(sorted[4], 7)
    T.eq(sorted[5], 9)
  end)

  T.it("does not modify source array", function()
    local src = {5, 3, 7, 1}
    queue.heapsort(src)
    T.eq(src[1], 5)
    T.eq(src[2], 3)
    T.eq(src[3], 7)
    T.eq(src[4], 1)
  end)

  T.it("empty array returns empty", function()
    local sorted = queue.heapsort({})
    T.eq(#sorted, 0)
  end)

  T.it("single element", function()
    local sorted = queue.heapsort({42})
    T.eq(#sorted, 1)
    T.eq(sorted[1], 42)
  end)

  T.it("already sorted array", function()
    local sorted = queue.heapsort({1, 2, 3, 4, 5})
    T.eq(sorted[1], 1)
    T.eq(sorted[5], 5)
  end)

  T.it("reverse sorted array", function()
    local sorted = queue.heapsort({9, 7, 5, 3, 1})
    T.eq(sorted[1], 1)
    T.eq(sorted[5], 9)
  end)

  T.it("custom comparator (descending)", function()
    local sorted = queue.heapsort({5, 3, 7, 1, 9}, function(a, b) return a > b end)
    T.eq(sorted[1], 9)
    T.eq(sorted[2], 7)
    T.eq(sorted[3], 5)
    T.eq(sorted[4], 3)
    T.eq(sorted[5], 1)
  end)

  T.it("duplicate values", function()
    local sorted = queue.heapsort({3, 1, 4, 1, 5, 9, 2, 6})
    T.eq(sorted[1], 1)
    T.eq(sorted[2], 1)
    T.eq(sorted[3], 2)
    T.eq(sorted[4], 3)
  end)
end)

