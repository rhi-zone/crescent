    q:push(2)
    q:push(3)
    T.eq(q:pop(), 1)
    T.eq(q:pop(), 2)
    T.eq(q:pop(), 3)
  end)

  T.it("pop on empty returns nil", function()
    local q = queue.new()
    T.eq(q:pop(), nil)
  end)

  T.it("enqueue/dequeue aliases work", function()
    local q = queue.new()
    q:enqueue(10)
    q:enqueue(20)
    T.eq(q:dequeue(), 10)
    T.eq(q:dequeue(), 20)
    T.eq(q:dequeue(), nil)
  end)
end)

T.describe("queue.new: peek", function()
  T.it("peek returns front without removing", function()
    local q = queue.new()
    q:push(1)
    q:push(2)
    T.eq(q:peek(), 1)
    T.eq(q:size(), 2)
    T.eq(q:peek(), 1)
  end)

  T.it("peek on empty returns nil", function()
