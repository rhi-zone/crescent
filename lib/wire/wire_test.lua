-- ---------------------------------------------------------------------------
-- Reader position methods
-- ---------------------------------------------------------------------------
T.describe("reader position", function()
	T.it("pos() starts at 1", function()
		local r = M.reader("abc")
		T.eq(r:pos(), 1)
	end)
	T.it("pos() advances after reads", function()
		local r = M.reader("abcd")
		r:uint8()
		T.eq(r:pos(), 2)
		r:uint16_le()
		T.eq(r:pos(), 4)
	end)
	T.it("remaining() counts bytes left", function()
		local r = M.reader("abcde")
		T.eq(r:remaining(), 5)
		r:bytes(2)
		T.eq(r:remaining(), 3)
	end)
	T.it("at_end() false when data remains", function()
		local r = M.reader("a")
		T.ok(not r:at_end())
	end)
	T.it("at_end() true when exhausted", function()
		local r = M.reader("a")
		r:uint8()
		T.ok(r:at_end())
	end)
	T.it("seek() moves position", function()
		local r = M.reader("abcde")
		r:seek(3)
		T.eq(r:pos(), 3)
		T.eq(r:uint8(), string.byte("c"))
	end)
	T.it("peek() does not advance", function()
		local r = M.reader("abcde")
		local s = r:peek(3)
		T.eq(s, "abc")
		T.eq(r:pos(), 1)
	end)
	T.it("skip() advances without returning data", function()
		local r = M.reader("abcde")
		r:skip(2)
		T.eq(r:pos(), 3)
		T.eq(r:uint8(), string.byte("c"))
	end)
end)

