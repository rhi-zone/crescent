-- ---------------------------------------------------------------------------
-- varint (LEB128 unsigned)
-- ---------------------------------------------------------------------------
T.describe("varint", function()
	local cases = {
		{ 0,      "\x00" },
		{ 1,      "\x01" },
		{ 127,    "\x7f" },
		{ 128,    "\x80\x01" },
		{ 300,    "\xac\x02" },
		{ 65535,  "\xff\xff\x03" },
		{ 268435455, "\xff\xff\xff\x7f" },
	}
	for _, c in ipairs(cases) do
		local n, expected = c[1], c[2]
		T.it("encodes " .. n, function()
			local w = M.writer()
			w:varint(n)
			T.eq(w:build(), expected)
		end)
		T.it("round-trips " .. n, function()
			local w = M.writer()
			w:varint(n)
			local r = M.reader(w:build())
			T.eq(r:varint(), n)
		end)
	end
end)

-- ---------------------------------------------------------------------------
-- varint_signed (zigzag)
-- ---------------------------------------------------------------------------
T.describe("varint_signed", function()
	-- zigzag: 0->0, -1->1, 1->2, -2->3, 2->4
	local cases = {
		{ 0,  0 },
		{ -1, 1 },
		{ 1,  2 },
		{ -2, 3 },
		{ 2,  4 },
		{ -64, 127 },
		{ 64,  128 },
	}
	for _, c in ipairs(cases) do
		local n, zz = c[1], c[2]
		T.it("zigzag " .. n .. " -> " .. zz, function()
			local w = M.writer()
			w:varint_signed(n)
			-- the encoded bytes should be the varint of zz
			local w2 = M.writer()
			w2:varint(zz)
			T.eq(w:build(), w2:build())
		end)
		T.it("round-trips " .. n, function()
			local w = M.writer()
			w:varint_signed(n)
			local r = M.reader(w:build())
			T.eq(r:varint_signed(), n)
		end)
	end
end)

