-- ---------------------------------------------------------------------------
-- uint16 LE / BE
-- ---------------------------------------------------------------------------
T.describe("uint16", function()
	T.it("uint16_le round-trip", function()
		local w = M.writer()
		w:uint16_le(0x1234)
		local data = w:build()
		T.eq(#data, 2)
		local r = M.reader(data)
		T.eq(r:uint16_le(), 0x1234)
	end)
	T.it("uint16_be round-trip", function()
		local w = M.writer()
		w:uint16_be(0x1234)
		local data = w:build()
		T.eq(#data, 2)
		local r = M.reader(data)
		T.eq(r:uint16_be(), 0x1234)
	end)
	T.it("LE and BE byte order differs", function()
		local w1, w2 = M.writer(), M.writer()
		w1:uint16_le(0x0102)
		w2:uint16_be(0x0102)
		T.neq(w1:build(), w2:build())
	end)
	T.it("uint16_le byte order: LSB first", function()
		local w = M.writer()
		w:uint16_le(0x0102)
		local data = w:build()
		T.eq(string.byte(data, 1), 0x02)
		T.eq(string.byte(data, 2), 0x01)
	end)
	T.it("uint16_be byte order: MSB first", function()
		local w = M.writer()
		w:uint16_be(0x0102)
		local data = w:build()
		T.eq(string.byte(data, 1), 0x01)
		T.eq(string.byte(data, 2), 0x02)
	end)
end)

