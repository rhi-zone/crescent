-- ---------------------------------------------------------------------------
-- Framing
-- ---------------------------------------------------------------------------
T.describe("M.frame / M.unframe", function()
	local prefixes = { "u32_be", "u32_le", "u16_be", "u16_le", "varint" }
	for _, p in ipairs(prefixes) do
		T.it("round-trips with prefix=" .. p, function()
			local payload = "hello world"
			local framed = M.frame(payload, { prefix = p })
			T.ok(framed ~= nil)
			local out, rem = M.unframe(framed, { prefix = p })
			T.eq(out, payload)
			T.eq(rem, "")
		end)
	end
	T.it("unframe leaves trailing bytes in remaining", function()
		local payload = "ping"
		local framed = M.frame(payload, { prefix = "u32_be" })
		local combined = framed .. "extra"
		local out, rem = M.unframe(combined, { prefix = "u32_be" })
		T.eq(out, payload)
		T.eq(rem, "extra")
	end)
	T.it("default prefix is u32_be", function()
		local payload = "test"
		local framed = M.frame(payload)
		local out = M.unframe(framed)
		T.eq(out, payload)
	end)
	T.it("frame length prefix is correct byte count", function()
		local payload = "abc"
		local framed = M.frame(payload, { prefix = "u32_be" })
		-- first 4 bytes = big-endian length = 3
		T.eq(string.byte(framed, 1), 0)
		T.eq(string.byte(framed, 2), 0)
		T.eq(string.byte(framed, 3), 0)
		T.eq(string.byte(framed, 4), 3)
	end)
end)

-- ---------------------------------------------------------------------------
-- Streaming unframer
-- ---------------------------------------------------------------------------
T.describe("M.unframer streaming", function()
	T.it("returns nil when no data fed", function()
		local uf = M.unframer()
		T.eq(uf:next(), nil)
	end)
	T.it("returns nil with partial length prefix", function()
		local uf = M.unframer({ prefix = "u32_be" })
		uf:feed("\x00\x00")  -- only 2 of 4 bytes of length
		T.eq(uf:next(), nil)
	end)
	T.it("returns nil with complete prefix but partial payload", function()
		local uf = M.unframer({ prefix = "u32_be" })
		-- length = 10, but only 3 bytes of payload
		uf:feed("\x00\x00\x00\x0a" .. "abc")
		T.eq(uf:next(), nil)
	end)
	T.it("returns message after full frame received in one feed", function()
		local uf = M.unframer({ prefix = "u32_be" })
		local framed = M.frame("hello", { prefix = "u32_be" })
		uf:feed(framed)
		T.eq(uf:next(), "hello")
	end)
	T.it("returns nil after consuming the only message", function()
		local uf = M.unframer({ prefix = "u32_be" })
		uf:feed(M.frame("hello", { prefix = "u32_be" }))
		uf:next()
		T.eq(uf:next(), nil)
	end)
	T.it("returns message after two partial feeds", function()
		local uf = M.unframer({ prefix = "u32_be" })
		local framed = M.frame("world", { prefix = "u32_be" })
		-- split at byte 5 (after 4-byte header + 1 byte payload)
		uf:feed(framed:sub(1, 5))
		T.eq(uf:next(), nil)  -- not yet complete
		uf:feed(framed:sub(6))
		T.eq(uf:next(), "world")
	end)
	T.it("returns two messages fed together", function()
		local uf = M.unframer({ prefix = "u32_be" })
		uf:feed(M.frame("first",  { prefix = "u32_be" }))
		uf:feed(M.frame("second", { prefix = "u32_be" }))
		T.eq(uf:next(), "first")
		T.eq(uf:next(), "second")
		T.eq(uf:next(), nil)
	end)
	T.it("works with varint prefix", function()
		local uf = M.unframer({ prefix = "varint" })
		uf:feed(M.frame("varint-msg", { prefix = "varint" }))
		T.eq(uf:next(), "varint-msg")
	end)
	T.it("works with u16_be prefix", function()
		local uf = M.unframer({ prefix = "u16_be" })
		uf:feed(M.frame("short", { prefix = "u16_be" }))
		T.eq(uf:next(), "short")
	end)
end)

