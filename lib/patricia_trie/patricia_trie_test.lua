local T = require("lib.test.assert")
local PT = require("lib.patricia_trie")

T.describe("patricia_trie: basics", function()
  T.it("new trie is empty", function()
    local t = PT.new()
    T.ok(t:is_empty())
    T.eq(t:size(), 0)
  end)

  T.it("insert and get single key", function()
    local t = PT.new()
    t:insert("hello", 42)
    T.eq(t:get("hello"), 42)
    T.eq(t:size(), 1)
    T.ok(not t:is_empty())
  end)

  T.it("get returns nil for missing key", function()
    local t = PT.new()
    t:insert("hello", 1)
    T.eq(t:get("world"), nil)
    T.eq(t:get("hell"), nil)
    T.eq(t:get("helloo"), nil)
  end)

  T.it("default value is true", function()
    local t = PT.new()
    t:insert("x")
    T.eq(t:get("x"), true)
  end)

  T.it("update existing key", function()
    local t = PT.new()
    t:insert("foo", 1)
    t:insert("foo", 2)
    T.eq(t:get("foo"), 2)
    T.eq(t:size(), 1)
  end)

  T.it("contains: true for present, false for absent", function()
    local t = PT.new()
    t:insert("abc", 99)
    T.ok(t:contains("abc"))
    T.ok(not t:contains("ab"))
    T.ok(not t:contains("abcd"))
    T.ok(not t:contains("xyz"))
  end)
end)

T.describe("patricia_trie: remove", function()
  T.it("remove existing key returns true", function()
    local t = PT.new()
    t:insert("key", 7)
    T.ok(t:remove("key"))
    T.eq(t:size(), 0)
    T.eq(t:get("key"), nil)
    T.ok(t:is_empty())
  end)

  T.it("remove missing key returns false", function()
    local t = PT.new()
    t:insert("key", 7)
    T.ok(not t:remove("other"))
    T.eq(t:size(), 1)
  end)

  T.it("remove does not affect siblings", function()
    local t = PT.new()
    t:insert("foo", 1)
    t:insert("bar", 2)
    t:insert("baz", 3)
    t:remove("bar")
    T.eq(t:get("foo"), 1)
    T.eq(t:get("bar"), nil)
    T.eq(t:get("baz"), 3)
    T.eq(t:size(), 2)
  end)

  T.it("remove prefix key leaves longer keys intact", function()
    local t = PT.new()
    t:insert("test", 1)
    t:insert("testing", 2)
    t:remove("test")
    T.eq(t:get("test"), nil)
    T.eq(t:get("testing"), 2)
    T.eq(t:size(), 1)
  end)

  T.it("remove longer key leaves prefix key intact", function()
    local t = PT.new()
    t:insert("test", 1)
    t:insert("testing", 2)
    t:remove("testing")
    T.eq(t:get("test"), 1)
    T.eq(t:get("testing"), nil)
    T.eq(t:size(), 1)
  end)
end)

T.describe("patricia_trie: common prefix splitting", function()
  T.it("test / testing / tester / tested all findable", function()
    local t = PT.new()
    t:insert("test", 10)
    t:insert("testing", 20)
    t:insert("tester", 30)
    t:insert("tested", 40)
    T.eq(t:get("test"), 10)
    T.eq(t:get("testing"), 20)
    T.eq(t:get("tester"), 30)
    T.eq(t:get("tested"), 40)
    T.eq(t:size(), 4)
  end)

  T.it("overlapping prefixes: a, ab, abc, abcd", function()
    local t = PT.new()
    t:insert("a", 1)
    t:insert("ab", 2)
    t:insert("abc", 3)
    t:insert("abcd", 4)
    T.eq(t:get("a"), 1)
    T.eq(t:get("ab"), 2)
    T.eq(t:get("abc"), 3)
    T.eq(t:get("abcd"), 4)
    T.eq(t:get("abcde"), nil)
    T.eq(t:size(), 4)
  end)

  T.it("diverging keys at first character", function()
    local t = PT.new()
    t:insert("apple", 1)
    t:insert("banana", 2)
    t:insert("cherry", 3)
    T.eq(t:get("apple"), 1)
    T.eq(t:get("banana"), 2)
    T.eq(t:get("cherry"), 3)
  end)

  T.it("split in the middle of an edge label", function()
    local t = PT.new()
    t:insert("foobar", 1)
    t:insert("foobaz", 2)
    T.eq(t:get("foobar"), 1)
    T.eq(t:get("foobaz"), 2)
    T.eq(t:get("fooba"), nil)
    T.eq(t:size(), 2)
  end)
end)

T.describe("patricia_trie: prefix_search", function()
  T.it("returns all keys with given prefix", function()
    local t = PT.new()
    t:insert("test", 1)
    t:insert("testing", 2)
    t:insert("tester", 3)
    t:insert("toast", 4)
    t:insert("other", 5)
    local res = t:prefix_search("test")
    -- Should contain test, testing, tester but not toast or other.
    T.eq(#res, 3)
    local found = {}
    for i = 1, #res do found[res[i][1]] = res[i][2] end
    T.eq(found["test"], 1)
    T.eq(found["testing"], 2)
    T.eq(found["tester"], 3)
    T.eq(found["toast"], nil)
  end)

  T.it("prefix_search with empty prefix returns all", function()
    local t = PT.new()
    t:insert("a", 1)
    t:insert("b", 2)
    t:insert("c", 3)
    local res = t:prefix_search("")
    T.eq(#res, 3)
  end)

  T.it("prefix_search returns empty for no matches", function()
    local t = PT.new()
    t:insert("hello", 1)
    local res = t:prefix_search("world")
    T.eq(#res, 0)
  end)

  T.it("prefix_search results are sorted", function()
    local t = PT.new()
    t:insert("tester", 3)
    t:insert("test", 1)
    t:insert("testing", 2)
    local res = t:prefix_search("test")
    T.eq(res[1][1], "test")
    T.eq(res[2][1], "tester")
    T.eq(res[3][1], "testing")
  end)

  T.it("prefix_search on exact key returns just that key", function()
    local t = PT.new()
    t:insert("exact", 99)
    local res = t:prefix_search("exact")
    T.eq(#res, 1)
    T.eq(res[1][1], "exact")
    T.eq(res[1][2], 99)
  end)
end)

T.describe("patricia_trie: longest_prefix", function()
  T.it("returns longest stored prefix of query", function()
    local t = PT.new()
    t:insert("a", 1)
    t:insert("ab", 2)
    t:insert("abc", 3)
    local k, v = t:longest_prefix("abcdef")
    T.eq(k, "abc")
    T.eq(v, 3)
  end)

  T.it("returns nil when no prefix matches", function()
    local t = PT.new()
    t:insert("xyz", 1)
    local k = t:longest_prefix("abc")
    T.eq(k, nil)
  end)

  T.it("returns exact match when query == key", function()
    local t = PT.new()
    t:insert("hello", 42)
    local k, v = t:longest_prefix("hello")
    T.eq(k, "hello")
    T.eq(v, 42)
  end)

  T.it("prefers longer match over shorter", function()
    local t = PT.new()
    t:insert("foo", 1)
    t:insert("foobar", 2)
    local k, v = t:longest_prefix("foobarbaz")
    T.eq(k, "foobar")
    T.eq(v, 2)
  end)

  T.it("returns shortest match when only one fits", function()
    local t = PT.new()
    t:insert("foo", 1)
    t:insert("foobar", 2)
    local k, v = t:longest_prefix("foot")
    T.eq(k, "foo")
    T.eq(v, 1)
  end)

  T.it("empty-string key matches any query", function()
    local t = PT.new()
    t:insert("", 0)
    t:insert("ab", 2)
    local k, v = t:longest_prefix("abcdef")
    T.eq(k, "ab")
    T.eq(v, 2)
  end)
end)

