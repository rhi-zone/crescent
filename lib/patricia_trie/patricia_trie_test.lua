T.describe("patricia_trie: stress test", function()
  T.it("insert 100 keys, get all", function()
    local t = PT.new()
    for i = 1, 100 do
      t:insert("key" .. i, i)
    end
    T.eq(t:size(), 100)
    for i = 1, 100 do
      T.eq(t:get("key" .. i), i)
    end
  end)

  T.it("insert 100, remove 50, verify remainder", function()
    local t = PT.new()
    for i = 1, 100 do
      t:insert("item" .. i, i)
    end
    -- Remove even-numbered items.
    for i = 1, 100 do
      if i % 2 == 0 then
        T.ok(t:remove("item" .. i))
      end
    end
    T.eq(t:size(), 50)
    for i = 1, 100 do
      if i % 2 == 0 then
        T.eq(t:get("item" .. i), nil)
      else
        T.eq(t:get("item" .. i), i)
      end
    end
  end)

  T.it("to_array after stress returns sorted list", function()
    local t = PT.new()
    local expected = {}
    for i = 1, 20 do
      local k = string.format("key%03d", i)
      t:insert(k, i)
      expected[#expected + 1] = k
    end
    table.sort(expected)
    local arr = t:to_array()
    T.eq(#arr, 20)
    for i = 1, #arr do
      T.eq(arr[i][1], expected[i])
    end
  end)
end)

T.describe("patricia_trie: unicode / binary keys", function()
  T.it("multi-byte UTF-8 keys treated as byte strings", function()
    local t = PT.new()
    -- These are valid UTF-8 strings; patricia trie treats them as byte sequences.
    t:insert("héllo", 1)
    t:insert("héllo world", 2)
    t:insert("café", 3)
    T.eq(t:get("héllo"), 1)
    T.eq(t:get("héllo world"), 2)
    T.eq(t:get("café"), 3)
    T.eq(t:size(), 3)
  end)

  T.it("prefix_search works on UTF-8 prefix", function()
    local t = PT.new()
    t:insert("héllo", 1)
    t:insert("héllo world", 2)
    t:insert("café", 3)
    local res = t:prefix_search("héllo")
    T.eq(#res, 2)
  end)

  T.it("binary / arbitrary byte keys", function()
    local t = PT.new()
    t:insert("\x00\x01\x02", "bin1")
    t:insert("\x00\x01\x03", "bin2")
    t:insert("\xFF", "maxbyte")
    T.eq(t:get("\x00\x01\x02"), "bin1")
    T.eq(t:get("\x00\x01\x03"), "bin2")
    T.eq(t:get("\xFF"), "maxbyte")
    T.eq(t:size(), 3)
  end)
end)

T.describe("patricia_trie: edge cases", function()
  T.it("single character keys", function()
    local t = PT.new()
    for i = 97, 122 do  -- a-z
      t:insert(string.char(i), i)
    end
    T.eq(t:size(), 26)
    for i = 97, 122 do
      T.eq(t:get(string.char(i)), i)
    end
  end)

  T.it("very long key", function()
    local t = PT.new()
    local long = string.rep("a", 1000)
    t:insert(long, "long")
    T.eq(t:get(long), "long")
    T.eq(t:get(long:sub(1, 999)), nil)
  end)

  T.it("insert same key multiple times only counts once", function()
    local t = PT.new()
    t:insert("dup", 1)
    t:insert("dup", 2)
    t:insert("dup", 3)
    T.eq(t:size(), 1)
    T.eq(t:get("dup"), 3)
  end)

  T.it("removing non-existent key from empty trie", function()
    local t = PT.new()
    T.ok(not t:remove("nope"))
    T.eq(t:size(), 0)
  end)

  T.it("prefix_search where prefix is a full key in trie", function()
    local t = PT.new()
    t:insert("pre", 1)
    t:insert("prefix", 2)
    t:insert("preface", 3)
    local res = t:prefix_search("pre")
    T.eq(#res, 3)
    local found = {}
    for i = 1, #res do found[res[i][1]] = true end
    T.ok(found["pre"])
    T.ok(found["prefix"])
    T.ok(found["preface"])
  end)

  T.it("prefix_search on prefix longer than any key", function()
    local t = PT.new()
    t:insert("hi", 1)
    local res = t:prefix_search("highlight")
    T.eq(#res, 0)
  end)

  T.it("is_empty after insertions and full removal", function()
    local t = PT.new()
    t:insert("a", 1)
    t:insert("b", 2)
    t:remove("a")
    t:remove("b")
    T.ok(t:is_empty())
    T.eq(t:size(), 0)
  end)
end)
