T.describe("patricia_trie: each and to_array", function()
  T.it("each visits all keys in sorted order", function()
    local t = PT.new()
    t:insert("banana", 2)
    t:insert("apple", 1)
    t:insert("cherry", 3)
    local seen = {}
    t:each(function(k, v) seen[#seen + 1] = { k, v } end)
    T.eq(#seen, 3)
    T.eq(seen[1][1], "apple")
    T.eq(seen[2][1], "banana")
    T.eq(seen[3][1], "cherry")
    T.eq(seen[1][2], 1)
    T.eq(seen[2][2], 2)
    T.eq(seen[3][2], 3)
  end)

  T.it("to_array returns sorted pairs", function()
    local t = PT.new()
    t:insert("z", 26)
    t:insert("a", 1)
    t:insert("m", 13)
    local arr = t:to_array()
    T.eq(#arr, 3)
    T.eq(arr[1][1], "a")
    T.eq(arr[2][1], "m")
    T.eq(arr[3][1], "z")
  end)

  T.it("to_array on empty trie returns empty table", function()
    local t = PT.new()
    T.eq(#t:to_array(), 0)
  end)
end)

T.describe("patricia_trie: height", function()
  T.it("height of empty trie is 0", function()
    local t = PT.new()
    T.eq(t:height(), 0)
  end)

  T.it("height of single key is 1", function()
    local t = PT.new()
    t:insert("abc", 1)
    T.eq(t:height(), 1)
  end)

  T.it("height grows with nesting", function()
    local t = PT.new()
    t:insert("a", 1)
    t:insert("ab", 2)
    t:insert("abc", 3)
    -- Patricia trie compresses: a / b / c might be 3 edges deep or 1 depending on splits.
    -- At least 1, at most 3.
    local h = t:height()
    T.ok(h >= 1)
    T.ok(h <= 3)
  end)
end)

