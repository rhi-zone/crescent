if not package.path:find("./?/init.lua", 1, true) then
	package.path = "./?/init.lua;" .. package.path
end

local T = require("lib.test.assert")
local i18n = require("lib.i18n")

T.describe("i18n", function()

	T.describe("new", function()
		T.it("creates a new instance", function()
			local t = i18n.new()
			T.ok(t)
		end)

		T.it("starts with no locale", function()
			local t = i18n.new()
			T.eq(t:t("anything"), "anything")
		end)

		T.it("starts with no locales loaded", function()
			local t = i18n.new()
			local locs = t:locales()
			T.eq(#locs, 0)
		end)
	end)

	T.describe("load", function()
		T.it("loads translations for a locale", function()
			local t = i18n.new()
			t:load("en", { hello = "Hello" })
			t:set_locale("en")
			T.eq(t:t("hello"), "Hello")
		end)

		T.it("merges translations on multiple loads", function()
			local t = i18n.new()
			t:load("en", { a = "A" })
			t:load("en", { b = "B" })
			t:set_locale("en")
			T.eq(t:t("a"), "A")
			T.eq(t:t("b"), "B")
		end)

		T.it("overwrites keys on reload", function()
			local t = i18n.new()
			t:load("en", { a = "old" })
			t:load("en", { a = "new" })
			t:set_locale("en")
			T.eq(t:t("a"), "new")
		end)

		T.it("loads multiple locales independently", function()
			local t = i18n.new()
			t:load("en", { hello = "Hello" })
			t:load("es", { hello = "Hola" })
			t:set_locale("en")
			T.eq(t:t("hello"), "Hello")
			t:set_locale("es")
			T.eq(t:t("hello"), "Hola")
		end)
	end)

	T.describe("basic translation", function()
		T.it("returns simple string values", function()
			local t = i18n.new()
			t:load("en", { greeting = "Hello" })
			t:set_locale("en")
			T.eq(t:t("greeting"), "Hello")
		end)

		T.it("returns the key when not found", function()
			local t = i18n.new()
			t:load("en", {})
			t:set_locale("en")
			T.eq(t:t("missing_key"), "missing_key")
		end)

		T.it("returns key for missing locale", function()
			local t = i18n.new()
			t:set_locale("xx")
			T.eq(t:t("hello"), "hello")
		end)

		T.it("returns key when no locale is set", function()
			local t = i18n.new()
			t:load("en", { hello = "Hello" })
			T.eq(t:t("hello"), "hello")
		end)
	end)

	T.describe("interpolation", function()
		T.it("replaces a single variable", function()
			local t = i18n.new()
			t:load("en", { greeting = "Hello, {{name}}!" })
			t:set_locale("en")
			T.eq(t:t("greeting", { name = "World" }), "Hello, World!")
		end)

		T.it("replaces multiple variables", function()
			local t = i18n.new()
			t:load("en", { msg = "{{a}} and {{b}} and {{c}}" })
			t:set_locale("en")
			T.eq(t:t("msg", { a = "1", b = "2", c = "3" }), "1 and 2 and 3")
		end)

		T.it("leaves unknown variables as-is", function()
			local t = i18n.new()
			t:load("en", { msg = "Hi {{name}}, your id is {{id}}" })
			t:set_locale("en")
			T.eq(t:t("msg", { name = "Bob" }), "Hi Bob, your id is {{id}}")
		end)

		T.it("handles no data argument", function()
			local t = i18n.new()
			t:load("en", { msg = "Hello {{name}}" })
			t:set_locale("en")
			T.eq(t:t("msg"), "Hello {{name}}")
		end)

		T.it("converts numbers to strings", function()
			local t = i18n.new()
			t:load("en", { msg = "You have {{n}} items" })
			t:set_locale("en")
			T.eq(t:t("msg", { n = 42 }), "You have 42 items")
		end)

		T.it("converts booleans to strings", function()
			local t = i18n.new()
			t:load("en", { msg = "Active: {{v}}" })
			t:set_locale("en")
			T.eq(t:t("msg", { v = true }), "Active: true")
		end)

		T.it("handles empty string variable", function()
			local t = i18n.new()
			t:load("en", { msg = "Hello {{name}}!" })
			t:set_locale("en")
			T.eq(t:t("msg", { name = "" }), "Hello !")
		end)

		T.it("handles adjacent interpolations", function()
			local t = i18n.new()
			t:load("en", { msg = "{{a}}{{b}}" })
			t:set_locale("en")
			T.eq(t:t("msg", { a = "X", b = "Y" }), "XY")
		end)
	end)

	T.describe("nested keys", function()
		T.it("resolves dot-separated keys", function()
			local t = i18n.new()
			t:load("en", { nested = { deep = { key = "Found it" } } })
			t:set_locale("en")
			T.eq(t:t("nested.deep.key"), "Found it")
		end)

		T.it("returns key for partial path", function()
			local t = i18n.new()
			t:load("en", { a = { b = { c = "value" } } })
			t:set_locale("en")
			T.eq(t:t("a.b"), "a.b") -- table, not string
		end)

		T.it("returns key for missing nested segment", function()
			local t = i18n.new()
			t:load("en", { a = { b = "val" } })
			t:set_locale("en")
			T.eq(t:t("a.b.c"), "a.b.c")
		end)

		T.it("prefers direct key over dotted path", function()
			local t = i18n.new()
			t:load("en", { ["a.b"] = "direct", a = { b = "nested" } })
			t:set_locale("en")
			T.eq(t:t("a.b"), "direct")
		end)

		T.it("resolves nested keys with interpolation", function()
			local t = i18n.new()
			t:load("en", { ui = { welcome = "Welcome, {{user}}!" } })
			t:set_locale("en")
			T.eq(t:t("ui.welcome", { user = "Ada" }), "Welcome, Ada!")
		end)
	end)

	T.describe("pluralization", function()
		T.it("selects 'one' for count=1 in English", function()
			local t = i18n.new()
			t:load("en", { items = { one = "{{count}} item", other = "{{count}} items" } })
			t:set_locale("en")
			T.eq(t:t("items", { count = 1 }), "1 item")
		end)

		T.it("selects 'other' for count=0 in English", function()
			local t = i18n.new()
			t:load("en", { items = { one = "{{count}} item", other = "{{count}} items" } })
			t:set_locale("en")
			T.eq(t:t("items", { count = 0 }), "0 items")
		end)

		T.it("selects 'other' for count=5 in English", function()
			local t = i18n.new()
			t:load("en", { items = { one = "{{count}} item", other = "{{count}} items" } })
			t:set_locale("en")
			T.eq(t:t("items", { count = 5 }), "5 items")
		end)

		T.it("selects 'other' for count=100", function()
			local t = i18n.new()
			t:load("en", { items = { one = "{{count}} item", other = "{{count}} items" } })
			t:set_locale("en")
			T.eq(t:t("items", { count = 100 }), "100 items")
		end)

		T.it("uses French plural rule (0 is 'one')", function()
			local t = i18n.new()
			t:load("fr", { items = { one = "{{count}} article", other = "{{count}} articles" } })
			t:set_locale("fr")
			T.eq(t:t("items", { count = 0 }), "0 article")
			T.eq(t:t("items", { count = 1 }), "1 article")
			T.eq(t:t("items", { count = 2 }), "2 articles")
		end)

		T.it("uses Japanese plural rule (always 'other')", function()
			local t = i18n.new()
			t:load("ja", { items = { other = "{{count}}個" } })
			t:set_locale("ja")
			T.eq(t:t("items", { count = 1 }), "1個")
			T.eq(t:t("items", { count = 5 }), "5個")
		end)

		T.it("uses Arabic plural rule", function()
			local t = i18n.new()
			t:load("ar", {
				items = {
					zero = "لا عناصر",
					one = "عنصر واحد",
					two = "عنصران",
					few = "{{count}} عناصر",
					many = "{{count}} عنصرا",
					other = "{{count}} عنصر",
				},
			})
			t:set_locale("ar")
			T.eq(t:t("items", { count = 0 }), "لا عناصر")
			T.eq(t:t("items", { count = 1 }), "عنصر واحد")
			T.eq(t:t("items", { count = 2 }), "عنصران")
			T.eq(t:t("items", { count = 5 }), "5 عناصر")
			T.eq(t:t("items", { count = 50 }), "50 عنصرا")
			T.eq(t:t("items", { count = 200 }), "200 عنصر")
		end)

		T.it("falls back to 'other' when form is missing", function()
			local t = i18n.new()
			t:load("en", { items = { other = "{{count}} items" } })
			t:set_locale("en")
			T.eq(t:t("items", { count = 1 }), "1 items") -- no "one", falls back to "other"
		end)

		T.it("returns key when plural table has no matching form", function()
			local t = i18n.new()
			t:load("en", { items = { one = "one item" } })
			t:set_locale("en")
			T.eq(t:t("items", { count = 5 }), "items") -- no "other" form
		end)

		T.it("returns key for table without count in data", function()
			local t = i18n.new()
			t:load("en", { items = { one = "1 item", other = "many" } })
			t:set_locale("en")
			T.eq(t:t("items", { name = "test" }), "items")
		end)

		T.it("handles nested plural keys", function()
			local t = i18n.new()
			t:load("en", { shop = { items = { one = "{{count}} item", other = "{{count}} items" } } })
			t:set_locale("en")
			T.eq(t:t("shop.items", { count = 1 }), "1 item")
			T.eq(t:t("shop.items", { count = 3 }), "3 items")
		end)
	end)

	T.describe("custom plural rules", function()
		T.it("overrides the default rule for a locale", function()
			local t = i18n.new()
			t:load("en", { items = { one = "one", other = "other", zero = "none" } })
			t:set_locale("en")
			t:set_plural_rule("en", function(count)
				if count == 0 then return "zero" end
				return count == 1 and "one" or "other"
			end)
			T.eq(t:t("items", { count = 0 }), "none")
			T.eq(t:t("items", { count = 1 }), "one")
			T.eq(t:t("items", { count = 2 }), "other")
		end)

		T.it("adds a rule for an unknown locale", function()
			local t = i18n.new()
			t:load("xx", { items = { few = "few", other = "other" } })
			t:set_locale("xx")
			t:set_plural_rule("xx", function(count)
				return count < 5 and "few" or "other"
			end)
			T.eq(t:t("items", { count = 3 }), "few")
			T.eq(t:t("items", { count = 10 }), "other")
		end)
	end)

	T.describe("locale switching", function()
		T.it("switches between locales", function()
			local t = i18n.new()
			t:load("en", { hello = "Hello" })
			t:load("es", { hello = "Hola" })
			t:set_locale("en")
			T.eq(t:t("hello"), "Hello")
			t:set_locale("es")
			T.eq(t:t("hello"), "Hola")
		end)

		T.it("per-call locale override", function()
			local t = i18n.new()
			t:load("en", { hello = "Hello" })
			t:load("es", { hello = "Hola" })
			t:set_locale("en")
			T.eq(t:t("hello", nil, "es"), "Hola")
			-- Original locale unchanged
			T.eq(t:t("hello"), "Hello")
		end)

		T.it("per-call override with interpolation", function()
			local t = i18n.new()
			t:load("en", { greeting = "Hello, {{name}}!" })
			t:load("es", { greeting = "Hola, {{name}}!" })
			t:set_locale("en")
			T.eq(t:t("greeting", { name = "Mundo" }, "es"), "Hola, Mundo!")
		end)
	end)

	T.describe("fallback locale", function()
		T.it("falls back when key is missing in current locale", function()
			local t = i18n.new()
			t:load("en", { hello = "Hello", goodbye = "Goodbye" })
			t:load("es", { hello = "Hola" })
			t:set_locale("es")
			t:set_fallback("en")
			T.eq(t:t("hello"), "Hola")
			T.eq(t:t("goodbye"), "Goodbye") -- falls back to en
		end)

		T.it("returns key when missing from both locales", function()
			local t = i18n.new()
			t:load("en", { hello = "Hello" })
			t:load("es", { hello = "Hola" })
			t:set_locale("es")
			t:set_fallback("en")
			T.eq(t:t("nope"), "nope")
		end)

		T.it("does not fall back when key exists in current locale", function()
			local t = i18n.new()
			t:load("en", { hello = "Hello" })
			t:load("es", { hello = "Hola" })
			t:set_locale("es")
			t:set_fallback("en")
			T.eq(t:t("hello"), "Hola")
		end)

		T.it("fallback works with nested keys", function()
			local t = i18n.new()
			t:load("en", { ui = { save = "Save" } })
			t:load("es", {})
			t:set_locale("es")
			t:set_fallback("en")
			T.eq(t:t("ui.save"), "Save")
		end)

		T.it("fallback works with pluralization", function()
			local t = i18n.new()
			t:load("en", { items = { one = "{{count}} item", other = "{{count}} items" } })
			t:load("es", {})
			t:set_locale("es")
			t:set_fallback("en")
			T.eq(t:t("items", { count = 1 }), "1 item")
			T.eq(t:t("items", { count = 5 }), "5 items")
		end)

		T.it("fallback does not apply when per-call locale is set", function()
			local t = i18n.new()
			t:load("en", { hello = "Hello" })
			t:load("es", {})
			t:load("fr", { hello = "Bonjour" })
			t:set_locale("es")
			t:set_fallback("en")
			-- Per-call locale "fr" has the key, should not touch fallback
			T.eq(t:t("hello", nil, "fr"), "Bonjour")
		end)

		T.it("fallback applies when per-call locale misses the key", function()
			local t = i18n.new()
			t:load("en", { hello = "Hello" })
			t:load("fr", {})
			t:set_locale("en")
			t:set_fallback("en")
			T.eq(t:t("hello", nil, "fr"), "Hello")
		end)
	end)

	T.describe("has", function()
		T.it("returns true for existing key", function()
			local t = i18n.new()
			t:load("en", { hello = "Hello" })
			t:set_locale("en")
			T.ok(t:has("hello"))
		end)

		T.it("returns false for missing key", function()
			local t = i18n.new()
			t:load("en", {})
			t:set_locale("en")
			T.eq(t:has("nope"), false)
		end)

		T.it("returns true for nested key", function()
			local t = i18n.new()
			t:load("en", { a = { b = "val" } })
			t:set_locale("en")
			T.ok(t:has("a.b"))
		end)

		T.it("returns true for key in fallback", function()
			local t = i18n.new()
			t:load("en", { hello = "Hello" })
			t:load("es", {})
			t:set_locale("es")
			t:set_fallback("en")
			T.ok(t:has("hello"))
		end)

		T.it("returns false when no locale set", function()
			local t = i18n.new()
			t:load("en", { hello = "Hello" })
			T.eq(t:has("hello"), false)
		end)
	end)

	T.describe("locales", function()
		T.it("returns empty table when none loaded", function()
			local t = i18n.new()
			T.eq(#t:locales(), 0)
		end)

		T.it("returns loaded locale names sorted", function()
			local t = i18n.new()
			t:load("es", {})
			t:load("en", {})
			t:load("fr", {})
			local locs = t:locales()
			T.eq(#locs, 3)
			T.eq(locs[1], "en")
			T.eq(locs[2], "es")
			T.eq(locs[3], "fr")
		end)

		T.it("does not duplicate locales on reload", function()
			local t = i18n.new()
			t:load("en", { a = "1" })
			t:load("en", { b = "2" })
			T.eq(#t:locales(), 1)
		end)
	end)

	T.describe("edge cases", function()
		T.it("handles empty string translation", function()
			local t = i18n.new()
			t:load("en", { empty = "" })
			t:set_locale("en")
			T.eq(t:t("empty"), "")
		end)

		T.it("handles translation with only interpolation", function()
			local t = i18n.new()
			t:load("en", { v = "{{val}}" })
			t:set_locale("en")
			T.eq(t:t("v", { val = "hello" }), "hello")
		end)

		T.it("handles empty key", function()
			local t = i18n.new()
			t:load("en", { [""] = "empty key" })
			t:set_locale("en")
			T.eq(t:t(""), "empty key")
		end)

		T.it("handles numeric count of 0", function()
			local t = i18n.new()
			t:load("en", { n = { one = "one", other = "{{count}}" } })
			t:set_locale("en")
			T.eq(t:t("n", { count = 0 }), "0")
		end)

		T.it("handles negative count", function()
			local t = i18n.new()
			t:load("en", { n = { one = "one", other = "{{count}}" } })
			t:set_locale("en")
			T.eq(t:t("n", { count = -3 }), "-3")
		end)

		T.it("handles same locale and fallback", function()
			local t = i18n.new()
			t:load("en", { hello = "Hello" })
			t:set_locale("en")
			t:set_fallback("en")
			T.eq(t:t("hello"), "Hello")
			T.eq(t:t("nope"), "nope")
		end)

		T.it("interpolation with special pattern characters", function()
			local t = i18n.new()
			t:load("en", { msg = "Price: {{price}}" })
			t:set_locale("en")
			T.eq(t:t("msg", { price = "$100.00" }), "Price: $100.00")
		end)

		T.it("key with dots but no nesting", function()
			local t = i18n.new()
			t:load("en", { ["x.y.z"] = "flat" })
			t:set_locale("en")
			T.eq(t:t("x.y.z"), "flat")
		end)
	end)
end)
