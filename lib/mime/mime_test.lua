T.describe("mime.content_type", function()
	T.it("html with charset", function()
		T.eq(mime.content_type("file.html"), "text/html; charset=utf-8")
	end)
	T.it("css with charset", function()
		T.eq(mime.content_type("style.css"), "text/css; charset=utf-8")
	end)
	T.it("json with charset", function()
		T.eq(mime.content_type(".json"), "application/json; charset=utf-8")
	end)
	T.it("js with charset", function()
		T.eq(mime.content_type("app.js"), "text/javascript; charset=utf-8")
	end)
	T.it("svg with charset", function()
		T.eq(mime.content_type("logo.svg"), "image/svg+xml; charset=utf-8")
	end)
	T.it("jpg without charset", function()
		T.eq(mime.content_type("photo.jpg"), "image/jpeg")
	end)
	T.it("png without charset", function()
		T.eq(mime.content_type("icon.png"), "image/png")
	end)
	T.it("pdf without charset", function()
		T.eq(mime.content_type("doc.pdf"), "application/pdf")
	end)
	T.it("wasm without charset", function()
		T.eq(mime.content_type("mod.wasm"), "application/wasm")
	end)
	T.it("unknown returns nil", function()
		T.eq(mime.content_type("file.xyz"), nil)
	end)
end)

T.describe("mime.types and mime.extensions tables", function()
	T.it("types table has entries", function()
		T.ok(mime.types.html ~= nil)
		T.eq(mime.types.html, "text/html")
	end)
	T.it("extensions table has entries", function()
		T.ok(mime.extensions["text/html"] ~= nil)
		T.eq(mime.extensions["text/html"], "html")
	end)
	T.it("types count >= 100", function()
		local count = 0
		for _ in pairs(mime.types) do count = count + 1 end
		T.ok(count >= 100, "expected >= 100 mime types, got " .. count)
	end)
end)
