T.describe("mime.is_text", function()
	T.it("text/html is text", function()
		T.ok(mime.is_text("text/html"))
	end)
	T.it("text/plain is text", function()
		T.ok(mime.is_text("text/plain"))
	end)
	T.it("text/css is text", function()
		T.ok(mime.is_text("text/css"))
	end)
	T.it("application/json is text", function()
		T.ok(mime.is_text("application/json"))
	end)
	T.it("image/svg+xml is text", function()
		T.ok(mime.is_text("image/svg+xml"))
	end)
	T.it("image/png is not text", function()
		T.ok(not mime.is_text("image/png"))
	end)
	T.it("application/pdf is not text", function()
		T.ok(not mime.is_text("application/pdf"))
	end)
	T.it("application/wasm is not text", function()
		T.ok(not mime.is_text("application/wasm"))
	end)
end)

