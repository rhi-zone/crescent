T.describe("mime.extension", function()
	T.it("text/html -> html", function()
		T.eq(mime.extension("text/html"), "html")
	end)
	T.it("image/jpeg -> jpg", function()
		T.eq(mime.extension("image/jpeg"), "jpg")
	end)
	T.it("application/json -> json", function()
		T.eq(mime.extension("application/json"), "json")
	end)
	T.it("image/png -> png", function()
		T.eq(mime.extension("image/png"), "png")
	end)
	T.it("text/css -> css", function()
		T.eq(mime.extension("text/css"), "css")
	end)
	T.it("text/javascript -> js", function()
		T.eq(mime.extension("text/javascript"), "js")
	end)
	T.it("application/pdf -> pdf", function()
		T.eq(mime.extension("application/pdf"), "pdf")
	end)
	T.it("font/woff2 -> woff2", function()
		T.eq(mime.extension("font/woff2"), "woff2")
	end)
	T.it("unknown type returns nil", function()
		T.eq(mime.extension("application/x-unknown-thing"), nil)
	end)
	T.it("case insensitive", function()
		T.eq(mime.extension("TEXT/HTML"), "html")
		T.eq(mime.extension("Image/PNG"), "png")
	end)
end)

