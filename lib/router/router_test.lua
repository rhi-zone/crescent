		r:add("GET", "/users/:id", h2)
		local m1 = r:find("GET", "/users/new")
		local m2 = r:find("GET", "/users/42")
		T.eq(m1.handler, h1)
		T.eq(m2.handler, h2)
	end)

	T.it("param at end of path", function()
