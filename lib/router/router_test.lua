-- ── new ──────────────────────────────────────────────────────────────────────

T.describe("router.new", function()
	T.it("creates a router", function()
		local r = router.new()
		T.ok(r, "router should not be nil")
	end)
end)

-- ── add ──────────────────────────────────────────────────────────────────────

T.describe("add", function()
	T.it("adds a static route", function()
		local r = router.new()
		local ok, err = r:add("GET", "/users", h1)
		T.eq(ok, true)
		T.eq(err, nil)
	end)

	T.it("returns error for empty method", function()
		local r = router.new()
		local ok, err = r:add("", "/users", h1)
		T.eq(ok, nil)
		T.ok(err, "should return error message")
	end)

	T.it("returns error for empty path", function()
		local r = router.new()
		local ok, err = r:add("GET", "", h1)
		T.eq(ok, nil)
		T.ok(err, "should return error message")
	end)

	T.it("returns error for nil handler", function()
		local r = router.new()
		local ok, err = r:add("GET", "/test", nil)
		T.eq(ok, nil)
		T.ok(err, "should return error message")
	end)

	T.it("returns error for duplicate route", function()
		local r = router.new()
		r:add("GET", "/users", h1)
		local ok, err = r:add("GET", "/users", h2)
		T.eq(ok, nil)
		T.ok(err:find("already exists"), "should mention already exists")
	end)

	T.it("allows same path with different methods", function()
		local r = router.new()
		local ok1 = r:add("GET", "/users", h1)
		local ok2 = r:add("POST", "/users", h2)
		T.eq(ok1, true)
		T.eq(ok2, true)
	end)

	T.it("uppercases method", function()
		local r = router.new()
		r:add("get", "/test", h1)
		local m = r:find("GET", "/test")
		T.ok(m, "should find route added with lowercase method")
		T.eq(m.handler, h1)
	end)
end)

