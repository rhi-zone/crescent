local T = require("lib.test.assert")
local router = require("lib.router")

-- Sentinel handlers for identity comparison
local h1 = function() return "h1" end
local h2 = function() return "h2" end
local h3 = function() return "h3" end
local h4 = function() return "h4" end
local h5 = function() return "h5" end
local h6 = function() return "h6" end
