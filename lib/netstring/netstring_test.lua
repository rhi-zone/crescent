-- ========================
-- EDGE CASES AND ROUND-TRIPS
-- ========================

T.describe("edge cases", function()
  T.it("netstring round-trip for various lengths", function()
    for _, s in ipairs({"", "a", "hello world", string.rep("x", 100)}) do
      local encoded = N.encode(s)
      local decoded, _ = N.decode(encoded)
      T.eq(decoded, s)
    end
  end)
  T.it("unpack_u16 at offset", function()
    local buf = "\x00\x00\x01\x02"
    local v, pos = N.unpack_u16(buf, 3)
    T.eq(v, 0x0102)
    T.eq(pos, 5)
  end)
  T.it("unpack_u32 at offset", function()
    local buf = "\x00\x00\x00\x00\x01\x02\x03\x04"
    local v, pos = N.unpack_u32(buf, 5)
    T.eq(v, 0x01020304)
    T.eq(pos, 9)
  end)
  T.it("TLV 2-byte type + 4-byte length round-trip", function()
    local opts = {type_bytes=2, length_bytes=4}
    local s = "complex data"
    local encoded, _ = N.tlv_encode(0x1234, s, opts)
    local t, v, _, err = N.tlv_decode(encoded, 1, opts)
    T.eq(err, nil)
    T.eq(t, 0x1234)
    T.eq(v, s)
  end)
  T.it("varint round-trips large value", function()
    local n = 2097151  -- 3-byte varint max (21 bits)
    local enc = N.encode_varint(n)
    local dec, _ = N.decode_varint(enc, 1)
    T.eq(dec, n)
  end)
end)
