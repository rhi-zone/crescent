T.describe("varint decode", function()
  T.it("decodes 0", function()
    local v, pos = N.decode_varint("\x00", 1)
    T.eq(v, 0)
    T.eq(pos, 2)
  end)
  T.it("decodes 1", function()
    local v, _ = N.decode_varint("\x01", 1)
    T.eq(v, 1)
  end)
  T.it("decodes 127", function()
    local v, _ = N.decode_varint("\x7f", 1)
    T.eq(v, 127)
  end)
  T.it("decodes 128", function()
    local v, pos = N.decode_varint("\x80\x01", 1)
    T.eq(v, 128)
    T.eq(pos, 3)
  end)
  T.it("decodes 255", function()
    local v, _ = N.decode_varint("\xff\x01", 1)
    T.eq(v, 255)
  end)
  T.it("decodes 300", function()
    local v, _ = N.decode_varint("\xac\x02", 1)
    T.eq(v, 300)
  end)
  T.it("decodes 16383", function()
    local v, _ = N.decode_varint("\xff\x7f", 1)
    T.eq(v, 16383)
  end)
  T.it("decodes 16384", function()
    local v, pos = N.decode_varint("\x80\x80\x01", 1)
    T.eq(v, 16384)
    T.eq(pos, 4)
  end)
  T.it("error: buffer ends mid-varint", function()
    local v, err = N.decode_varint("\x80", 1)
    T.eq(v, nil)
    T.ok(err ~= nil)
  end)
  T.it("round-trips encode/decode for various values", function()
    for _, n in ipairs({0, 1, 63, 64, 127, 128, 255, 300, 1000, 16383, 16384}) do
      local encoded = N.encode_varint(n)
      local decoded, _ = N.decode_varint(encoded, 1)
      T.eq(decoded, n)
    end
  end)
end)

-- ========================
-- LENGTH-DELIMITED
-- ========================

T.describe("length-delimited framing", function()
  T.it("encodes and decodes round-trip", function()
    local encoded = N.ld_encode("hello")
    local data, pos = N.ld_decode(encoded, 1)
    T.eq(data, "hello")
    T.eq(pos, #encoded + 1)
  end)
  T.it("handles empty string", function()
    local encoded = N.ld_encode("")
    local data, pos = N.ld_decode(encoded, 1)
    T.eq(data, "")
    T.eq(pos, 2)
  end)
  T.it("handles binary data", function()
    local s = "\x00\x01\x02\xff"
    local encoded = N.ld_encode(s)
    local data, _ = N.ld_decode(encoded, 1)
    T.eq(data, s)
  end)
  T.it("decodes at offset within larger buffer", function()
    local buf = N.ld_encode("first") .. N.ld_encode("second")
    local d1, pos1 = N.ld_decode(buf, 1)
    T.eq(d1, "first")
    local d2, _ = N.ld_decode(buf, pos1)
    T.eq(d2, "second")
  end)
  T.it("error: buffer too short", function()
    local data, err = N.ld_decode("\x05hel", 1)
    T.eq(data, nil)
    T.ok(err ~= nil)
  end)
  T.it("round-trips large data (128+ bytes)", function()
    local s = string.rep("x", 200)
    local encoded = N.ld_encode(s)
    local data, _ = N.ld_decode(encoded, 1)
    T.eq(data, s)
    T.eq(#encoded, 2 + 200)  -- varint(200) = 2 bytes: \xc8\x01
  end)
end)

