T.describe("TLV encode/decode 1-byte type, 1-byte length", function()
  T.it("encodes type=1, value=hello", function()
    local bytes, err = N.tlv_encode(1, "hello")
    T.eq(err, nil)
    T.eq(bytes, "\x01\x05hello")
  end)
  T.it("decodes type=1, value=hello", function()
    local t, v, pos, err = N.tlv_decode("\x01\x05hello", 1)
    T.eq(err, nil)
    T.eq(t, 1)
    T.eq(v, "hello")
    T.eq(pos, 8)
  end)
  T.it("round-trips type=255, value=data", function()
    local encoded, _ = N.tlv_encode(255, "data")
    local t, v, _, err = N.tlv_decode(encoded, 1)
    T.eq(err, nil)
    T.eq(t, 255)
    T.eq(v, "data")
  end)
  T.it("encodes/decodes empty value", function()
    local encoded, _ = N.tlv_encode(5, "")
    local t, v, pos, err = N.tlv_decode(encoded, 1)
    T.eq(err, nil)
    T.eq(t, 5)
    T.eq(v, "")
    T.eq(pos, 3)
  end)
end)

T.describe("TLV encode/decode 2-byte type", function()
  T.it("encodes and decodes 2-byte type tag", function()
    local encoded, err = N.tlv_encode(1000, "hello", {type_bytes=2})
    T.eq(err, nil)
    local t, v, _, derr = N.tlv_decode(encoded, 1, {type_bytes=2})
    T.eq(derr, nil)
    T.eq(t, 1000)
    T.eq(v, "hello")
  end)
  T.it("encodes 2-byte type=0x0102", function()
    local encoded, _ = N.tlv_encode(0x0102, "ab", {type_bytes=2})
    T.eq(string.byte(encoded, 1), 0x01)
    T.eq(string.byte(encoded, 2), 0x02)
  end)
end)

T.describe("TLV encode/decode 2-byte length", function()
  T.it("round-trips with 2-byte length field", function()
