local T = require("lib.test.assert")
local N = require("lib.netstring")

-- ========================
-- NETSTRING encode
-- ========================

T.describe("netstring encode", function()
  T.it("encodes simple string", function()
    T.eq(N.encode("hello"), "5:hello,")
  end)
  T.it("encodes empty string", function()
    T.eq(N.encode(""), "0:,")
  end)
  T.it("encodes string with special chars", function()
    T.eq(N.encode("a:b,c"), "5:a:b,c,")
  end)
  T.it("encodes binary data", function()
    T.eq(N.encode("\0\1\2"), "3:\0\1\2,")
  end)
end)

-- ========================
-- NETSTRING decode
-- ========================

T.describe("netstring decode", function()
  T.it("decodes simple netstring", function()
    local data, rest = N.decode("5:hello,")
    T.eq(data, "hello")
    T.eq(rest, "")
  end)
  T.it("decodes empty netstring", function()
    local data, rest = N.decode("0:,")
    T.eq(data, "")
    T.eq(rest, "")
  end)
  T.it("returns rest of buffer", function()
    local data, rest = N.decode("5:hello,world")
    T.eq(data, "hello")
    T.eq(rest, "world")
  end)
  T.it("error: no colon", function()
    local data, err = N.decode("hello")
    T.eq(data, nil)
    T.ok(err ~= nil)
  end)
  T.it("error: invalid length (non-numeric)", function()
    local data, err = N.decode("abc:hello,")
    T.eq(data, nil)
    T.ok(err ~= nil)
  end)
  T.it("error: wrong length (buffer too short)", function()
    local data, err = N.decode("10:hi,")
    T.eq(data, nil)
    T.ok(err ~= nil)
  end)
  T.it("error: missing trailing comma", function()
    local data, err = N.decode("5:hello!")
    T.eq(data, nil)
    T.ok(err ~= nil)
  end)
  T.it("decodes netstring with colon in data", function()
    local data, rest = N.decode("5:a:b,c,")
    T.eq(data, "a:b,c")
    T.eq(rest, "")
  end)
end)

-- ========================
-- NETSTRING decode_all
-- ========================

T.describe("netstring decode_all", function()
  T.it("decodes multiple netstrings", function()
    local strings, rest = N.decode_all("5:hello,5:world,")
    T.eq(#strings, 2)
    T.eq(strings[1], "hello")
    T.eq(strings[2], "world")
    T.eq(rest, "")
  end)
  T.it("stops at incomplete netstring", function()
    local strings, rest = N.decode_all("5:hello,5:wor")
    T.eq(#strings, 1)
    T.eq(strings[1], "hello")
    T.eq(rest, "5:wor")
  end)
  T.it("handles empty buffer", function()
    local strings, rest = N.decode_all("")
    T.eq(#strings, 0)
    T.eq(rest, "")
  end)
  T.it("decodes single empty netstring", function()
    local strings, rest = N.decode_all("0:,")
    T.eq(#strings, 1)
    T.eq(strings[1], "")
    T.eq(rest, "")
  end)
end)

-- ========================
-- NETSTRING encode_all
-- ========================

T.describe("netstring encode_all", function()
  T.it("encodes multiple strings", function()
    local buf = N.encode_all({"hello", "world"})
    T.eq(buf, "5:hello,5:world,")
  end)
  T.it("encodes empty list", function()
    T.eq(N.encode_all({}), "")
  end)
  T.it("round-trips through decode_all", function()
    local strs = {"foo", "bar", "", "baz"}
    local buf = N.encode_all(strs)
    local decoded, rest = N.decode_all(buf)
    T.eq(#decoded, 4)
    T.eq(decoded[1], "foo")
    T.eq(decoded[2], "bar")
    T.eq(decoded[3], "")
    T.eq(decoded[4], "baz")
    T.eq(rest, "")
  end)
end)

-- ========================
-- STREAMING DECODER
-- ========================

T.describe("streaming decoder", function()
  T.it("decodes complete message in one feed", function()
    local d = N.decoder()
    local results, err = d:feed("5:hello,")
    T.eq(err, nil)
    T.eq(#results, 1)
    T.eq(results[1], "hello")
  end)
  T.it("decodes fragmented input across feeds", function()
    local d = N.decoder()
    local r1, _ = d:feed("5:he")
    T.eq(#r1, 0)
    local r2, _ = d:feed("llo,")
    T.eq(#r2, 1)
    T.eq(r2[1], "hello")
  end)
  T.it("returns multiple messages from one feed", function()
    local d = N.decoder()
    local results, err = d:feed("3:foo,3:bar,")
    T.eq(err, nil)
    T.eq(#results, 2)
    T.eq(results[1], "foo")
    T.eq(results[2], "bar")
  end)
  T.it("accumulates partial data across feeds", function()
    local d = N.decoder()
    d:feed("5:")
    d:feed("hel")
    local results, _ = d:feed("lo,3:end,")
    T.eq(#results, 2)
    T.eq(results[1], "hello")
    T.eq(results[2], "end")
  end)
  T.it("handles empty string netstring via streaming", function()
    local d = N.decoder()
    local results, err = d:feed("0:,")
    T.eq(err, nil)
    T.eq(#results, 1)
    T.eq(results[1], "")
  end)
end)

