T.describe("TLV decode_all", function()
  T.it("decodes multiple TLV records", function()
    local buf = N.tlv_encode(1, "foo") .. N.tlv_encode(2, "bar") .. N.tlv_encode(3, "baz")
    local records, err = N.tlv_decode_all(buf)
    T.eq(err, nil)
    T.eq(#records, 3)
    T.eq(records[1][1], 1)
    T.eq(records[1][2], "foo")
    T.eq(records[2][1], 2)
    T.eq(records[2][2], "bar")
    T.eq(records[3][1], 3)
    T.eq(records[3][2], "baz")
  end)
  T.it("handles empty buffer", function()
    local records, err = N.tlv_decode_all("")
    T.eq(err, nil)
    T.eq(#records, 0)
  end)
  T.it("error on truncated buffer", function()
    local records, err = N.tlv_decode_all("\x01\x05hel")
    T.ok(err ~= nil)
  end)
end)

