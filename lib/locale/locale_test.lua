T.describe("locale: format_currency", function()
  T.it("USD $ prefix in en-US", function()
    local s = L.format_currency(1234.56, "USD", "en-US")
    T.ok(s:sub(1, 1) == "$", "expected $ prefix, got: "..s)
    T.ok(s:find("1,234") ~= nil, "expected thousands sep, got: "..s)
  end)
  T.it("EUR € suffix in de-DE", function()
    local s = L.format_currency(1234.56, "EUR", "de-DE")
    -- should end with € symbol (UTF-8: e2 82 ac)
    T.ok(s:find("\xe2\x82\xac") ~= nil, "expected € in result, got: "..s)
    -- € should not be prefix for de-DE
    T.ok(s:sub(1, 3) ~= "\xe2\x82\xac", "EUR should be suffix for de-DE, got: "..s)
  end)
  T.it("EUR € suffix in fr-FR", function()
    local s = L.format_currency(100, "EUR", "fr-FR")
    T.ok(s:find("\xe2\x82\xac") ~= nil, "expected € in result, got: "..s)
    T.ok(s:sub(1, 3) ~= "\xe2\x82\xac", "EUR should be suffix for fr-FR, got: "..s)
  end)
  T.it("GBP £ prefix", function()
    local s = L.format_currency(50, "GBP", "en-GB")
    T.ok(s:sub(1, 2) == "\xc2\xa3", "expected £ prefix, got: "..s)
  end)
  T.it("unknown currency returns nil + errmsg", function()
    local v, err = L.format_currency(10, "XYZ", "en-US")
    T.eq(v, nil)
    T.ok(type(err) == "string")
  end)
end)

