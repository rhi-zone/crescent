local T = require("lib.test.assert")
local L = require("lib.locale")

T.describe("locale: locale()", function()
  T.it("parses language-region", function()
    local loc = L.locale("en-US")
    T.eq(loc.language, "en")
    T.eq(loc.region, "US")
    T.eq(loc.script, nil)
  end)
  T.it("parses language only", function()
    local loc = L.locale("de")
    T.eq(loc.language, "de")
    T.eq(loc.region, nil)
  end)
  T.it("returns nil on bad input", function()
    local v, err = L.locale("")
    T.eq(v, nil)
    T.ok(type(err) == "string")
  end)
end)

T.describe("locale: catalog add/t interpolation", function()
  local cat = L.catalog("en")
  cat:add("greeting", "Hello, {name}!")
  cat:add("farewell", "Goodbye!")
  cat:add_all({ notice = "Notice: {msg}", plain = "No placeholders" })

  T.it("translates with interpolation", function()
    T.eq(cat:t("greeting", { name = "World" }), "Hello, World!")
  end)
  T.it("translates without params", function()
    T.eq(cat:t("farewell"), "Goodbye!")
  end)
  T.it("add_all works", function()
    T.eq(cat:t("plain"), "No placeholders")
    T.eq(cat:t("notice", { msg = "test" }), "Notice: test")
  end)
  T.it("unknown key returns key", function()
    T.eq(cat:t("missing.key"), "missing.key")
  end)
  T.it("missing param left as placeholder", function()
    T.eq(cat:t("greeting"), "Hello, {name}!")
  end)
end)

