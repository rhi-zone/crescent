T.describe("locale: truncate", function()
  T.it("short string unchanged", function()
    T.eq(L.truncate("hello", 10), "hello")
  end)
  T.it("exact length unchanged", function()
    T.eq(L.truncate("hello", 5), "hello")
  end)
  T.it("truncates ASCII with ellipsis", function()
    local result = L.truncate("hello world", 8)
    -- "hello wo" + "…" but keep = 8-1 = 7 chars → "hello w…"
    T.eq(result, "hello w\xe2\x80\xa6")
  end)
  T.it("custom ellipsis", function()
    local result = L.truncate("hello world", 8, "...")
    -- keep = 8-3 = 5 chars → "hello..."
    T.eq(result, "hello...")
  end)
  T.it("respects multi-byte UTF-8 codepoints", function()
    -- "héllo" is 5 codepoints (h é l l o), 6 bytes
    local s = "h\xc3\xa9llo world"
    local result = L.truncate(s, 6)
    -- 6 codepoints total to keep: keep=5 + ellipsis(1)
    -- first 5 codepoints: h é l l o → "héllo"
    T.eq(result, "h\xc3\xa9llo\xe2\x80\xa6")
  end)
  T.it("very small max_chars uses plain truncation", function()
    local result = L.truncate("hello", 1, "...")
    -- keep = 1-3 = -2 → fallback to first 1 codepoint
    T.eq(result, "h")
  end)
end)

T.describe("locale: format_date", function()
  -- Use a fixed timestamp: 2024-03-15 14:30:00 UTC
  -- We use os.time which is local time — test with current time to at least
  -- exercise the code path without being timezone-sensitive.
  T.it("returns a non-empty string for medium style", function()
    local s = L.format_date(os.time(), "en", { style = "medium" })
    T.ok(type(s) == "string" and #s > 0)
  end)
  T.it("date+time includes colon for time", function()
    local s = L.format_date(os.time(), "en", { style = "short", time = true })
    T.ok(s:find(":") ~= nil, "time part should contain colon, got: "..s)
  end)
  T.it("de style short has dots", function()
    local s = L.format_date(os.time(), "de", { style = "short" })
    T.ok(s:find("%.") ~= nil, "de short date should have dots, got: "..s)
  end)
end)

