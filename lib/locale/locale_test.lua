T.describe("locale: collate", function()
  T.it("en: basic alphabetical sort", function()
    local sorted = L.collate({"banana", "apple", "cherry"}, "en")
    T.eq(sorted[1], "apple")
    T.eq(sorted[2], "banana")
    T.eq(sorted[3], "cherry")
  end)
  T.it("de: umlauts sorted as base+e", function()
    -- ä sorts after 'a' but as 'ae', so after 'a' and 'ac' etc.
    local sorted = L.collate({"Öl", "Oel", "Oil"}, "de")
    -- "Oel" and "Öl" should both sort as "oel"; "Oil" as "oil"
    -- either Oel or Öl first, then Oil
    T.ok(sorted[3] == "Oil", "Oil should sort last, got: "..sorted[3])
  end)
  T.it("returns a new table (does not mutate input)", function()
    local input = {"b", "a"}
    local sorted = L.collate(input, "en")
    T.eq(input[1], "b") -- unchanged
    T.eq(sorted[1], "a")
  end)
  T.it("empty list", function()
    local sorted = L.collate({}, "en")
    T.eq(#sorted, 0)
  end)
end)

