  end)
  T.it("unknown locale: 2 → other (en fallback)", function()
    T.eq(xx(2), "other")
  end)
end)

T.describe("locale: format_number", function()
  T.it("en-US: 1234.56 → 1,234.56", function()
    T.eq(L.format_number(1234.56, "en-US", { decimals = 2 }), "1,234.56")
  end)
  T.it("en-US: 1000000 → 1,000,000", function()
    T.eq(L.format_number(1000000, "en-US", { decimals = 0 }), "1,000,000")
  end)
  T.it("de-DE: 1234.56 → 1.234,56", function()
    T.eq(L.format_number(1234.56, "de-DE", { decimals = 2 }), "1.234,56")
  end)
  T.it("de-DE: no group separator when group_sep=false", function()
    T.eq(L.format_number(1234.56, "de-DE", { decimals = 2, group_sep = false }), "1234,56")
  end)
  T.it("en-US: negative number", function()
    T.eq(L.format_number(-42.5, "en-US", { decimals = 1 }), "-42.5")
  end)
  T.it("en-US: zero decimals", function()
    T.eq(L.format_number(42, "en-US", { decimals = 0 }), "42")
  end)
  T.it("en-US: min_decimals pads", function()
    T.eq(L.format_number(3.1, "en-US", { min_decimals = 2, max_decimals = 2 }), "3.10")
  end)
  T.it("invalid input returns nil + errmsg", function()
    local v, err = L.format_number("not a number", "en-US")
    T.eq(v, nil)
    T.ok(type(err) == "string")
  end)
  T.it("unknown locale falls back gracefully", function()
    local result = L.format_number(1234.5, "xx-ZZ", { decimals = 1 })
    T.ok(type(result) == "string")
    T.ok(result:find("1234") ~= nil or result:find("1,234") ~= nil)
  end)
end)

