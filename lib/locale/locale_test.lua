  T.it("ru: 21 → one", function()
    T.eq(ru(21), "one")
  end)
  T.it("ru: 22 → few", function()
    T.eq(ru(22), "few")
  end)

  local ar = L.plural_rule("ar")
  T.it("ar: 0 → zero", function()
    T.eq(ar(0), "zero")
  end)
  T.it("ar: 1 → one", function()
    T.eq(ar(1), "one")
  end)
  T.it("ar: 2 → two", function()
    T.eq(ar(2), "two")
  end)
  T.it("ar: 5 → few", function()
    T.eq(ar(5), "few")
  end)
  T.it("ar: 15 → many", function()
    T.eq(ar(15), "many")
