-- ── Parent / child spans ──────────────────────────────────────────────────────

T.describe("parent/child spans", function()
  T.it("child has parent_span_id equal to parent span_id", function()
    local prov, exp = make_provider()
    local tr = prov:tracer("svc")
    local parent = tr:start_span("parent")
    local child  = tr:start_span("child", { parent = parent })
    child:finish()
    parent:finish()
    local spans = exp:spans()
    -- child finishes first
    T.eq(spans[1].parent_span_id, parent.span_id)
  end)

  T.it("child shares trace_id with parent", function()
    local prov, exp = make_provider()
    local tr = prov:tracer("svc")
    local parent = tr:start_span("parent")
    local child  = tr:start_span("child", { parent = parent })
    child:finish()
    parent:finish()
    local spans = exp:spans()
    T.eq(spans[1].trace_id, spans[2].trace_id)
  end)

  T.it("child via context() carries same trace_id", function()
    local prov, exp = make_provider()
    local tr = prov:tracer("svc")
    local root = tr:start_span("root")
    local ctx  = root:context()
    local child = tr:start_span("child", { context = ctx })
    child:finish()
    root:finish()
    local spans = exp:spans()
    T.eq(spans[1].trace_id, root.trace_id)
    T.eq(spans[1].parent_span_id, root.span_id)
  end)

  T.it("multiple spans in same trace share trace_id", function()
    local prov, exp = make_provider()
    local tr = prov:tracer("svc")
    local root = tr:start_span("root")
    local s1 = tr:start_span("s1", { parent = root })
    local s2 = tr:start_span("s2", { parent = root })
    s1:finish()
    s2:finish()
    root:finish()
    local spans = exp:spans()
    T.eq(#spans, 3)
    T.eq(spans[1].trace_id, spans[2].trace_id)
    T.eq(spans[2].trace_id, spans[3].trace_id)
  end)
end)

