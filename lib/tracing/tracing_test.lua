-- ── W3C TraceContext ──────────────────────────────────────────────────────────

T.describe("W3C TraceContext", function()
  T.it("inject produces correctly formatted header", function()
    local prov, exp = make_provider(42)
    local tr = prov:tracer("svc")
    local sp = tr:start_span("op")
    sp:finish()
    local s = exp:spans()[1]
    local header = Tr.inject(s)
    T.eq(type(header), "string")
    -- format: 00-{32hex}-{16hex}-01
    T.ok(header:match("^00%-%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%-%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%-01$"),
      "header matches W3C pattern")
  end)

  T.it("extract parses a valid header", function()
    local header = "00-4bf92f3577b34da6a3ce929d0e0e4736-00f067aa0ba902b7-01"
    local ctx, err = Tr.extract(header)
    T.ok(err == nil, "no error")
    T.eq(ctx.trace_id, "4bf92f3577b34da6a3ce929d0e0e4736")
    T.eq(ctx.span_id,  "00f067aa0ba902b7")
    T.eq(ctx.flags,    "01")
  end)

  T.it("inject/extract round-trip", function()
    local prov, exp = make_provider(55)
    local tr = prov:tracer("svc")
    local sp = tr:start_span("op")
    sp:finish()
    local s = exp:spans()[1]
    local header = Tr.inject(s)
    local ctx, err = Tr.extract(header)
    T.ok(err == nil, "no extract error")
    T.eq(ctx.trace_id, s.trace_id)
    T.eq(ctx.span_id,  s.span_id)
    T.eq(ctx.flags,    "01")
  end)

  T.it("extract returns nil,errmsg for invalid header", function()
    local ctx, err = Tr.extract("not-a-header")
    T.eq(ctx, nil)
    T.ok(type(err) == "string", "error message returned")
  end)

  T.it("extract returns nil,errmsg for non-string", function()
    local ctx, err = Tr.extract(42)
    T.eq(ctx, nil)
    T.ok(type(err) == "string")
  end)

  T.it("child span from extracted context shares trace_id", function()
    local prov, exp = make_provider(77)
    local tr = prov:tracer("svc")
    local sp = tr:start_span("root")
    local header = Tr.inject(sp)
    local ctx = Tr.extract(header)
    local child = tr:start_span("child", { context = ctx })
    child:finish()
    sp:finish()
    local spans = exp:spans()
    T.eq(spans[1].trace_id, spans[2].trace_id)
    T.eq(spans[1].parent_span_id, sp.span_id)
  end)
end)

