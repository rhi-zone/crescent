-- ── with_span ─────────────────────────────────────────────────────────────────

T.describe("with_span", function()
  T.it("span is auto-finished", function()
    local prov, exp = make_provider()
    local tr = prov:tracer("svc")
    tr:with_span("op", function(sp)
      sp:set_attribute("x", 1)
    end)
    local spans = exp:spans()
    T.eq(#spans, 1)
    T.ok(spans[1].end_time ~= nil, "end_time set")
  end)

  T.it("span name is set correctly", function()
    local prov, exp = make_provider()
    local tr = prov:tracer("svc")
    tr:with_span("my-op", function(_sp) end)
    T.eq(exp:spans()[1].name, "my-op")
  end)

  T.it("attributes set inside fn are preserved", function()
    local prov, exp = make_provider()
    local tr = prov:tracer("svc")
    tr:with_span("op", function(sp)
      sp:set_attribute("key", "value")
    end)
    T.eq(exp:spans()[1].attributes["key"], "value")
  end)

  T.it("error in fn sets status to error", function()
    local prov, exp = make_provider()
    local tr = prov:tracer("svc")
    local ok = pcall(function()
      tr:with_span("failing", function(_sp)
        error("boom")
      end)
    end)
    T.ok(not ok, "error propagated")
    local s = exp:spans()[1]
    T.eq(s.status, "error")
    T.ok(s.status_message ~= nil, "status_message set on error")
  end)

  T.it("error in fn still finishes span", function()
    local prov, exp = make_provider()
    local tr = prov:tracer("svc")
    pcall(function()
      tr:with_span("failing", function(_sp)
        error("boom")
      end)
    end)
    T.eq(#exp:spans(), 1)
    T.ok(exp:spans()[1].end_time ~= nil)
  end)

  T.it("accepts opts table before fn", function()
    local prov, exp = make_provider()
    local tr = prov:tracer("svc")
    local parent = tr:start_span("root")
    tr:with_span("child", { parent = parent }, function(sp)
      T.eq(sp.parent_span_id, parent.span_id)
    end)
    parent:finish()
    T.eq(#exp:spans(), 2)
  end)
end)

