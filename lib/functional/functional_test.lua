-- helper: deep equal for arrays
local function arr_eq(a, b)
  if #a ~= #b then return false end
  for i = 1, #a do
    if a[i] ~= b[i] then return false end
  end
  return true
end

local function arr2_eq(a, b)
  if #a ~= #b then return false end
  for i = 1, #a do
    if not arr_eq(a[i], b[i]) then return false end
  end
  return true
end

