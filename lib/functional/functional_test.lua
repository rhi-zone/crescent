T.describe("transducers", function()
  local append = function(acc, v) acc[#acc+1] = v; return acc end

  T.it("map_xf transforms values", function()
    local r = F.transduce(F.map_xf(function(x) return x * 2 end), append, {}, {1,2,3})
    T.ok(arr_eq(r, {2,4,6}))
  end)

  T.it("filter_xf keeps matching values", function()
    local r = F.transduce(F.filter_xf(function(x) return x % 2 == 0 end), append, {}, {1,2,3,4,5})
    T.ok(arr_eq(r, {2,4}))
  end)

  T.it("take_xf takes first n", function()
    local r = F.transduce(F.take_xf(3), append, {}, {10,20,30,40,50})
    T.ok(arr_eq(r, {10,20,30}))
  end)

  T.it("comp_xf composes map then filter", function()
    local xf = F.comp_xf(
      F.map_xf(function(x) return x * 3 end),
      F.filter_xf(function(x) return x > 6 end)
    )
    local r = F.transduce(xf, append, {}, {1,2,3,4,5})
    T.ok(arr_eq(r, {9,12,15}))
  end)

  T.it("comp_xf with take", function()
    local xf = F.comp_xf(
      F.filter_xf(function(x) return x % 2 == 0 end),
      F.take_xf(2)
    )
    local r = F.transduce(xf, append, {}, {1,2,3,4,5,6,7,8})
    T.ok(arr_eq(r, {2,4}))
  end)
end)

