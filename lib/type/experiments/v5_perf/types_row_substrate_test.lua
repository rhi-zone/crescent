-- lib/type/experiments/v5_perf/types_row_substrate_test.lua
-- Tests for Phase 1 substrate: TRowVar, open TRecord, TIntersection.
-- Covers constructors, structural equality, and substitution walk.

if not package.path:find("./?/init.lua", 1, true) then
	package.path = "./?/init.lua;" .. package.path
end

local T      = require("lib.test.assert")
local types  = require("lib.type.experiments.v5_perf.types")
local subst  = require("lib.type.experiments.v5_perf.subst")

T.describe("TRowVar constructor", function()
	T.it("produces a value with tag rowvar", function()
		local rv = types.rowvar(7)
		T.eq(rv.tag, "rowvar")
		T.eq(rv.id, 7)
	end)
	T.it("two rowvars with the same id are equal", function()
		T.ok(types.equal(types.rowvar(3), types.rowvar(3)))
	end)
	T.it("two rowvars with different ids are not equal", function()
		T.ok(not types.equal(types.rowvar(1), types.rowvar(2)))
	end)
end)

T.describe("TRecord closed (no row)", function()
	T.it("record() produces a closed record (row is nil)", function()
		local r = types.record({ x = types.field(types.const("number"), false, false) })
		T.eq(r.tag, "record")
		T.ok(r.row == nil)
	end)
	T.it("two closed records with same fields are equal", function()
		local a = types.record({ x = types.field(types.const("number"), false, false) })
		local b = types.record({ x = types.field(types.const("number"), false, false) })
		T.ok(types.equal(a, b))
	end)
	T.it("closed record is not equal to open record with same fields", function()
		local rv = types.rowvar(1)
		local a = types.record({ x = types.field(types.const("number"), false, false) })
		local b = types.record_open({ x = types.field(types.const("number"), false, false) }, rv)
		T.ok(not types.equal(a, b))
	end)
end)

T.describe("TRecord open (with row)", function()
	T.it("record_open() produces an open record with the given rowvar", function()
		local rv = types.rowvar(42)
		local r = types.record_open({ y = types.field(types.const("string"), false, false) }, rv)
		T.eq(r.tag, "record")
		T.ok(r.row ~= nil)
		T.eq(r.row.id, 42)
	end)
	T.it("two open records with same fields and same rowvar are equal", function()
		local rv = types.rowvar(5)
		local a = types.record_open({ y = types.field(types.const("string"), false, false) }, rv)
		local b = types.record_open({ y = types.field(types.const("string"), false, false) }, rv)
		T.ok(types.equal(a, b))
	end)
	T.it("two open records with same fields but different rowvars are not equal", function()
		local a = types.record_open({ y = types.field(types.const("string"), false, false) }, types.rowvar(1))
		local b = types.record_open({ y = types.field(types.const("string"), false, false) }, types.rowvar(2))
		T.ok(not types.equal(a, b))
	end)
end)

T.describe("TIntersection constructor", function()
	T.it("intersection produces a value with tag intersection", function()
		local t = types.intersection({ types.const("number"), types.const("string") })
		T.eq(t.tag, "intersection")
		T.eq(#t.parts, 2)
	end)
	T.it("two intersections with equal parts are equal", function()
		local a = types.intersection({ types.const("number"), types.const("string") })
		local b = types.intersection({ types.const("number"), types.const("string") })
		T.ok(types.equal(a, b))
	end)
	T.it("intersection with 1 part", function()
		local t = types.intersection({ types.const("boolean") })
		T.eq(#t.parts, 1)
		T.ok(types.equal(t.parts[1], types.const("boolean")))
	end)
	T.it("intersection with 3 parts", function()
		local t = types.intersection({ types.const("number"), types.const("string"), types.const("boolean") })
		T.eq(#t.parts, 3)
	end)
	T.it("intersections with different parts are not equal", function()
		local a = types.intersection({ types.const("number") })
		local b = types.intersection({ types.const("string") })
		T.ok(not types.equal(a, b))
	end)
end)

T.describe("substitution walk: TRowVar", function()
	T.it("walk returns rowvar unchanged (row vars are not in uvar subst)", function()
		local s = subst.new()
		local rv = types.rowvar(9)
		local result = subst.walk(s, rv)
		T.eq(result.tag, "rowvar")
		T.eq(result.id, 9)
	end)
end)

T.describe("substitution walk: recurses into TRecord.row", function()
	T.it("walk preserves closed record row=nil", function()
		local s = subst.new()
		local r = types.record({ x = types.field(types.const("number"), false, false) })
		local result = subst.walk(s, r)
		T.eq(result.tag, "record")
		T.ok(result.row == nil)
	end)
	T.it("walk preserves open record row field", function()
		local s = subst.new()
		local rv = types.rowvar(3)
		local r = types.record_open({ x = types.field(types.const("number"), false, false) }, rv)
		local result = subst.walk(s, r)
		T.eq(result.tag, "record")
		T.ok(result.row ~= nil)
		T.eq(result.row.id, 3)
	end)
	T.it("walk substitutes uvar inside open record fields, preserves row", function()
		local s = subst.new()
		local alpha = subst.fresh(s, "open")
		subst.bind(s, alpha, types.const("boolean"))
		local rv = types.rowvar(1)
		local r = types.record_open({ flag = types.field(types.uvar(alpha), false, false) }, rv)
		local result = subst.walk(s, r)
		T.eq(result.tag, "record")
		-- Three-region: result.fields.flag is a TField; its `.type` is walked.
		T.ok(types.equal(result.fields.flag.type, types.const("boolean")))
		T.ok(result.row ~= nil)
		T.eq(result.row.id, 1)
	end)
end)

T.describe("substitution walk: recurses into TIntersection.parts", function()
	T.it("walk substitutes uvar inside intersection part", function()
		local s = subst.new()
		local alpha = subst.fresh(s, "open")
		subst.bind(s, alpha, types.const("number"))
		local t = types.intersection({ types.uvar(alpha), types.const("string") })
		local result = subst.walk(s, t)
		T.eq(result.tag, "intersection")
		T.eq(#result.parts, 2)
		T.ok(types.equal(result.parts[1], types.const("number")))
		T.ok(types.equal(result.parts[2], types.const("string")))
	end)
	T.it("walk recurses into nested intersection parts", function()
		local s = subst.new()
		local alpha = subst.fresh(s, "open")
		subst.bind(s, alpha, types.const("boolean"))
		local inner = types.intersection({ types.uvar(alpha) })
		local outer = types.intersection({ inner, types.const("number") })
		local result = subst.walk(s, outer)
		T.eq(result.tag, "intersection")
		local inner_result = result.parts[1]
		T.eq(inner_result.tag, "intersection")
		T.ok(types.equal(inner_result.parts[1], types.const("boolean")))
	end)
end)

-- ── TParam leaf + subst_params / has_param (Phase 2.4.5) ─────────────────────

T.describe("TParam constructor", function()
	T.it("param() produces a value with tag param", function()
		local p = types.param(1)
		T.eq(p.tag, "param")
		T.eq(p.idx, 1)
	end)
	T.it("two params with the same idx are equal", function()
		T.ok(types.equal(types.param(2), types.param(2)))
	end)
	T.it("two params with different idx are not equal", function()
		T.ok(not types.equal(types.param(1), types.param(2)))
	end)
	T.it("shift leaves a param unchanged (not De Bruijn relocated)", function()
		local p = types.param(3)
		T.ok(types.equal(types.shift(p, 5, 0), p))
	end)
	T.it("instantiate leaves a param unchanged", function()
		local p = types.param(3)
		T.ok(types.equal(types.instantiate(p, types.const("number"), 0), p))
	end)
end)

T.describe("has_param", function()
	T.it("true for a bare param leaf", function()
		T.ok(types.has_param(types.param(1)))
	end)
	T.it("false for a param-free type", function()
		T.ok(not types.has_param(types.const("number")))
		T.ok(not types.has_param(types.arrow({ types.const("number") }, { types.const("string") })))
	end)
	T.it("true when a param hides inside an arrow return match", function()
		local arms = {} --[[: TMatchArm[] ]]
		arms[1] = { pattern = types.literal("boolean", true), result = types.const("string") }
		local m = types.match(types.param(1), arms)
		local ar = types.arrow({ types.const("boolean") }, { m })
		T.ok(types.has_param(ar.ret))
		T.ok(types.has_param(ar))
	end)
	T.it("true when a param hides inside a union / intersection / record / app", function()
		T.ok(types.has_param(types.union({ types.const("number"), types.param(1) })))
		T.ok(types.has_param(types.intersection({ types.param(2), types.const("nil") })))
		T.ok(types.has_param(types.app(types.const("F"), types.param(1))))
		local rec = types.record({ x = types.field(types.param(1), false, false) })
		T.ok(types.has_param(rec))
	end)
end)

T.describe("subst_params", function()
	T.it("replaces param(i) with args[i]", function()
		local out = types.subst_params(types.param(1), { types.const("number") })
		T.ok(types.equal(out, types.const("number")))
	end)
	T.it("replaces an out-of-range param with nil const (missing arg)", function()
		local out = types.subst_params(types.param(3), { types.const("number") })
		T.ok(types.equal(out, types.const("nil")))
	end)
	T.it("simultaneous substitution: distinct params get distinct args", function()
		local u = types.union({ types.param(1), types.param(2) })
		local out = types.subst_params(u, { types.const("string"), types.const("integer") })
		T.eq(out.tag, "union")
		T.ok(types.equal(out.xs[1], types.const("string")))
		T.ok(types.equal(out.xs[2], types.const("integer")))
	end)
	T.it("result is param-free (has_param false after subst)", function()
		local arms = {} --[[: TMatchArm[] ]]
		arms[1] = { pattern = types.literal("boolean", true), result = types.const("string") }
		arms[2] = { pattern = types.literal("boolean", false), result = types.const("integer") }
		local m = types.match(types.param(1), arms)
		local out = types.subst_params(m, { types.literal("boolean", true) })
		T.ok(not types.has_param(out))
		T.eq(out.tag, "match")
		T.ok(types.equal(out.param, types.literal("boolean", true)))
	end)
	T.it("substitutes through an arrow's args and ret packs", function()
		local ar = types.arrow({ types.param(1) }, { types.param(1) })
		local out = types.subst_params(ar, { types.const("number") })
		T.eq(out.tag, "arrow")
		T.ok(types.equal(out.args.items[1], types.const("number")))
		T.ok(types.equal(out.ret.items[1], types.const("number")))
	end)
	T.it("leaves non-param leaves untouched", function()
		local out = types.subst_params(types.const("string"), { types.const("number") })
		T.ok(types.equal(out, types.const("string")))
	end)
end)
