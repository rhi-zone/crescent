-- lib/type/experiments/v5_perf/types_row_substrate_test.lua
-- Tests for Phase 1 substrate: TRowVar, open TRecord, TIntersection.
-- Covers constructors, structural equality, and substitution walk.

if not package.path:find("./?/init.lua", 1, true) then
	package.path = "./?/init.lua;" .. package.path
end

local T      = require("lib.test.assert")
local types  = require("lib.type.experiments.v5_perf.types")
local subst  = require("lib.type.experiments.v5_perf.subst")

T.describe("TRowVar constructor", function()
	T.it("produces a value with tag rowvar", function()
		local rv = types.rowvar(7)
		T.eq(rv.tag, "rowvar")
		T.eq(rv.id, 7)
	end)
	T.it("two rowvars with the same id are equal", function()
		T.ok(types.equal(types.rowvar(3), types.rowvar(3)))
	end)
	T.it("two rowvars with different ids are not equal", function()
		T.ok(not types.equal(types.rowvar(1), types.rowvar(2)))
	end)
end)

T.describe("TRecord closed (no row)", function()
	T.it("record() produces a closed record (row is nil)", function()
		local r = types.record({ x = types.const("number") })
		T.eq(r.tag, "record")
		T.ok(r.row == nil)
	end)
	T.it("two closed records with same fields are equal", function()
		local a = types.record({ x = types.const("number") })
		local b = types.record({ x = types.const("number") })
		T.ok(types.equal(a, b))
	end)
	T.it("closed record is not equal to open record with same fields", function()
		local rv = types.rowvar(1)
		local a = types.record({ x = types.const("number") })
		local b = types.record_open({ x = types.const("number") }, rv)
		T.ok(not types.equal(a, b))
	end)
end)

T.describe("TRecord open (with row)", function()
	T.it("record_open() produces an open record with the given rowvar", function()
		local rv = types.rowvar(42)
		local r = types.record_open({ y = types.const("string") }, rv)
		T.eq(r.tag, "record")
		T.ok(r.row ~= nil)
		T.eq(r.row.id, 42)
	end)
	T.it("two open records with same fields and same rowvar are equal", function()
		local rv = types.rowvar(5)
		local a = types.record_open({ y = types.const("string") }, rv)
		local b = types.record_open({ y = types.const("string") }, rv)
		T.ok(types.equal(a, b))
	end)
	T.it("two open records with same fields but different rowvars are not equal", function()
		local a = types.record_open({ y = types.const("string") }, types.rowvar(1))
		local b = types.record_open({ y = types.const("string") }, types.rowvar(2))
		T.ok(not types.equal(a, b))
	end)
end)

T.describe("TIntersection constructor", function()
	T.it("intersection produces a value with tag intersection", function()
		local t = types.intersection({ types.const("number"), types.const("string") })
		T.eq(t.tag, "intersection")
		T.eq(#t.parts, 2)
	end)
	T.it("two intersections with equal parts are equal", function()
		local a = types.intersection({ types.const("number"), types.const("string") })
		local b = types.intersection({ types.const("number"), types.const("string") })
		T.ok(types.equal(a, b))
	end)
	T.it("intersection with 1 part", function()
		local t = types.intersection({ types.const("boolean") })
		T.eq(#t.parts, 1)
		T.ok(types.equal(t.parts[1], types.const("boolean")))
	end)
	T.it("intersection with 3 parts", function()
		local t = types.intersection({ types.const("number"), types.const("string"), types.const("boolean") })
		T.eq(#t.parts, 3)
	end)
	T.it("intersections with different parts are not equal", function()
		local a = types.intersection({ types.const("number") })
		local b = types.intersection({ types.const("string") })
		T.ok(not types.equal(a, b))
	end)
end)

T.describe("substitution walk: TRowVar", function()
	T.it("walk returns rowvar unchanged (row vars are not in uvar subst)", function()
		local s = subst.new()
		local rv = types.rowvar(9)
		local result = subst.walk(s, rv)
		T.eq(result.tag, "rowvar")
		T.eq(result.id, 9)
	end)
end)

T.describe("substitution walk: recurses into TRecord.row", function()
	T.it("walk preserves closed record row=nil", function()
		local s = subst.new()
		local r = types.record({ x = types.const("number") })
		local result = subst.walk(s, r)
		T.eq(result.tag, "record")
		T.ok(result.row == nil)
	end)
	T.it("walk preserves open record row field", function()
		local s = subst.new()
		local rv = types.rowvar(3)
		local r = types.record_open({ x = types.const("number") }, rv)
		local result = subst.walk(s, r)
		T.eq(result.tag, "record")
		T.ok(result.row ~= nil)
		T.eq(result.row.id, 3)
	end)
	T.it("walk substitutes uvar inside open record fields, preserves row", function()
		local s = subst.new()
		local alpha = subst.fresh(s, "open")
		subst.bind(s, alpha, types.const("boolean"))
		local rv = types.rowvar(1)
		local r = types.record_open({ flag = types.uvar(alpha) }, rv)
		local result = subst.walk(s, r)
		T.eq(result.tag, "record")
		T.ok(types.equal(result.fields.flag, types.const("boolean")))
		T.ok(result.row ~= nil)
		T.eq(result.row.id, 1)
	end)
end)

T.describe("substitution walk: recurses into TIntersection.parts", function()
	T.it("walk substitutes uvar inside intersection part", function()
		local s = subst.new()
		local alpha = subst.fresh(s, "open")
		subst.bind(s, alpha, types.const("number"))
		local t = types.intersection({ types.uvar(alpha), types.const("string") })
		local result = subst.walk(s, t)
		T.eq(result.tag, "intersection")
		T.eq(#result.parts, 2)
		T.ok(types.equal(result.parts[1], types.const("number")))
		T.ok(types.equal(result.parts[2], types.const("string")))
	end)
	T.it("walk recurses into nested intersection parts", function()
		local s = subst.new()
		local alpha = subst.fresh(s, "open")
		subst.bind(s, alpha, types.const("boolean"))
		local inner = types.intersection({ types.uvar(alpha) })
		local outer = types.intersection({ inner, types.const("number") })
		local result = subst.walk(s, outer)
		T.eq(result.tag, "intersection")
		local inner_result = result.parts[1]
		T.eq(inner_result.tag, "intersection")
		T.ok(types.equal(inner_result.parts[1], types.const("boolean")))
	end)
end)
