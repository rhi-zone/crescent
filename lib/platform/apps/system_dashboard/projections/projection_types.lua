--::   alt?:          string,
--::   width?:        number | string,
--::   height?:       number | string,
--::   type?:         string,
--::   name?:         string,
--::   placeholder?:  string,
--::   value?:        string | number | boolean,
--::   checked?:      boolean,
--::   selected?:     boolean,
--::   disabled?:     boolean,
--::   readonly?:     boolean,
--::   required?:     boolean,
--::   multiple?:     boolean,
--::   open?:         boolean,
--::   autocomplete?: string,
--::   pattern?:      string,
--::   min?:          number | string,
--::   max?:          number | string,
--::   step?:         number | string,
--::   datetime?:     string,
--::   viewBox?:      string,
--::   xmlns?:        string,
--::   d?:            string,
--::   fill?:         string,
--::   stroke?:       string,
--::   transform?:    string,
--::   x?:            number | string,
--::   y?:            number | string,
--::   x1?:           number | string,
--::   y1?:           number | string,
--::   x2?:           number | string,
--::   y2?:           number | string,
--::   cx?:           number | string,
--::   cy?:           number | string,
--::   r?:            number | string,
--::   rx?:           number | string,
--::   ry?:           number | string,
--::   dx?:           number | string,
--::   dy?:           number | string,
--::   points?:       string,
--::   opacity?:      number | string,
--::   [string]:      string | number | boolean | nil,
--::   ...
--:: }

