-- lib/base32/base32_test.lua
-- Tests for lib/base32 — RFC 4648 standard, hex, and Crockford variants.

if not package.path:find("./?/init.lua", 1, true) then
    package.path = "./?/init.lua;" .. package.path
end

local T = require("lib.test.assert")
local b32 = require("lib.base32")

-- ── Standard Base32 (RFC 4648 §6) ─────────────────────────────────────────────

T.describe("base32 standard encode", function()
    -- RFC 4648 §10 test vectors
    T.it("encodes empty string", function()
        T.eq(b32.encode(""), "")
    end)
    T.it("encodes 'f'", function()
        T.eq(b32.encode("f"), "MY======")
    end)
    T.it("encodes 'fo'", function()
        T.eq(b32.encode("fo"), "MZXQ====")
    end)
    T.it("encodes 'foo'", function()
        T.eq(b32.encode("foo"), "MZXW6===")
    end)
    T.it("encodes 'foob'", function()
        T.eq(b32.encode("foob"), "MZXW6YQ=")
    end)
    T.it("encodes 'fooba'", function()
        T.eq(b32.encode("fooba"), "MZXW6YTB")
    end)
    T.it("encodes 'foobar'", function()
        T.eq(b32.encode("foobar"), "MZXW6YTBOI======")
    end)
end)

T.describe("base32 standard decode", function()
    T.it("decodes empty string", function()
        T.eq(b32.decode(""), "")
    end)
    T.it("decodes MY======", function()
        T.eq(b32.decode("MY======"), "f")
    end)
    T.it("decodes MZXQ====", function()
        T.eq(b32.decode("MZXQ===="), "fo")
    end)
    T.it("decodes MZXW6===", function()
        T.eq(b32.decode("MZXW6==="), "foo")
    end)
    T.it("decodes MZXW6YQ=", function()
        T.eq(b32.decode("MZXW6YQ="), "foob")
    end)
    T.it("decodes MZXW6YTB", function()
        T.eq(b32.decode("MZXW6YTB"), "fooba")
    end)
    T.it("decodes MZXW6YTBOI======", function()
        T.eq(b32.decode("MZXW6YTBOI======"), "foobar")
    end)
    T.it("decodes lowercase my======", function()
        T.eq(b32.decode("my======"), "f")
    end)
    T.it("decodes mixed case", function()
        T.eq(b32.decode("mZxW6YtB"), "fooba")
    end)
end)

T.describe("base32 standard round-trips", function()
    T.it("round-trips single byte 0x00", function()
        local s = "\000"
        T.eq(b32.decode(b32.encode(s)), s)
    end)
    T.it("round-trips single byte 0xff", function()
        local s = "\255"
        T.eq(b32.decode(b32.encode(s)), s)
    end)
    T.it("round-trips binary with null bytes", function()
        local s = "\000\001\002\003\004\255\254\253"
        T.eq(b32.decode(b32.encode(s)), s)
    end)
    T.it("round-trips all printable ASCII", function()
        local chars = {}
        for i = 32, 126 do chars[#chars + 1] = string.char(i) end
        local s = table.concat(chars)
        T.eq(b32.decode(b32.encode(s)), s)
    end)
    T.it("round-trips 1-byte boundary", function()
        T.eq(b32.decode(b32.encode("A")), "A")
    end)
    T.it("round-trips 2-byte boundary", function()
        T.eq(b32.decode(b32.encode("AB")), "AB")
    end)
    T.it("round-trips 3-byte boundary", function()
        T.eq(b32.decode(b32.encode("ABC")), "ABC")
    end)
    T.it("round-trips 4-byte boundary", function()
        T.eq(b32.decode(b32.encode("ABCD")), "ABCD")
    end)
    T.it("round-trips 5-byte boundary", function()
        T.eq(b32.decode(b32.encode("ABCDE")), "ABCDE")
    end)
    T.it("round-trips 10-byte boundary", function()
        T.eq(b32.decode(b32.encode("ABCDEFGHIJ")), "ABCDEFGHIJ")
    end)
end)

T.describe("base32 decode errors", function()
    T.it("errors on invalid character", function()
        local result, err = b32.decode("M1======")
        T.eq(result, nil)
        T.ok(err ~= nil, "expected error message")
    end)
    T.it("errors on invalid character 0x80", function()
        local result, err = b32.decode("M\128=====")
        T.eq(result, nil)
        T.ok(err ~= nil, "expected error message")
    end)
end)

