    T.it("string_to_base32 == encode", function()
        T.eq(b32.string_to_base32("foo"), b32.encode("foo"))
    end)
    T.it("base32_to_string == decode", function()
        T.eq(b32.base32_to_string("MZXW6==="), b32.decode("MZXW6==="))
