-- ── Crockford Base32 ──────────────────────────────────────────────────────────

T.describe("crockford encode", function()
    T.it("encodes empty string", function()
        T.eq(b32.encode_crockford(""), "")
    end)
    T.it("encodes 'f'", function()
        -- 'f' = 0x66 = 0110 0110
        -- 5 bits: 01100 = 12 = 'C', 11000 = 24 = 'R' (but only 3 bits used: 110 00 = last 3 bits of 0x66 = 6, pad to 5: 01100)
        -- Actually: 0x66 = 102 decimal
        -- first 5 bits: 102 >> 3 = 12 → 'C'
        -- last 3 bits << 2: (102 & 7) << 2 = 6<<2 = 24 → 'R'
        -- So: "CR" (no padding for Crockford)
        T.eq(b32.encode_crockford("f"), "CR")
    end)
    T.it("encodes 'foo'", function()
        -- same 5 chars as standard but with crockford alphabet (no padding)
        local result = b32.encode_crockford("foo")
        T.eq(#result, 5)
        T.eq(b32.decode_crockford(result), "foo")
    end)
    T.it("encodes 'foobar'", function()
        local result = b32.encode_crockford("foobar")
        T.eq(#result, 10)  -- ceil(6*8/5) = ceil(9.6) = 10
        T.eq(b32.decode_crockford(result), "foobar")
    end)
    T.it("no padding characters in output", function()
        local result = b32.encode_crockford("f")
        T.ok(not result:find("="), "crockford output should not contain padding")
    end)
end)

T.describe("crockford decode", function()
    T.it("decodes empty string", function()
        T.eq(b32.decode_crockford(""), "")
    end)
    T.it("case-insensitive: lowercase", function()
        local upper = b32.encode_crockford("foo")
        T.eq(b32.decode_crockford(upper:lower()), "foo")
    end)
    T.it("maps I to 1", function()
        -- encode "0" as crockford, then replace digit '1' with 'I' and re-decode
        -- 0x30 = 48: first 5 bits = 6 → '6', last 3 = 0, padded = 0 → '0'
        -- So encode("0") = "60" (no pad)
        -- encode uses value 6 → char '6', value 0 → char '0'
        -- Now '1' has value 1, same as 'I'
        -- Let's just check that a string with 'I' and the same string with '1' decode the same
        local with_one  = b32.decode_crockford("0I")
        local with_i    = b32.decode_crockford("01")
        T.eq(with_one, with_i)
    end)
    T.it("maps L to 1", function()
        local with_l = b32.decode_crockford("0L")
        local with_1 = b32.decode_crockford("01")
        T.eq(with_l, with_1)
    end)
    T.it("maps O to 0", function()
        local with_o = b32.decode_crockford("O0")
        local with_0 = b32.decode_crockford("00")
        T.eq(with_o, with_0)
    end)
    T.it("round-trips binary data", function()
        local s = "\000\128\255\001\254"
        T.eq(b32.decode_crockford(b32.encode_crockford(s)), s)
    end)
    T.it("errors on invalid character (U is not in crockford)", function()
        local result, err = b32.decode_crockford("OU======")
        T.eq(result, nil)
        T.ok(err ~= nil, "expected error message")
    end)
end)

