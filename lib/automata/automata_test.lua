T.describe("from_regex: edge cases", function()
  T.it("empty language: DFA with no accepting states rejects all", function()
    local dfa = automata.dfa_new()
    local q0 = dfa:add_state({ start = true })
    -- no accepting states
    T.fail(dfa:accepts(""))
    T.fail(dfa:accepts("a"))
  end)

  T.it("NFA with no accepting states", function()
    local nfa = automata.nfa_new()
    local s0 = nfa:add_state()
    local s1 = nfa:add_state()
    nfa:set_start(s0)
    nfa:add_transition(s0, "a", s1)
    T.fail(nfa:accepts("a"))
    T.fail(nfa:accepts(""))
  end)

  T.it("single char regex via nfa_to_dfa", function()
    local nfa = automata.from_regex("x")
    local dfa = automata.nfa_to_dfa(nfa)
    T.ok(dfa:accepts("x"))
    T.fail(dfa:accepts(""))
    T.fail(dfa:accepts("y"))
  end)

  T.it("complex regex via nfa_to_dfa + minimize", function()
    local nfa = automata.from_regex("(a|b)*abb")
    local dfa = automata.nfa_to_dfa(nfa)
    local min = automata.minimize(dfa)
    T.ok(min:accepts("abb"))
    T.ok(min:accepts("aabb"))
    T.ok(min:accepts("babb"))
    T.ok(min:accepts("ababb"))
    T.fail(min:accepts("ab"))
    T.fail(min:accepts(""))
    T.fail(min:accepts("ab"))
  end)
end)

