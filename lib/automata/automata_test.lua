local T = require("lib.test.assert")
local automata = require("lib.automata")

-- ── NFA construction ────────────────────────────────────────────────────────

T.describe("NFA construction", function()
  T.it("add_state returns sequential ids", function()
    local nfa = automata.nfa_new()
    local s0 = nfa:add_state()
    local s1 = nfa:add_state()
    local s2 = nfa:add_state({ accept = true })
    T.eq(s0, 1)
    T.eq(s1, 2)
    T.eq(s2, 3)
    T.eq(nfa.states[s2].accept, true)
    T.eq(nfa.states[s0].accept, false)
  end)

  T.it("set_start sets start state", function()
    local nfa = automata.nfa_new()
    local s0 = nfa:add_state()
    nfa:set_start(s0)
    T.eq(nfa.start, s0)
  end)

  T.it("add_transition stores transitions", function()
    local nfa = automata.nfa_new()
    local s0 = nfa:add_state()
    local s1 = nfa:add_state()
    nfa:add_transition(s0, "a", s1)
    T.ok(nfa.trans[s0] ~= nil)
    T.ok(nfa.trans[s0]["a"] ~= nil)
    T.ok(nfa.trans[s0]["a"][s1])
  end)

  T.it("add_transition stores epsilon (nil key = false)", function()
    local nfa = automata.nfa_new()
    local s0 = nfa:add_state()
    local s1 = nfa:add_state()
    nfa:add_transition(s0, nil, s1)
    T.ok(nfa.trans[s0][false] ~= nil)
    T.ok(nfa.trans[s0][false][s1])
  end)
end)

-- ── NFA epsilon closure ─────────────────────────────────────────────────────

T.describe("NFA epsilon_closure", function()
  T.it("trivial: no eps transitions", function()
    local nfa = automata.nfa_new()
    local s0 = nfa:add_state()
    local s1 = nfa:add_state()
    nfa:add_transition(s0, "a", s1)
    local cl = nfa:epsilon_closure({ [s0] = true })
    T.ok(cl[s0])
    T.eq(cl[s1], nil)
  end)

  T.it("follows epsilon transitions", function()
    local nfa = automata.nfa_new()
    local s0 = nfa:add_state()
    local s1 = nfa:add_state()
    local s2 = nfa:add_state()
    nfa:add_transition(s0, nil, s1)
    nfa:add_transition(s1, nil, s2)
    local cl = nfa:epsilon_closure({ [s0] = true })
    T.ok(cl[s0])
    T.ok(cl[s1])
    T.ok(cl[s2])
  end)

  T.it("does not follow non-epsilon transitions", function()
    local nfa = automata.nfa_new()
    local s0 = nfa:add_state()
    local s1 = nfa:add_state()
    nfa:add_transition(s0, "a", s1)
    local cl = nfa:epsilon_closure({ [s0] = true })
    T.ok(cl[s0])
    T.eq(cl[s1], nil)
  end)
end)

-- ── NFA simulation ──────────────────────────────────────────────────────────

T.describe("NFA accepts", function()
  T.it("accepts simple literal sequence", function()
    local nfa = automata.nfa_new()
    local s0 = nfa:add_state()
    local s1 = nfa:add_state()
    local s2 = nfa:add_state({ accept = true })
    nfa:set_start(s0)
    nfa:add_transition(s0, "a", s1)
    nfa:add_transition(s1, "b", s2)
    T.ok(nfa:accepts("ab"))
    T.fail(nfa:accepts("a"))
    T.fail(nfa:accepts("b"))
    T.fail(nfa:accepts("abc"))
    T.fail(nfa:accepts(""))
  end)

  T.it("accepts via epsilon transition", function()
    local nfa = automata.nfa_new()
    local s0 = nfa:add_state()
    local s1 = nfa:add_state()
    local s2 = nfa:add_state({ accept = true })
    nfa:set_start(s0)
    nfa:add_transition(s0, nil, s1)   -- epsilon from s0 to s1
    nfa:add_transition(s1, "b", s2)
    T.ok(nfa:accepts("b"))
    T.fail(nfa:accepts("ab"))
    T.fail(nfa:accepts(""))
  end)

  T.it("rejects when no start state", function()
    local nfa = automata.nfa_new()
    T.fail(nfa:accepts("anything"))
  end)

  T.it("accepts empty string if start is accepting", function()
    local nfa = automata.nfa_new()
    local s0 = nfa:add_state({ accept = true })
    nfa:set_start(s0)
    T.ok(nfa:accepts(""))
  end)

  T.it("NFA with branching paths", function()
    -- Language: {ab, ac}
    local nfa = automata.nfa_new()
    local s0 = nfa:add_state()
    local s1 = nfa:add_state()
    local s2 = nfa:add_state({ accept = true })
    local s3 = nfa:add_state({ accept = true })
    nfa:set_start(s0)
    nfa:add_transition(s0, "a", s1)
    nfa:add_transition(s1, "b", s2)
    nfa:add_transition(s1, "c", s3)
    T.ok(nfa:accepts("ab"))
    T.ok(nfa:accepts("ac"))
    T.fail(nfa:accepts("a"))
    T.fail(nfa:accepts("ad"))
  end)
end)

