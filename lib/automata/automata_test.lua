-- ── DFA minimization ────────────────────────────────────────────────────────

T.describe("minimize", function()
  T.it("minimized DFA accepts same language", function()
    local dfa = automata.dfa_new()
    local q0 = dfa:add_state({ start = true })
    local q1 = dfa:add_state()
    local q2 = dfa:add_state({ accept = true })
    dfa:add_transition(q0, "a", q1)
    dfa:add_transition(q1, "b", q2)
    local min = automata.minimize(dfa)
    T.ok(min:accepts("ab"))
    T.fail(min:accepts("a"))
    T.fail(min:accepts("b"))
    T.fail(min:accepts(""))
  end)

  T.it("minimizes redundant states", function()
    -- DFA with two equivalent accepting states
    local dfa = automata.dfa_new()
    local q0 = dfa:add_state({ start = true })
    local q1 = dfa:add_state({ accept = true })
    local q2 = dfa:add_state({ accept = true }) -- equivalent to q1
    dfa:add_transition(q0, "a", q1)
    dfa:add_transition(q0, "b", q2)
    -- Both q1 and q2 are accepting and have no outgoing transitions
    -- They should merge to 1 accepting state
    local min = automata.minimize(dfa)
    T.ok(min:accepts("a"))
    T.ok(min:accepts("b"))
    T.fail(min:accepts(""))
    T.fail(min:accepts("ab"))
  end)

  T.it("empty DFA minimizes ok", function()
    local dfa = automata.dfa_new()
    local min = automata.minimize(dfa)
    T.fail(min:accepts(""))
    T.fail(min:accepts("a"))
  end)
end)

-- ── DFA complement ──────────────────────────────────────────────────────────

T.describe("complement", function()
  T.it("accepts exactly strings the original rejects", function()
    local dfa = automata.dfa_new()
    local q0 = dfa:add_state({ start = true })
    local q1 = dfa:add_state()
    local q2 = dfa:add_state({ accept = true })
    dfa:add_transition(q0, "a", q1)
    dfa:add_transition(q1, "b", q2)
    local comp = automata.complement(dfa)
    T.fail(comp:accepts("ab"))  -- original accepted
    T.ok(comp:accepts("b"))     -- original rejected
    T.ok(comp:accepts("a"))     -- original rejected
    T.ok(comp:accepts(""))      -- original rejected
  end)

  T.it("double complement = original", function()
    local dfa = automata.dfa_new()
    local q0 = dfa:add_state({ start = true })
    local q1 = dfa:add_state()
    local q2 = dfa:add_state({ accept = true })
    dfa:add_transition(q0, "a", q1)
    dfa:add_transition(q1, "b", q2)
    local comp2 = automata.complement(automata.complement(dfa))
    T.ok(comp2:accepts("ab"))
    T.fail(comp2:accepts("b"))
    T.fail(comp2:accepts("a"))
  end)
end)

-- ── DFA intersection / union ────────────────────────────────────────────────

T.describe("intersection", function()
  T.it("intersection: only strings in both languages", function()
    -- dfa1: accepts "ab"
    local dfa1 = automata.dfa_new()
    local a0 = dfa1:add_state({ start = true })
    local a1 = dfa1:add_state()
    local a2 = dfa1:add_state({ accept = true })
    dfa1:add_transition(a0, "a", a1)
    dfa1:add_transition(a1, "b", a2)

    -- dfa2: accepts "ab" or "ac"
    local dfa2 = automata.dfa_new()
    local b0 = dfa2:add_state({ start = true })
    local b1 = dfa2:add_state()
    local b2 = dfa2:add_state({ accept = true })
    local b3 = dfa2:add_state({ accept = true })
    dfa2:add_transition(b0, "a", b1)
    dfa2:add_transition(b1, "b", b2)
    dfa2:add_transition(b1, "c", b3)

    local inter = automata.intersection(dfa1, dfa2)
    T.ok(inter:accepts("ab"))   -- in both
    T.fail(inter:accepts("ac")) -- only in dfa2
    T.fail(inter:accepts("a"))
  end)
end)

T.describe("union", function()
  T.it("union: strings in either language", function()
    -- dfa1: accepts "a"
