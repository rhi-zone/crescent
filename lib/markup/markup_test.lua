local T = require("lib.test.assert")
local M = require("lib.markup")

-- ============================================================
-- Markdown: Headings
-- ============================================================
T.describe("markdown headings", function()
  T.it("h1", function()
    T.eq(M.markdown("# Hello"), "<h1>Hello</h1>\n")
  end)
  T.it("h2", function()
    T.eq(M.markdown("## World"), "<h2>World</h2>\n")
  end)
  T.it("h3 through h6", function()
    T.eq(M.markdown("### A"), "<h3>A</h3>\n")
    T.eq(M.markdown("#### B"), "<h4>B</h4>\n")
    T.eq(M.markdown("##### C"), "<h5>C</h5>\n")
    T.eq(M.markdown("###### D"), "<h6>D</h6>\n")
  end)
  T.it("clamps at h6", function()
    T.eq(M.markdown("####### Too deep"), "<h6>Too deep</h6>\n")
  end)
  T.it("setext h1 with ===", function()
    local html = M.markdown("Title\n=====")
    T.eq(html, "<h1>Title</h1>\n")
  end)
  T.it("setext h2 with ---", function()
    local html = M.markdown("Section\n-------")
    T.eq(html, "<h2>Section</h2>\n")
  end)
  T.it("heading strips trailing hashes", function()
    T.eq(M.markdown("## Heading ##"), "<h2>Heading</h2>\n")
  end)
end)

-- ============================================================
