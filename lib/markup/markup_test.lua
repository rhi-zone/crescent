-- ============================================================
-- Markdown: AST structure
-- ============================================================
T.describe("markdown parse_markdown returns AST", function()
  T.it("document node", function()
    local ast = M.parse_markdown("# Hello")
    T.eq(ast.tag, "Document")
    T.ok(#ast.children >= 1)
  end)
  T.it("heading node structure", function()
    local ast = M.parse_markdown("## Hi")
    local h = ast.children[1]
    T.eq(h.tag, "Heading")
    T.eq(h.level, 2)
    T.eq(h.children[1].tag, "Text")
    T.eq(h.children[1].value, "Hi")
  end)
  T.it("paragraph node structure", function()
    local ast = M.parse_markdown("Hello")
    local p = ast.children[1]
    T.eq(p.tag, "Paragraph")
    T.eq(p.children[1].tag, "Text")
    T.eq(p.children[1].value, "Hello")
  end)
  T.it("bold node structure", function()
    local ast = M.parse_markdown("**bold**")
    local p = ast.children[1]
    local b = p.children[1]
    T.eq(b.tag, "Bold")
    T.eq(b.children[1].value, "bold")
  end)
end)

-- ============================================================
-- ast_to_text: strip markup
-- ============================================================
T.describe("ast_to_text strips markup", function()
  T.it("plain text passes through", function()
    local ast = M.parse_markdown("Hello world")
    T.eq(M.ast_to_text(ast):gsub("\n+$", ""), "Hello world")
  end)
  T.it("strips bold markers", function()
    local ast = M.parse_markdown("**bold text**")
    T.ok(M.ast_to_text(ast):find("bold text"))
    T.ok(not M.ast_to_text(ast):find("%*%*"))
  end)
  T.it("strips italic markers", function()
    local ast = M.parse_markdown("*italic text*")
    T.ok(M.ast_to_text(ast):find("italic text"))
    T.ok(not M.ast_to_text(ast):find("%*"))
  end)
  T.it("strips link brackets and keeps text", function()
    local ast = M.parse_markdown("[link text](url)")
    local plain = M.ast_to_text(ast)
    T.ok(plain:find("link text"))
    T.ok(not plain:find("%["))
    T.ok(not plain:find("%]"))
  end)
  T.it("image: uses alt text", function()
    local ast = M.parse_markdown("![my image](foo.png)")
    local plain = M.ast_to_text(ast)
    T.ok(plain:find("my image"))
  end)
  T.it("heading text extracted", function()
    local ast = M.parse_markdown("# Title Here")
    local plain = M.ast_to_text(ast)
    T.ok(plain:find("Title Here"))
  end)
  T.it("code block value extracted", function()
    local ast = M.parse_markdown("```\nfn main() {}\n```")
    local plain = M.ast_to_text(ast)
    T.ok(plain:find("fn main"))
  end)
end)

