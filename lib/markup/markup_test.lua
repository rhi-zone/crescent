-- ============================================================
-- Markdown: Bold, Italic, Code
-- ============================================================
T.describe("markdown inline formatting", function()
  T.it("bold **", function()
    T.eq(M.markdown("**bold**"), "<p><strong>bold</strong></p>\n")
  end)
  T.it("bold __", function()
    T.eq(M.markdown("__bold__"), "<p><strong>bold</strong></p>\n")
  end)
  T.it("italic *", function()
    T.eq(M.markdown("*italic*"), "<p><em>italic</em></p>\n")
  end)
  T.it("italic _", function()
    T.eq(M.markdown("_italic_"), "<p><em>italic</em></p>\n")
  end)
  T.it("inline code", function()
    T.eq(M.markdown("`code`"), "<p><code>code</code></p>\n")
  end)
  T.it("inline code escapes HTML", function()
    T.eq(M.markdown("`<b>`"), "<p><code>&lt;b&gt;</code></p>\n")
  end)
  T.it("bold and italic in sentence", function()
    local html = M.markdown("This is **bold** and *italic* text.")
    T.ok(html:find("<strong>bold</strong>"))
    T.ok(html:find("<em>italic</em>"))
  end)
  T.it("HTML entities escaped in text", function()
    local html = M.markdown("a < b & c > d")
    T.ok(html:find("&lt;"))
    T.ok(html:find("&amp;"))
    T.ok(html:find("&gt;"))
  end)
end)

