-- RST: Headings and inline formatting
-- ============================================================
T.describe("rst headings", function()
  T.it("underline-style heading", function()
    local html = M.rst("Title\n=====")
    T.ok(html:find("<h1>Title</h1>"))
  end)
  T.it("different chars get different levels", function()
    local input = "Chapter\n=======\n\nSection\n-------"
    local html = M.rst(input)
    T.ok(html:find("<h1>Chapter</h1>"))
    T.ok(html:find("<h2>Section</h2>"))
  end)
  T.it("same char = same level", function()
    local input = "One\n===\n\nTwo\n==="
    local html = M.rst(input)
    -- Both should be h1
    local _, n1 = html:gsub("<h1>", "")
    T.eq(n1, 2)
  end)
end)

