    T.eq(v, "b")
  end)

  T.it("merge keeps higher timestamp", function()
    local a = crdt.lww_register("r1")
    local b = crdt.lww_register("r2")
    a:set("old", 1)
    b:set("new", 5)
    a:merge(b)
    local v, ts = a:get()
    T.eq(v,  "new")
    T.eq(ts, 5)
  end)

  T.it("merge does not downgrade", function()
    local a = crdt.lww_register("r1")
    local b = crdt.lww_register("r2")
    a:set("high", 10)
    b:set("low",   2)
    a:merge(b)
    local v = a:get()
