-- ─── LWW-Register ────────────────────────────────────────────────────────────

T.describe("LWWRegister", function()
  T.it("get returns nil before set", function()
    local reg = crdt.lww_register("r1")
    local v, ts = reg:get()
    T.eq(v,  nil)
    T.eq(ts, -1)
  end)

  T.it("set and get", function()
    local reg = crdt.lww_register("r1")
    reg:set("hello", 1)
    local v, ts = reg:get()
    T.eq(v,  "hello")
    T.eq(ts, 1)
  end)

  T.it("higher timestamp wins", function()
    local reg = crdt.lww_register("r1")
    reg:set("a", 1)
    reg:set("b", 3)
    reg:set("c", 2)  -- older — should not overwrite
