    T.eq(ts, 4)
  end)
end)

-- ─── 2P-Set ──────────────────────────────────────────────────────────────────

T.describe("TPSet", function()
  T.it("empty set contains nothing", function()
    local s = crdt.tpset()
    T.fail(s:contains("a"))
  end)

  T.it("add and contains", function()
    local s = crdt.tpset()
    s:add("a")
    T.ok(s:contains("a"))
  end)

  T.it("remove works", function()
    local s = crdt.tpset()
    s:add("a")
    s:remove("a")
    T.fail(s:contains("a"))
  end)

  T.it("removed elements cannot be re-added", function()
    local s = crdt.tpset()
    s:add("a")
    s:remove("a")
    s:add("a")        -- silently ignored — remove wins
    T.fail(s:contains("a"))
  end)

  T.it("value returns live elements", function()
    local s = crdt.tpset()
    s:add("a"); s:add("b"); s:add("c")
    s:remove("b")
    local v = s:value()
    T.ok(v["a"])
    T.fail(v["b"])
    T.ok(v["c"])
  end)

  T.it("merge unions both sets", function()
    local a = crdt.tpset()
    local b = crdt.tpset()
    a:add("x"); a:add("y")
    b:add("y"); b:add("z"); b:remove("y")
    a:merge(b)
    T.ok(a:contains("x"))
    T.fail(a:contains("y"))   -- removal from b propagates
    T.ok(a:contains("z"))
  end)

  T.it("commutativity", function()
    local a = crdt.tpset()
    local b = crdt.tpset()
    a:add("p"); a:add("q"); a:remove("q")
    b:add("q"); b:add("r")
    local ab = a:clone(); ab:merge(b)
    local ba = b:clone(); ba:merge(a)
    T.ok(ab:eq(ba))
  end)

  T.it("idempotency", function()
    local s = crdt.tpset()
    s:add("a"); s:remove("a"); s:add("b")
    local c = s:clone(); s:merge(c)
    T.ok(s:eq(c))
  end)

  T.it("associativity", function()
    local a = crdt.tpset(); a:add("x")
    local b = crdt.tpset(); b:add("y"); b:remove("y")
    local c = crdt.tpset(); c:add("z"); c:add("x"); c:remove("x")
    local left  = a:clone(); left:merge(b); left:merge(c)
    local right = a:clone(); local bc = b:clone(); bc:merge(c); right:merge(bc)
    T.ok(left:eq(right))
  end)
end)

-- ─── OR-Set ──────────────────────────────────────────────────────────────────

T.describe("ORSet", function()
  T.it("empty set contains nothing", function()
    local s = crdt.orset("r1")
    T.fail(s:contains("a"))
  end)

  T.it("add and contains", function()
    local s = crdt.orset("r1")
    s:add("a")
    T.ok(s:contains("a"))
  end)

  T.it("remove wipes element", function()
    local s = crdt.orset("r1")
    s:add("a")
    s:remove("a")
    T.fail(s:contains("a"))
  end)

  T.it("re-add after remove", function()
    local s = crdt.orset("r1")
    s:add("a")
    s:remove("a")
    s:add("a")
    T.ok(s:contains("a"))
  end)

  T.it("value reflects live elements", function()
    local s = crdt.orset("r1")
    s:add("a"); s:add("b"); s:remove("a")
    local v = s:value()
    T.fail(v["a"])
    T.ok(v["b"])
  end)

  T.it("merge unions observed tags", function()
    local a = crdt.orset("r1")
    local b = crdt.orset("r2")
    a:add("x")
    b:add("x")
    b:remove("x")      -- b removes its own tag only
    a:merge(b)
    -- a still has its own tag for "x", so it should still be present
    T.ok(a:contains("x"))
  end)

  T.it("remove then merge: concurrent add wins in OR-set semantics", function()
    -- replica A adds "x"; replica B concurrently removes "x"
    -- after merge, A's add tag survives because B only knew B's tags (none here)
    local a = crdt.orset("r1")
    local b = crdt.orset("r2")
    a:add("x")
    -- B has not observed A's add, so B's remove removes nothing
    b:remove("x")
    a:merge(b)
    T.ok(a:contains("x"))
  end)

  T.it("commutativity", function()
    local a = crdt.orset("r1")
    local b = crdt.orset("r2")
    a:add("p"); a:add("q")
    b:add("q"); b:remove("q"); b:add("r")
    local ab = a:clone(); ab:merge(b)
    local ba = b:clone(); ba:merge(a)
    T.ok(ab:eq(ba))
  end)

  T.it("idempotency", function()
    local s = crdt.orset("r1")
    s:add("a"); s:remove("a"); s:add("b")
    local c = s:clone()
    s:merge(c)
    T.ok(s:eq(c))
  end)

  T.it("associativity", function()
    local a = crdt.orset("r1"); a:add("x")
    local b = crdt.orset("r2"); b:add("y")
    local c = crdt.orset("r3"); c:add("z"); c:add("y"); c:remove("y")
    local left  = a:clone(); left:merge(b); left:merge(c)
    local right = a:clone(); local bc = b:clone(); bc:merge(c); right:merge(bc)
    T.ok(left:eq(right))
  end)
end)

-- ─── LWW-Map ─────────────────────────────────────────────────────────────────

T.describe("LWWMap", function()
  T.it("get on missing key returns nil", function()
    local m = crdt.lww_map("r1")
    T.eq(m:get("k"), nil)
  end)

  T.it("set and get", function()
    local m = crdt.lww_map("r1")
    m:set("k", "v", 1)
    local v, ts = m:get("k")
    T.eq(v,  "v")
    T.eq(ts, 1)
  end)

  T.it("higher-timestamp update wins", function()
    local m = crdt.lww_map("r1")
    m:set("k", "old", 1)
    m:set("k", "new", 5)
    T.eq(m:get("k"), "new")
  end)

  T.it("lower-timestamp update is ignored", function()
    local m = crdt.lww_map("r1")
    m:set("k", "new", 5)
    m:set("k", "old", 1)
    T.eq(m:get("k"), "new")
  end)

  T.it("delete tombstones the key", function()
    local m = crdt.lww_map("r1")
    m:set("k", "v", 1)
    m:delete("k", 3)
    T.eq(m:get("k"), nil)
  end)

  T.it("set after delete with higher ts revives key", function()
    local m = crdt.lww_map("r1")
    m:set("k", "v", 1)
    m:delete("k", 3)
    m:set("k", "revived", 5)
    T.eq(m:get("k"), "revived")
  end)

  T.it("set with lower ts after delete does not revive", function()
    local m = crdt.lww_map("r1")
    m:set("k", "v", 3)
    m:delete("k", 5)
    m:set("k", "old", 2)  -- lower ts than tombstone
    T.eq(m:get("k"), nil)
  end)

  T.it("keys returns only live keys", function()
    local m = crdt.lww_map("r1")
    m:set("a", 1, 1); m:set("b", 2, 1); m:set("c", 3, 1)
    m:delete("b", 2)
    local ks = m:keys()
    table.sort(ks)
    T.eq(#ks, 2)
    T.eq(ks[1], "a")
    T.eq(ks[2], "c")
  end)

  T.it("merge keeps higher-ts entries", function()
    local a = crdt.lww_map("r1")
    local b = crdt.lww_map("r2")
    a:set("x", "from_a", 1)
    b:set("x", "from_b", 5)
    a:merge(b)
    T.eq(a:get("x"), "from_b")
  end)

  T.it("merge propagates tombstones", function()
    local a = crdt.lww_map("r1")
    local b = crdt.lww_map("r2")
    a:set("x", "val", 1)
    b:delete("x", 3)
    a:merge(b)
    T.eq(a:get("x"), nil)
  end)

  T.it("commutativity", function()
    local a = crdt.lww_map("r1")
    local b = crdt.lww_map("r2")
    a:set("p", "ap", 2); a:set("q", "aq", 1)
    b:set("p", "bp", 5); b:delete("q", 3)
    local ab = a:clone(); ab:merge(b)
    local ba = b:clone(); ba:merge(a)
    T.ok(ab:eq(ba))
  end)

  T.it("idempotency", function()
    local m = crdt.lww_map("r1")
    m:set("a", 1, 1); m:delete("b", 2)
    local c = m:clone()
    m:merge(c)
    T.ok(m:eq(c))
  end)

  T.it("associativity", function()
    local a = crdt.lww_map("r1"); a:set("x", "a", 1)
    local b = crdt.lww_map("r2"); b:set("x", "b", 3); b:set("y", "by", 1)
    local c = crdt.lww_map("r3"); c:delete("y", 5)
    local left  = a:clone(); left:merge(b); left:merge(c)
    local right = a:clone(); local bc = b:clone(); bc:merge(c); right:merge(bc)
    T.ok(left:eq(right))
  end)
end)

