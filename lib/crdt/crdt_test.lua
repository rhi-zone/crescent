local T    = require("lib.test.assert")
local crdt = require("lib.crdt")

-- ─── helpers ─────────────────────────────────────────────────────────────────

-- Returns true when two plain key→true tables have identical key sets.
local function set_eq(a, b)
  for k in pairs(a) do
    if not b[k] then return false end
  end
  for k in pairs(b) do
    if not a[k] then return false end
  end
  return true
end

-- ─── G-Counter ───────────────────────────────────────────────────────────────

T.describe("GCounter", function()
  T.it("starts at zero", function()
    local gc = crdt.gcounter("r1")
    T.eq(gc:value(), 0)
  end)

  T.it("increments by 1", function()
    local gc = crdt.gcounter("r1")
    gc:increment()
    T.eq(gc:value(), 1)
  end)

  T.it("increments by n", function()
    local gc = crdt.gcounter("r1")
    gc:increment(5)
    T.eq(gc:value(), 5)
  end)

  T.it("merge takes per-replica max", function()
    local a = crdt.gcounter("r1")
    local b = crdt.gcounter("r2")
    a:increment(3)
    b:increment(2)
    a:merge(b)
    T.eq(a:value(), 5)
  end)

  T.it("merge does not shrink own count", function()
    local a = crdt.gcounter("r1")
    local b = crdt.gcounter("r1")
    a:increment(10)
    b:increment(3)
    a:merge(b)
    T.eq(a:value(), 10)
  end)

  T.it("commutativity: merge(a,b) == merge(b,a)", function()
    local a = crdt.gcounter("r1")
    local b = crdt.gcounter("r2")
    a:increment(4)
    b:increment(7)
    local ab = a:clone(); ab:merge(b)
    local ba = b:clone(); ba:merge(a)
    T.eq(ab:value(), ba:value())
  end)

  T.it("idempotency: merge(a,a) == a", function()
    local a = crdt.gcounter("r1")
    a:increment(6)
    local before = a:value()
    a:merge(a:clone())
    T.eq(a:value(), before)
  end)

  T.it("associativity: merge(merge(a,b),c) == merge(a,merge(b,c))", function()
    local a = crdt.gcounter("r1")
    local b = crdt.gcounter("r2")
    local c = crdt.gcounter("r3")
    a:increment(1); b:increment(2); c:increment(3)
    local left  = a:clone(); left:merge(b);  left:merge(c)
    local right = a:clone(); local bc = b:clone(); bc:merge(c); right:merge(bc)
    T.eq(left:value(), right:value())
  end)

  T.it("clone is independent", function()
    local a = crdt.gcounter("r1")
    a:increment(5)
    local b = a:clone()
    b:increment(10)
    T.eq(a:value(), 5)
    T.eq(b:value(), 15)
  end)
end)

