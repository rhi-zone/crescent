T.describe("to_hex / from_hex round-trip", function()
  T.it("all-zero round-trips", function()
    local b = bitset.new(64)
    local h = b:to_hex()
    T.eq(#h, 16)  -- 2 words × 8 hex digits
    local b2, err = bitset.from_hex(h, 64)
    T.eq(err, nil)
    T.eq(b2:count(), 0)
  end)

  T.it("round-trip preserves set bits", function()
    local b = bitset.new(64)
    b:set(1); b:set(32); b:set(33); b:set(64)
    local h = b:to_hex()
    local b2 = bitset.from_hex(h, 64)
    T.ok(b2:get(1))
    T.ok(b2:get(32))
    T.ok(b2:get(33))
    T.ok(b2:get(64))
    T.ok(not b2:get(2))
    T.eq(b2:count(), 4)
  end)

  T.it("from_hex error on wrong length", function()
    local b, err = bitset.from_hex("aabbccdd", 64)  -- need 16 chars for 64 bits
    T.eq(b, nil)
    T.ok(err ~= nil)
  end)

  T.it("from_hex error on invalid hex", function()
    local b, err = bitset.from_hex("zzzzzzzzzzzzzzzz", 64)
    T.eq(b, nil)
    T.ok(err ~= nil)
  end)

  T.it("round-trip with 32-bit bitset", function()
    local b = bitset.new(32)
    for i = 1, 32, 2 do b:set(i) end
    local h = b:to_hex()
    T.eq(#h, 8)
    local b2 = bitset.from_hex(h, 32)
    T.eq(b2:count(), 16)
    for i = 1, 32, 2 do T.ok(b2:get(i)) end
    for i = 2, 32, 2 do T.ok(not b2:get(i)) end
  end)

  T.it("round-trip with non-multiple-of-32 size", function()
    local b = bitset.new(33)
    b:set(1); b:set(33)
    local h = b:to_hex()
    local b2 = bitset.from_hex(h, 33)
    T.ok(b2:get(1))
    T.ok(b2:get(33))
    T.eq(b2:count(), 2)
  end)
end)

