-- lib/bitset/bitset_test.lua

if not package.path:find("./?/init.lua", 1, true) then
  package.path = "./?/init.lua;" .. package.path
end

local T = require("lib.test.assert")
local bitset = require("lib.bitset")

-- ---------------------------------------------------------------------------
T.describe("bitset.new", function()
  T.it("creates a zeroed bitset of given size", function()
    local b = bitset.new(64)
    T.eq(b:size(), 64)
    T.eq(b:count(), 0)
    T.ok(b:none())
    T.ok(not b:any())
    T.ok(not b:all())
  end)

  T.it("rejects invalid sizes", function()
    local b, err = bitset.new(0)
    T.eq(b, nil)
    T.ok(err ~= nil)
    local b2, err2 = bitset.new(-5)
    T.eq(b2, nil)
    T.ok(err2 ~= nil)
    local b3, err3 = bitset.new(1.5)
    T.eq(b3, nil)
    T.ok(err3 ~= nil)
  end)
end)

-- ---------------------------------------------------------------------------
T.describe("set / get / clear / flip", function()
  T.it("set and get bit 1", function()
    local b = bitset.new(64)
    T.ok(not b:get(1))
    b:set(1)
    T.ok(b:get(1))
  end)

  T.it("set and get bit 32 (word boundary)", function()
    local b = bitset.new(64)
    b:set(32)
    T.ok(b:get(32))
    T.ok(not b:get(31))
    T.ok(not b:get(33))
  end)

  T.it("set and get bit 33 (second word)", function()
    local b = bitset.new(64)
    b:set(33)
    T.ok(b:get(33))
    T.ok(not b:get(32))
    T.ok(not b:get(34))
  end)

  T.it("set and get bit 64 (last bit)", function()
    local b = bitset.new(64)
    b:set(64)
    T.ok(b:get(64))
    T.ok(not b:get(63))
  end)

  T.it("clear a set bit", function()
    local b = bitset.new(64)
    b:set(10)
    T.ok(b:get(10))
    b:clear(10)
    T.ok(not b:get(10))
  end)

  T.it("clear an already-clear bit is a no-op", function()
    local b = bitset.new(64)
    b:clear(5)
    T.ok(not b:get(5))
  end)

  T.it("flip toggles bit on and off", function()
    local b = bitset.new(64)
    T.ok(not b:get(5))
    b:flip(5)
    T.ok(b:get(5))
    b:flip(5)
    T.ok(not b:get(5))
  end)

  T.it("out-of-range set returns error", function()
    local b = bitset.new(32)
    local ok, err = b:set(33)
    T.eq(ok, nil)
    T.ok(err ~= nil)
  end)

  T.it("out-of-range get returns error", function()
    local b = bitset.new(32)
    local ok, err = b:get(0)
    T.eq(ok, nil)
    T.ok(err ~= nil)
  end)

  T.it("out-of-range clear returns error", function()
    local b = bitset.new(32)
    local ok, err = b:clear(33)
    T.eq(ok, nil)
    T.ok(err ~= nil)
  end)

  T.it("out-of-range flip returns error", function()
    local b = bitset.new(32)
    local ok, err = b:flip(0)
    T.eq(ok, nil)
    T.ok(err ~= nil)
  end)
end)

-- ---------------------------------------------------------------------------
T.describe("count / any / none / all", function()
  T.it("count increases with each set", function()
    local b = bitset.new(64)
    T.eq(b:count(), 0)
    b:set(1)
    T.eq(b:count(), 1)
    b:set(32)
    T.eq(b:count(), 2)
    b:set(33)
    T.eq(b:count(), 3)
    b:set(64)
    T.eq(b:count(), 4)
  end)

  T.it("count decreases with clear", function()
    local b = bitset.new(64)
    b:set(1); b:set(2); b:set(3)
    T.eq(b:count(), 3)
    b:clear(2)
    T.eq(b:count(), 2)
  end)

  T.it("any / none / all on empty bitset", function()
    local b = bitset.new(8)
    T.ok(b:none())
    T.ok(not b:any())
    T.ok(not b:all())
  end)

  T.it("any is true when at least one bit set", function()
    local b = bitset.new(8)
    b:set(4)
    T.ok(b:any())
    T.ok(not b:none())
  end)

  T.it("all is true when every bit set (8-bit)", function()
    local b = bitset.new(8)
    for i = 1, 8 do b:set(i) end
    T.ok(b:all())
    T.ok(b:any())
    T.ok(not b:none())
  end)

  T.it("all is true when every bit set (64-bit)", function()
    local b = bitset.new(64)
    for i = 1, 64 do b:set(i) end
    T.ok(b:all())
  end)

  T.it("all is false if one bit missing (non-multiple-of-32 size)", function()
    local b = bitset.new(33)
    for i = 1, 33 do b:set(i) end
    T.ok(b:all())
    b:clear(17)
    T.ok(not b:all())
  end)

  T.it("popcount across word boundary", function()
    local b = bitset.new(64)
    -- Set bits 30, 31, 32, 33, 34 — spanning word 1 and word 2
    b:set(30); b:set(31); b:set(32); b:set(33); b:set(34)
    T.eq(b:count(), 5)
  end)
end)

-- ---------------------------------------------------------------------------
T.describe("band / bor / bxor / bnot / difference", function()
  T.it("band: intersection", function()
    local b1 = bitset.new(64)
    local b2 = bitset.new(64)
    b1:set(1); b1:set(32); b1:set(33)
    b2:set(32); b2:set(33); b2:set(64)
    local r = b1:band(b2)
    T.ok(not r:get(1))
    T.ok(r:get(32))
    T.ok(r:get(33))
    T.ok(not r:get(64))
    T.eq(r:count(), 2)
  end)

  T.it("bor: union", function()
    local b1 = bitset.new(64)
    local b2 = bitset.new(64)
    b1:set(1); b1:set(10)
    b2:set(10); b2:set(20)
    local r = b1:bor(b2)
    T.ok(r:get(1))
    T.ok(r:get(10))
    T.ok(r:get(20))
    T.eq(r:count(), 3)
  end)

  T.it("bxor: symmetric difference", function()
    local b1 = bitset.new(64)
    local b2 = bitset.new(64)
    b1:set(1); b1:set(10)
    b2:set(10); b2:set(20)
    local r = b1:bxor(b2)
    T.ok(r:get(1))
    T.ok(not r:get(10))  -- shared → xored out
    T.ok(r:get(20))
    T.eq(r:count(), 2)
  end)

  T.it("bnot: flips all bits within size", function()
    local b = bitset.new(8)
    b:set(1); b:set(3); b:set(5); b:set(7)
    local r = b:bnot()
    T.ok(not r:get(1))
    T.ok(r:get(2))
    T.ok(not r:get(3))
    T.ok(r:get(4))
    T.ok(not r:get(5))
    T.ok(r:get(6))
    T.ok(not r:get(7))
    T.ok(r:get(8))
    T.eq(r:count(), 4)
  end)

  T.it("bnot on size non-multiple-of-32 does not set extra bits", function()
    local b = bitset.new(33)  -- 2 words but only 33 bits
    -- all zeros; bnot should set exactly 33 bits
    local r = b:bnot()
    T.eq(r:count(), 33)
    T.ok(not r:get(33) == false)  -- bit 33 is set
    T.ok(r:get(33))
  end)

  T.it("difference: bits in b1 but not b2", function()
    local b1 = bitset.new(64)
    local b2 = bitset.new(64)
    b1:set(1); b1:set(5); b1:set(10)
    b2:set(5); b2:set(10); b2:set(20)
    local r = b1:difference(b2)
    T.ok(r:get(1))
    T.ok(not r:get(5))
    T.ok(not r:get(10))
    T.ok(not r:get(20))
    T.eq(r:count(), 1)
  end)

  T.it("size mismatch returns error", function()
    local b1 = bitset.new(32)
    local b2 = bitset.new(64)
    local r, err = b1:band(b2)
    T.eq(r, nil)
    T.ok(err ~= nil)
    local r2, err2 = b1:bor(b2)
    T.eq(r2, nil)
    T.ok(err2 ~= nil)
    local r3, err3 = b1:bxor(b2)
    T.eq(r3, nil)
    T.ok(err3 ~= nil)
    local r4, err4 = b1:difference(b2)
    T.eq(r4, nil)
    T.ok(err4 ~= nil)
  end)
end)

-- ---------------------------------------------------------------------------
T.describe("iter / to_array", function()
  T.it("iter returns positions in ascending order", function()
    local b = bitset.new(64)
    b:set(1); b:set(5); b:set(32); b:set(33); b:set(64)
    local positions = {}
    for pos in b:iter() do positions[#positions + 1] = pos end
    T.eq(#positions, 5)
    T.eq(positions[1], 1)
    T.eq(positions[2], 5)
    T.eq(positions[3], 32)
    T.eq(positions[4], 33)
    T.eq(positions[5], 64)
  end)

  T.it("iter on empty bitset yields nothing", function()
    local b = bitset.new(64)
    local count = 0
    for _ in b:iter() do count = count + 1 end
    T.eq(count, 0)
  end)

  T.it("iter only goes up to size for partial last word", function()
    local b = bitset.new(33)
    b:set(33)
    local positions = {}
    for pos in b:iter() do positions[#positions + 1] = pos end
    T.eq(#positions, 1)
    T.eq(positions[1], 33)
  end)

  T.it("to_array matches iter", function()
    local b = bitset.new(64)
    b:set(2); b:set(17); b:set(40); b:set(63)
    local arr = b:to_array()
    T.eq(#arr, 4)
    T.eq(arr[1], 2)
    T.eq(arr[2], 17)
    T.eq(arr[3], 40)
    T.eq(arr[4], 63)
  end)
end)

