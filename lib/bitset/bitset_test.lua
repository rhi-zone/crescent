T.describe("dynamic bitset", function()
  T.it("starts empty", function()
    local db = bitset.dynamic_new()
    T.eq(db:count(), 0)
    T.ok(db:none())
    T.ok(not db:any())
  end)

  T.it("set and get within first word", function()
    local db = bitset.dynamic_new()
    db:set(1)
    T.ok(db:get(1))
    T.ok(not db:get(2))
    T.eq(db:count(), 1)
  end)

  T.it("auto-grows to accommodate large bit positions", function()
    local db = bitset.dynamic_new()
    db:set(1000)
    T.ok(db:get(1000))
    T.eq(db:count(), 1)
    T.ok(not db:get(999))
    T.ok(not db:get(1001))
  end)

  T.it("set multiple sparse bits", function()
    local db = bitset.dynamic_new()
    db:set(1); db:set(100); db:set(500); db:set(1000)
    T.eq(db:count(), 4)
    T.ok(db:get(1))
    T.ok(db:get(100))
    T.ok(db:get(500))
    T.ok(db:get(1000))
  end)

  T.it("clear a set bit", function()
    local db = bitset.dynamic_new()
    db:set(50)
    T.ok(db:get(50))
    db:clear(50)
    T.ok(not db:get(50))
    T.eq(db:count(), 0)
  end)

  T.it("clear beyond allocated range is a no-op", function()
    local db = bitset.dynamic_new()
    db:set(10)
    db:clear(10000)  -- not allocated
    T.ok(db:get(10))
    T.eq(db:count(), 1)
  end)

  T.it("flip toggles", function()
    local db = bitset.dynamic_new()
    db:flip(7)
    T.ok(db:get(7))
    db:flip(7)
    T.ok(not db:get(7))
  end)

  T.it("get on unset position returns false (no error)", function()
    local db = bitset.dynamic_new()
    T.ok(not db:get(9999))
  end)

  T.it("iter yields set bits in order", function()
    local db = bitset.dynamic_new()
    db:set(3); db:set(32); db:set(33); db:set(200)
    local arr = db:to_array()
    T.eq(#arr, 4)
    T.eq(arr[1], 3)
    T.eq(arr[2], 32)
    T.eq(arr[3], 33)
    T.eq(arr[4], 200)
  end)

  T.it("size tracks max bit set", function()
    local db = bitset.dynamic_new()
    T.eq(db:size(), 0)
    db:set(50)
    T.eq(db:size(), 50)
    db:set(200)
    T.eq(db:size(), 200)
  end)

  T.it("count across word boundaries", function()
    local db = bitset.dynamic_new()
    -- set bits around word boundary 32/33
    db:set(31); db:set(32); db:set(33); db:set(34)
    T.eq(db:count(), 4)
  end)

  T.it("any/none after set and clear", function()
    local db = bitset.dynamic_new()
    T.ok(db:none())
    db:set(42)
    T.ok(db:any())
    T.ok(not db:none())
    db:clear(42)
    T.ok(db:none())
    T.ok(not db:any())
  end)
end)

