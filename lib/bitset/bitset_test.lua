T.describe("to_string", function()
  T.it("all zeros gives all-zero string", function()
    local b = bitset.new(8)
    T.eq(b:to_string(), "00000000")
  end)

  T.it("bit 1 set gives leading 1", function()
    local b = bitset.new(8)
    b:set(1)
    T.eq(b:to_string(), "10000000")
  end)

  T.it("bit 8 set gives trailing 1", function()
    local b = bitset.new(8)
    b:set(8)
    T.eq(b:to_string(), "00000001")
  end)

  T.it("alternating bits", function()
    local b = bitset.new(8)
    b:set(1); b:set(3); b:set(5); b:set(7)
    T.eq(b:to_string(), "10101010")
  end)

  T.it("length equals size", function()
    local b = bitset.new(33)
    T.eq(#b:to_string(), 33)
  end)
end)

