T.describe("edge cases and regression", function()
  T.it("1-bit bitset works correctly", function()
    local b = bitset.new(1)
    T.eq(b:size(), 1)
    T.ok(not b:get(1))
    b:set(1)
    T.ok(b:get(1))
    T.ok(b:all())
    T.eq(b:count(), 1)
    b:clear(1)
    T.ok(b:none())
  end)

  T.it("32-bit bitset — bnot of all-ones gives empty", function()
    local b = bitset.new(32)
    for i = 1, 32 do b:set(i) end
    local r = b:bnot()
    T.eq(r:count(), 0)
    T.ok(r:none())
  end)

  T.it("bnot round-trip: bnot(bnot(b)) == b", function()
    local b = bitset.new(64)
    b:set(1); b:set(17); b:set(32); b:set(33); b:set(48); b:set(64)
    local arr_orig = b:to_array()
    local r = b:bnot():bnot()
    local arr_rt = r:to_array()
    T.eq(#arr_orig, #arr_rt)
    for i = 1, #arr_orig do
      T.eq(arr_orig[i], arr_rt[i])
    end
  end)

  T.it("band with self equals self", function()
    local b = bitset.new(64)
    b:set(7); b:set(8); b:set(9)
    local r = b:band(b)
    T.eq(r:to_string(), b:to_string())
  end)

  T.it("bxor with self gives empty", function()
    local b = bitset.new(64)
    b:set(7); b:set(40)
    local r = b:bxor(b)
    T.eq(r:count(), 0)
  end)

  T.it("bor with bnot gives all set", function()
    local b = bitset.new(32)
    b:set(1); b:set(15); b:set(32)
    local r = b:bor(b:bnot())
    T.ok(r:all())
  end)

  T.it("large bitset: 1024 bits", function()
    local b = bitset.new(1024)
    T.eq(b:size(), 1024)
    b:set(1)
    b:set(512)
    b:set(1024)
    T.eq(b:count(), 3)
    local arr = b:to_array()
    T.eq(arr[1], 1)
    T.eq(arr[2], 512)
    T.eq(arr[3], 1024)
  end)

  T.it("to_hex/from_hex round-trip on all-set 64-bit", function()
    local b = bitset.new(64)
    for i = 1, 64 do b:set(i) end
    local h = b:to_hex()
    local b2 = bitset.from_hex(h, 64)
    T.ok(b2:all())
    T.eq(b2:count(), 64)
  end)
end)
