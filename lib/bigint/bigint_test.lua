-- ── Basic arithmetic ─────────────────────────────────────────────────────────

T.describe("addition", function()
  T.it("adds two positive numbers", function()
    T.eq(bigint.new(123):add(bigint.new(456)):to_string(), "579")
  end)
  T.it("adds with carry across chunks", function()
    T.eq(bigint.new(9999999):add(bigint.new(1)):to_string(), "10000000")
  end)
  T.it("adds large numbers", function()
    local a = bigint.new("99999999999999999999999999999")
    local b = bigint.new("1")
    T.eq(a:add(b):to_string(), "100000000000000000000000000000")
  end)
  T.it("adds positive and negative", function()
    T.eq(bigint.new(10):add(bigint.new(-3)):to_string(), "7")
  end)
  T.it("adds negative and positive", function()
    T.eq(bigint.new(-10):add(bigint.new(3)):to_string(), "-7")
  end)
  T.it("adds two negatives", function()
    T.eq(bigint.new(-5):add(bigint.new(-3)):to_string(), "-8")
  end)
  T.it("adds to zero result", function()
    T.eq(bigint.new(42):add(bigint.new(-42)):to_string(), "0")
  end)
  T.it("adds zero", function()
    T.eq(bigint.new(42):add(bigint.new(0)):to_string(), "42")
  end)
end)

T.describe("subtraction", function()
  T.it("subtracts smaller from larger", function()
    T.eq(bigint.new(10):sub(bigint.new(3)):to_string(), "7")
  end)
  T.it("subtracts larger from smaller", function()
    T.eq(bigint.new(3):sub(bigint.new(10)):to_string(), "-7")
  end)
  T.it("subtracts equal values", function()
    T.eq(bigint.new(42):sub(bigint.new(42)):to_string(), "0")
  end)
  T.it("subtracts with borrow across chunks", function()
    T.eq(bigint.new(10000000):sub(bigint.new(1)):to_string(), "9999999")
  end)
  T.it("subtracts negative from positive", function()
    T.eq(bigint.new(5):sub(bigint.new(-3)):to_string(), "8")
  end)
end)

T.describe("multiplication", function()
  T.it("multiplies small numbers", function()
    T.eq(bigint.new(6):mul(bigint.new(7)):to_string(), "42")
  end)
  T.it("multiplies by zero", function()
    T.eq(bigint.new(123456):mul(bigint.new(0)):to_string(), "0")
  end)
  T.it("multiplies by one", function()
    T.eq(bigint.new(42):mul(bigint.new(1)):to_string(), "42")
  end)
  T.it("multiplies large numbers", function()
    local a = bigint.new("12345678901234567890")
    local b = bigint.new("98765432109876543210")
    T.eq(a:mul(b):to_string(), "1219326311370217952237463801111263526900")
  end)
  T.it("multiplies with different signs", function()
    T.eq(bigint.new(-6):mul(bigint.new(7)):to_string(), "-42")
    T.eq(bigint.new(6):mul(bigint.new(-7)):to_string(), "-42")
    T.eq(bigint.new(-6):mul(bigint.new(-7)):to_string(), "42")
  end)
end)

-- ── Division ─────────────────────────────────────────────────────────────────

T.describe("division", function()
  T.it("divides evenly", function()
    T.eq(bigint.new(42):div(bigint.new(6)):to_string(), "7")
  end)
  T.it("divides with truncation", function()
    T.eq(bigint.new(10):div(bigint.new(3)):to_string(), "3")
  end)
  T.it("divides large by small", function()
    T.eq(bigint.new("1000000000000"):div(bigint.new(7)):to_string(), "142857142857")
  end)
  T.it("divides large by large", function()
    local a = bigint.new("100000000000000000000")
    local b = bigint.new("33333333333")
    T.eq(a:div(b):to_string(), "3000000000")
  end)
  T.it("divides smaller by larger gives zero", function()
    T.eq(bigint.new(3):div(bigint.new(10)):to_string(), "0")
  end)
  T.it("returns nil,errmsg for division by zero", function()
    local v, err = bigint.new(1):div(bigint.new(0))
    T.eq(v, nil)
    T.ok(err)
  end)
  T.it("handles negative division", function()
    T.eq(bigint.new(-42):div(bigint.new(6)):to_string(), "-7")
    T.eq(bigint.new(42):div(bigint.new(-6)):to_string(), "-7")
    T.eq(bigint.new(-42):div(bigint.new(-6)):to_string(), "7")
  end)
end)

T.describe("mod", function()
  T.it("computes remainder", function()
    T.eq(bigint.new(10):mod(bigint.new(3)):to_string(), "1")
  end)
  T.it("zero remainder", function()
    T.eq(bigint.new(42):mod(bigint.new(6)):to_string(), "0")
  end)
  T.it("returns nil,errmsg for mod by zero", function()
    local v, err = bigint.new(1):mod(bigint.new(0))
    T.eq(v, nil)
    T.ok(err)
  end)
end)

T.describe("divmod", function()
  T.it("returns quotient and remainder", function()
    local q, r = bigint.new(17):divmod(bigint.new(5))
    T.eq(q:to_string(), "3")
    T.eq(r:to_string(), "2")
  end)
  T.it("returns nil,errmsg for zero divisor", function()
    local q, err = bigint.new(1):divmod(bigint.new(0))
    T.eq(q, nil)
    T.ok(err)
  end)
  T.it("quotient * divisor + remainder = dividend", function()
    local a = bigint.new("123456789012345678901234567890")
    local b = bigint.new("9876543210")
    local q, r = a:divmod(b)
    T.eq(q:mul(b):add(r):to_string(), a:to_string())
  end)
end)

