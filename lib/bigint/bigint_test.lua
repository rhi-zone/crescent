local T = require("lib.test.assert")
local bigint = require("lib.bigint")

-- ── Construction ─────────────────────────────────────────────────────────────

T.describe("bigint.new", function()
  T.it("creates from small number", function()
    local a = bigint.new(42)
    T.eq(a:to_string(), "42")
  end)
  T.it("creates from zero", function()
    T.eq(bigint.new(0):to_string(), "0")
  end)
  T.it("creates from negative number", function()
    T.eq(bigint.new(-123):to_string(), "-123")
  end)
  T.it("creates from string", function()
    T.eq(bigint.new("12345678901234567890"):to_string(), "12345678901234567890")
  end)
  T.it("creates from negative string", function()
    T.eq(bigint.new("-99999999999999"):to_string(), "-99999999999999")
  end)
  T.it("creates from string with leading zeros", function()
    T.eq(bigint.new("000123"):to_string(), "123")
  end)
  T.it("clones another bigint", function()
    local a = bigint.new(42)
    local b = bigint.new(a)
    T.eq(b:to_string(), "42")
    -- mutation of b should not affect a
    b.d[1] = 99
    T.eq(a:to_string(), "42")
  end)
  T.it("returns nil,errmsg for empty string", function()
    local v, err = bigint.new("")
    T.eq(v, nil)
    T.ok(err)
  end)
  T.it("returns nil,errmsg for non-digit string", function()
    local v, err = bigint.new("abc")
    T.eq(v, nil)
    T.ok(err)
  end)
  T.it("returns nil,errmsg for bad type", function()
    local v, err = bigint.new(true)
    T.eq(v, nil)
    T.ok(err)
  end)
  T.it("handles very large number string", function()
    local s = "9" .. ("0"):rep(99)
    local a = bigint.new(s)
    T.eq(a:to_string(), s)
  end)
end)

