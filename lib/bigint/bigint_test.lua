-- ── Edge cases ───────────────────────────────────────────────────────────────

T.describe("edge cases", function()
  T.it("negative zero normalizes to zero", function()
    local a = bigint.new("-0")
    T.eq(a:to_string(), "0")
    T.eq(a:sign(), 0)
    T.ok(a:is_zero())
  end)
  T.it("one", function()
    T.eq(bigint.new(1):to_string(), "1")
  end)
  T.it("negative one", function()
    T.eq(bigint.new(-1):to_string(), "-1")
  end)
  T.it("add identity", function()
    local a = bigint.new("99999999999999999999")
    T.eq(a:add(bigint.new(0)):to_string(), a:to_string())
  end)
  T.it("mul identity", function()
    local a = bigint.new("99999999999999999999")
    T.eq(a:mul(bigint.new(1)):to_string(), a:to_string())
  end)
  T.it("sub self", function()
    local a = bigint.new("12345678901234567890")
    T.eq(a:sub(a):to_string(), "0")
  end)
  T.it("div self", function()
    local a = bigint.new("12345678901234567890")
    T.eq(a:div(a):to_string(), "1")
  end)
  T.it("constants are immutable-ish", function()
    -- ZERO and ONE should remain unchanged after operations
    T.eq(bigint.ZERO:to_string(), "0")
    T.eq(bigint.ONE:to_string(), "1")
  end)
  T.it("many chunk boundary", function()
    -- 7 digits per chunk: 28-digit number = 4 chunks
    local a = bigint.new("1234567890123456789012345678")
    local b = bigint.new("8765432109876543210987654322")
    T.eq(a:add(b):to_string(), "10000000000000000000000000000")
  end)
  T.it("large multiplication result", function()
    local a = bigint.new(2):pow(128)
    T.eq(a:to_string(), "340282366920938463463374607431768211456")
  end)
end)
