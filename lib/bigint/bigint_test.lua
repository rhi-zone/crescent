-- ── GCD / LCM ────────────────────────────────────────────────────────────────

T.describe("gcd", function()
  T.it("gcd(12, 8) = 4", function()
    T.eq(bigint.gcd(bigint.new(12), bigint.new(8)):to_string(), "4")
  end)
  T.it("gcd(0, 5) = 5", function()
    T.eq(bigint.gcd(bigint.new(0), bigint.new(5)):to_string(), "5")
  end)
  T.it("gcd(7, 13) = 1 (coprime)", function()
    T.eq(bigint.gcd(bigint.new(7), bigint.new(13)):to_string(), "1")
  end)
  T.it("gcd ignores sign", function()
    T.eq(bigint.gcd(bigint.new(-12), bigint.new(8)):to_string(), "4")
  end)
  T.it("gcd of large numbers", function()
    local a = bigint.new("123456789012345678901234567890")
    local b = bigint.new("987654321098765432109876543210")
    local g = bigint.gcd(a, b)
    -- Verify it divides both
    T.eq(a:mod(g):to_string(), "0")
    T.eq(b:mod(g):to_string(), "0")
  end)
end)

