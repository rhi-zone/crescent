		T.ok(sql:find("AUTOINCREMENT"))
		T.ok(sql:find("NOT NULL"))
		T.ok(sql:find("UNIQUE"))
	end)

	T.it("default string with single quotes is escaped", function()
		local s = schema.new()
		s:create_table("t", function(t)
			t:text("msg"):default("it's")
		end)
		T.ok(s:to_sql()[1]:find("DEFAULT 'it''s'"))
	end)

	T.it("empty schema produces empty output", function()
		local s = schema.new()
		T.eq(#s:to_sql(), 0)
		T.eq(s:to_string(), "")
	end)

	T.it("schema operations are ordered", function()
		local s = schema.new()
		s:drop_table("a")
		s:drop_table("b")
		s:drop_table("c")
		local stmts = s:to_sql()
		T.eq(stmts[1], "DROP TABLE a")
		T.eq(stmts[2], "DROP TABLE b")
		T.eq(stmts[3], "DROP TABLE c")
	end)

	T.it("chaining multiple schema operations", function()
		local s = schema.new()
		s:drop_table("a")
		s:drop_table("b")
		s:rename_table("c", "d")
		T.eq(#s:to_sql(), 3)
	end)

	T.it("default with float", function()
		local s = schema.new()
		s:create_table("t", function(t)
			t:real("val"):default(3.14)
		end)
		T.ok(s:to_sql()[1]:find("DEFAULT 3.14"))
	end)

	T.it("default with negative number", function()
		local s = schema.new()
		s:create_table("t", function(t)
			t:integer("val"):default(-1)
		end)
		T.ok(s:to_sql()[1]:find("DEFAULT %-1"))
	end)

	T.it("table with only foreign keys (no plain columns)", function()
		local s = schema.new()
		s:create_table("join_table", function(t)
			t:foreign_key("a_id", "a", "id")
			t:foreign_key("b_id", "b", "id")
		end)
		local sql = s:to_sql()[1]
		T.ok(sql:find("a_id INTEGER"))
		T.ok(sql:find("b_id INTEGER"))
		T.ok(sql:find("FOREIGN KEY %(a_id%) REFERENCES a%(id%)"))
		T.ok(sql:find("FOREIGN KEY %(b_id%) REFERENCES b%(id%)"))
	end)

	T.it("raw SQL mixed with schema operations", function()
		local s = schema.new()
		s:raw("PRAGMA foreign_keys = ON")
		s:create_table("t", function(t) t:integer("id") end)
		s:raw("INSERT INTO t (id) VALUES (1)")
		local stmts = s:to_sql()
		T.eq(#stmts, 3)
		T.eq(stmts[1], "PRAGMA foreign_keys = ON")
		T.ok(stmts[2]:find("CREATE TABLE t"))
		T.eq(stmts[3], "INSERT INTO t (id) VALUES (1)")
	end)
