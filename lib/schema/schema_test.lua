-- ── full integration ─────────────────────────────────────────────────────────

T.describe("full schema example", function()
	T.it("matches the API example from the spec", function()
		local s = schema.new()

		s:create_table("users", function(t)
			t:integer("id"):primary_key():autoincrement()
			t:text("name"):not_null()
			t:text("email"):not_null():unique()
			t:integer("age"):default(0)
			t:real("score")
			t:blob("data")
			t:boolean("active"):default(true)
			t:timestamp("created_at"):default("CURRENT_TIMESTAMP")
			t:foreign_key("org_id", "organizations", "id")
			t:index("idx_email", "email")
			t:unique_index("idx_name_email", "name", "email")
		end)

		local stmts = s:to_sql()
		-- 1 CREATE TABLE + 2 index statements
		T.eq(#stmts, 3)

		local ct = stmts[1]
		T.ok(ct:find("CREATE TABLE users"))
		T.ok(ct:find("id INTEGER PRIMARY KEY AUTOINCREMENT"))
		T.ok(ct:find("name TEXT NOT NULL"))
		T.ok(ct:find("email TEXT NOT NULL UNIQUE"))
		T.ok(ct:find("age INTEGER DEFAULT 0"))
		T.ok(ct:find("score REAL"))
		T.ok(ct:find("data BLOB"))
		T.ok(ct:find("active BOOLEAN DEFAULT 1"))
		T.ok(ct:find("created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP"))
		T.ok(ct:find("org_id INTEGER"))
		T.ok(ct:find("FOREIGN KEY %(org_id%) REFERENCES organizations%(id%)"))

		T.eq(stmts[2], "CREATE INDEX idx_email ON users (email)")
		T.eq(stmts[3], "CREATE UNIQUE INDEX idx_name_email ON users (name, email)")
	end)

	T.it("full migration with create, alter, drop, rename", function()
		local s = schema.new()

		s:create_table("users", function(t)
			t:integer("id"):primary_key()
			t:text("name"):not_null()
		end)

		s:alter_table("users", function(t)
			t:add_column("bio", "TEXT")
			t:drop_column("name")
			t:rename_column("bio", "description")
			t:add_index("idx_desc", "description")
		end)

		s:rename_table("users", "accounts")
		s:drop_table("old_accounts")

		local stmts = s:to_sql()
		T.eq(#stmts, 7)
		T.ok(stmts[1]:find("CREATE TABLE users"))
		T.eq(stmts[2], "ALTER TABLE users ADD COLUMN bio TEXT")
		T.eq(stmts[3], "ALTER TABLE users DROP COLUMN name")
		T.eq(stmts[4], "ALTER TABLE users RENAME COLUMN bio TO description")
		T.eq(stmts[5], "CREATE INDEX idx_desc ON users (description)")
		T.eq(stmts[6], "ALTER TABLE users RENAME TO accounts")
		T.eq(stmts[7], "DROP TABLE old_accounts")
	end)

	T.it("multiple tables with foreign keys", function()
		local s = schema.new()

		s:create_table("organizations", function(t)
			t:integer("id"):primary_key():autoincrement()
			t:text("name"):not_null()
		end)

		s:create_table("users", function(t)
			t:integer("id"):primary_key():autoincrement()
			t:text("name"):not_null()
			t:foreign_key("org_id", "organizations", "id")
		end)

		s:create_table("posts", function(t)
			t:integer("id"):primary_key():autoincrement()
			t:text("title"):not_null()
			t:text("body")
			t:foreign_key("user_id", "users", "id")
		end)

		local stmts = s:to_sql()
		T.eq(#stmts, 3)
		T.ok(stmts[1]:find("CREATE TABLE organizations"))
		T.ok(stmts[2]:find("CREATE TABLE users"))
		T.ok(stmts[2]:find("FOREIGN KEY %(org_id%) REFERENCES organizations%(id%)"))
		T.ok(stmts[3]:find("CREATE TABLE posts"))
		T.ok(stmts[3]:find("FOREIGN KEY %(user_id%) REFERENCES users%(id%)"))
	end)

	T.it("to_string produces valid multi-statement SQL", function()
		local s = schema.new()
		s:create_table("t", function(t) t:integer("id"):primary_key() end)
		s:drop_table("old_t")
		local str = s:to_string()
		-- Should contain both statements separated by ;\n
		T.ok(str:find("CREATE TABLE t"))
		T.ok(str:find(";\n"))
		T.ok(str:find("DROP TABLE old_t"))
	end)
end)

