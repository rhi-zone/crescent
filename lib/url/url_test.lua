T.describe("url.join", function()
  T.it("resolves relative path with ..", function()
    T.eq(url.join("https://example.com/api/v1/", "../v2/users"),
         "https://example.com/api/v2/users")
  end)
  T.it("resolves absolute path", function()
    T.eq(url.join("https://example.com/api/v1/", "/v2/users"),
         "https://example.com/v2/users")
  end)
  T.it("resolves with query", function()
    T.eq(url.join("https://example.com/path", "?q=1"),
         "https://example.com/path?q=1")
  end)
  T.it("resolves empty reference", function()
    T.eq(url.join("https://example.com/path?q=1", ""),
         "https://example.com/path?q=1")
  end)
  T.it("resolves with fragment", function()
    T.eq(url.join("https://example.com/path", "#section"),
         "https://example.com/path#section")
  end)
  T.it("resolves full URL override", function()
    T.eq(url.join("https://example.com/path", "http://other.com/new"),
         "http://other.com/new")
  end)
  T.it("resolves sibling path", function()
    T.eq(url.join("https://example.com/a/b/c", "d"),
         "https://example.com/a/b/d")
  end)
  T.it("resolves with double ..", function()
    T.eq(url.join("https://example.com/a/b/c/d", "../../e"),
         "https://example.com/a/e")
  end)
end)

T.describe("url.resolve", function()
  -- RFC 3986 Section 5.4 reference resolution examples
  -- Base: http://a/b/c/d;p?q
  local base = "http://a/b/c/d;p?q"

  T.it("resolves g:h", function()
    T.eq(url.resolve(base, "g:h"), "g:h")
  end)
  T.it("resolves g", function()
    T.eq(url.resolve(base, "g"), "http://a/b/c/g")
  end)
  T.it("resolves ./g", function()
    T.eq(url.resolve(base, "./g"), "http://a/b/c/g")
  end)
  T.it("resolves g/", function()
    T.eq(url.resolve(base, "g/"), "http://a/b/c/g/")
  end)
  T.it("resolves /g", function()
    T.eq(url.resolve(base, "/g"), "http://a/g")
  end)
  T.it("resolves //g", function()
    T.eq(url.resolve(base, "//g"), "http://g")
  end)
  T.it("resolves ?y", function()
    T.eq(url.resolve(base, "?y"), "http://a/b/c/d;p?y")
  end)
  T.it("resolves g?y", function()
    T.eq(url.resolve(base, "g?y"), "http://a/b/c/g?y")
  end)
  T.it("resolves #s", function()
    T.eq(url.resolve(base, "#s"), "http://a/b/c/d;p?q#s")
  end)
  T.it("resolves g#s", function()
    T.eq(url.resolve(base, "g#s"), "http://a/b/c/g#s")
  end)
  T.it("resolves g?y#s", function()
    T.eq(url.resolve(base, "g?y#s"), "http://a/b/c/g?y#s")
  end)
  T.it("resolves ;x", function()
    T.eq(url.resolve(base, ";x"), "http://a/b/c/;x")
  end)
  T.it("resolves g;x", function()
    T.eq(url.resolve(base, "g;x"), "http://a/b/c/g;x")
  end)
  T.it("resolves g;x?y#s", function()
    T.eq(url.resolve(base, "g;x?y#s"), "http://a/b/c/g;x?y#s")
  end)
  T.it("resolves empty string", function()
    T.eq(url.resolve(base, ""), "http://a/b/c/d;p?q")
  end)
  T.it("resolves ../", function()
    T.eq(url.resolve(base, "../"), "http://a/b/")
  end)
  T.it("resolves ../g", function()
    T.eq(url.resolve(base, "../g"), "http://a/b/g")
  end)
  T.it("resolves ../../", function()
    T.eq(url.resolve(base, "../../"), "http://a/")
  end)
  T.it("resolves ../../g", function()
    T.eq(url.resolve(base, "../../g"), "http://a/g")
  end)
end)

