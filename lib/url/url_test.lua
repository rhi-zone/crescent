T.describe("url.parse", function()
  T.it("parses full URL", function()
    local u = url.parse("https://user:pass@example.com:8080/path?q=1&r=2#frag")
    T.eq(u.scheme, "https")
    T.eq(u.userinfo, "user:pass")
    T.eq(u.host, "example.com")
    T.eq(u.port, 8080)
    T.eq(u.path, "/path")
    T.eq(u.query, "q=1&r=2")
    T.eq(u.fragment, "frag")
  end)
  T.it("parses http URL", function()
    local u = url.parse("http://example.com/")
    T.eq(u.scheme, "http")
    T.eq(u.host, "example.com")
    T.eq(u.path, "/")
  end)
  T.it("parses URL without port", function()
    local u = url.parse("https://example.com/path")
    T.eq(u.scheme, "https")
    T.eq(u.host, "example.com")
    T.eq(u.port, nil)
    T.eq(u.path, "/path")
  end)
  T.it("parses URL without path", function()
    local u = url.parse("https://example.com")
    T.eq(u.scheme, "https")
    T.eq(u.host, "example.com")
    T.eq(u.path, "")
  end)
  T.it("parses URL without query", function()
    local u = url.parse("https://example.com/path#frag")
    T.eq(u.query, nil)
    T.eq(u.fragment, "frag")
  end)
  T.it("parses URL without fragment", function()
    local u = url.parse("https://example.com/path?q=1")
    T.eq(u.fragment, nil)
    T.eq(u.query, "q=1")
  end)
  T.it("parses URL with userinfo", function()
    local u = url.parse("ftp://admin@host.com/files")
    T.eq(u.userinfo, "admin")
    T.eq(u.host, "host.com")
  end)
  T.it("parses URL with empty query", function()
    local u = url.parse("http://example.com/?")
    T.eq(u.query, "")
  end)
  T.it("parses URL with empty fragment", function()
    local u = url.parse("http://example.com/#")
    T.eq(u.fragment, "")
  end)
  T.it("lowercases scheme", function()
    local u = url.parse("HTTPS://Example.com")
    T.eq(u.scheme, "https")
  end)
  T.it("parses protocol-relative URL", function()
    local u = url.parse("//example.com/path")
    T.eq(u.scheme, nil)
    T.eq(u.host, "example.com")
    T.eq(u.path, "/path")
  end)
  T.it("parses just a path", function()
    local u = url.parse("/path/to/resource")
    T.eq(u.scheme, nil)
    T.eq(u.host, nil)
    T.eq(u.path, "/path/to/resource")
  end)
  T.it("parses relative path", function()
    local u = url.parse("path/to/resource")
    T.eq(u.scheme, nil)
    T.eq(u.host, nil)
    T.eq(u.path, "path/to/resource")
  end)
  T.it("parses empty string", function()
    local u = url.parse("")
    T.eq(u.scheme, nil)
    T.eq(u.host, nil)
    T.eq(u.path, "")
  end)
  T.it("returns error for non-string", function()
    local u, err = url.parse(123)
    T.eq(u, nil)
    T.ok(err)
  end)
  T.it("parses IPv6 host", function()
    local u = url.parse("http://[::1]:8080/path")
    T.eq(u.host, "[::1]")
    T.eq(u.port, 8080)
    T.eq(u.path, "/path")
  end)
  T.it("parses IPv6 without port", function()
    local u = url.parse("http://[2001:db8::1]/path")
    T.eq(u.host, "[2001:db8::1]")
    T.eq(u.port, nil)
  end)
  T.it("parses data URI", function()
    local u = url.parse("data:text/html,<h1>Hello</h1>")
    T.eq(u.scheme, "data")
    T.eq(u.path, "text/html,<h1>Hello</h1>")
  end)
  T.it("parses mailto URI", function()
    local u = url.parse("mailto:user@example.com")
    T.eq(u.scheme, "mailto")
    T.eq(u.path, "user@example.com")
  end)
  T.it("parses URL with encoded path", function()
    local u = url.parse("http://example.com/path%20with%20spaces")
    T.eq(u.path, "/path%20with%20spaces")
  end)
  T.it("parses URL with multiple query params", function()
    local u = url.parse("http://example.com/?a=1&b=2&c=3")
    T.eq(u.query, "a=1&b=2&c=3")
  end)
  T.it("parses ws URL", function()
    local u = url.parse("ws://localhost:3000/socket")
    T.eq(u.scheme, "ws")
    T.eq(u.host, "localhost")
    T.eq(u.port, 3000)
  end)
  T.it("parses file URL", function()
    local u = url.parse("file:///home/user/file.txt")
    T.eq(u.scheme, "file")
    T.eq(u.host, "")
    T.eq(u.path, "/home/user/file.txt")
  end)
end)

