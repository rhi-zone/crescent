T.describe("url.normalize", function()
  T.it("lowercases scheme and host", function()
    T.eq(url.normalize("HTTPS://Example.COM/path"), "https://example.com/path")
  end)
  T.it("removes default https port", function()
    T.eq(url.normalize("https://example.com:443/path"), "https://example.com/path")
  end)
  T.it("removes default http port", function()
    T.eq(url.normalize("http://example.com:80/"), "http://example.com/")
  end)
  T.it("keeps non-default port", function()
    T.eq(url.normalize("http://example.com:8080/"), "http://example.com:8080/")
  end)
  T.it("removes dot segments", function()
    T.eq(url.normalize("https://example.com/a/../b/./c"), "https://example.com/b/c")
  end)
  T.it("normalizes complex dot segments", function()
    T.eq(url.normalize("https://Example.COM:443/a/../b/./c"), "https://example.com/b/c")
  end)
  T.it("adds slash for authority without path", function()
    T.eq(url.normalize("http://example.com"), "http://example.com/")
  end)
  T.it("decodes unreserved percent-encoded chars in path", function()
    T.eq(url.normalize("http://example.com/%61%62%63"), "http://example.com/abc")
  end)
  T.it("preserves reserved percent-encoded chars", function()
    T.eq(url.normalize("http://example.com/a%2Fb"), "http://example.com/a%2Fb")
  end)
  T.it("uppercases hex in percent-encoding", function()
    T.eq(url.normalize("http://example.com/a%2fb"), "http://example.com/a%2Fb")
  end)
end)

-- ============================================================
-- Edge cases
-- ============================================================

T.describe("url edge cases", function()
  T.it("handles URL with only scheme", function()
    local u = url.parse("http:")
    T.eq(u.scheme, "http")
    T.eq(u.path, "")
  end)
  T.it("handles URL with only query", function()
    local u = url.parse("?query=1")
    T.eq(u.query, "query=1")
    T.eq(u.path, "")
  end)
  T.it("handles URL with only fragment", function()
    local u = url.parse("#fragment")
    T.eq(u.fragment, "fragment")
    T.eq(u.path, "")
  end)
  T.it("handles consecutive slashes in path", function()
    local u = url.parse("http://example.com//a//b")
    T.eq(u.path, "//a//b")
  end)
  T.it("handles port 0", function()
    local u = url.parse("http://example.com:0/path")
    T.eq(u.port, 0)
  end)
  T.it("handles large port", function()
    local u = url.parse("http://example.com:65535/path")
    T.eq(u.port, 65535)
  end)
  T.it("parses URL with @ in path", function()
    local u = url.parse("http://example.com/user@host")
    T.eq(u.host, "example.com")
    T.eq(u.path, "/user@host")
  end)
  T.it("preserves query encoding", function()
    local u = url.parse("http://example.com/?q=hello%20world")
    T.eq(u.query, "q=hello%20world")
  end)
  T.it("handles very long URL", function()
    local long_path = "/" .. string.rep("a", 10000)
    local u = url.parse("http://example.com" .. long_path)
    T.eq(u.path, long_path)
  end)
end)

