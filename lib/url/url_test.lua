T.describe("url.build", function()
  T.it("builds full URL", function()
    local s = url.build({
      scheme = "https", userinfo = "user:pass",
      host = "example.com", port = 8080,
      path = "/path", query = "q=1", fragment = "frag"
    })
    T.eq(s, "https://user:pass@example.com:8080/path?q=1#frag")
  end)
  T.it("builds simple URL", function()
    T.eq(url.build({ scheme = "https", host = "example.com", path = "/api", query = "k=v" }),
         "https://example.com/api?k=v")
  end)
  T.it("builds URL without optional parts", function()
    T.eq(url.build({ scheme = "http", host = "localhost" }), "http://localhost")
  end)
  T.it("builds protocol-relative URL", function()
    T.eq(url.build({ host = "example.com", path = "/path" }), "//example.com/path")
  end)
  T.it("builds bare path", function()
    T.eq(url.build({ path = "/just/a/path" }), "/just/a/path")
  end)
  T.it("builds with fragment only", function()
    T.eq(url.build({ path = "", fragment = "top" }), "#top")
  end)
  T.it("round-trips with parse", function()
    local original = "https://user:pass@example.com:8080/path?q=1&r=2#frag"
    local u = url.parse(original)
    T.eq(url.build(u), original)
  end)
  T.it("round-trips http URL", function()
    local original = "http://example.com/"
    T.eq(url.build(url.parse(original)), original)
  end)
  T.it("round-trips complex query", function()
    local original = "https://search.example.com/q?term=lua+jit&page=2&sort=relevance#results"
    T.eq(url.build(url.parse(original)), original)
  end)
end)

