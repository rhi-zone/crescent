local url = require("lib.url")
local T = require("lib.test.assert")

-- ============================================================
-- Percent encoding
-- ============================================================

T.describe("url.encode", function()
  T.it("passes through unreserved characters", function()
    T.eq(url.encode("abcXYZ0123456789-._~"), "abcXYZ0123456789-._~")
  end)
  T.it("encodes spaces", function()
    T.eq(url.encode("hello world"), "hello%20world")
  end)
  T.it("encodes special characters", function()
    T.eq(url.encode("hello world!"), "hello%20world%21")
  end)
  T.it("encodes empty string", function()
    T.eq(url.encode(""), "")
  end)
  T.it("encodes all bytes", function()
    T.eq(url.encode("\0\1\255"), "%00%01%FF")
  end)
  T.it("encodes unicode bytes", function()
    -- UTF-8 for 'e' with acute: \xC3\xA9
    T.eq(url.encode("\xC3\xA9"), "%C3%A9")
  end)
  T.it("encodes slash", function()
    T.eq(url.encode("/path/to"), "%2Fpath%2Fto")
  end)
  T.it("encodes query special chars", function()
    T.eq(url.encode("a=1&b=2"), "a%3D1%26b%3D2")
  end)
end)

T.describe("url.decode", function()
  T.it("decodes percent-encoded", function()
    T.eq(url.decode("hello%20world"), "hello world")
  end)
  T.it("decodes plus as space", function()
    T.eq(url.decode("hello+world"), "hello world")
  end)
  T.it("decodes empty string", function()
    T.eq(url.decode(""), "")
  end)
  T.it("decodes lowercase hex", function()
    T.eq(url.decode("%c3%a9"), "\xC3\xA9")
  end)
  T.it("decodes uppercase hex", function()
    T.eq(url.decode("%C3%A9"), "\xC3\xA9")
  end)
  T.it("passes through plain text", function()
    T.eq(url.decode("hello"), "hello")
  end)
  T.it("round-trips with encode", function()
    local original = "hello world! /path?q=1&r=2#frag"
    T.eq(url.decode(url.encode(original)), original)
  end)
end)

-- ============================================================
-- Query string parsing
-- ============================================================

T.describe("url.parse_query", function()
  T.it("parses simple params", function()
    local q = url.parse_query("a=1&b=2")
    T.eq(q.a, "1")
    T.eq(q.b, "2")
  end)
  T.it("parses encoded values", function()
    local q = url.parse_query("msg=hello%20world")
    T.eq(q.msg, "hello world")
  end)
  T.it("parses plus as space", function()
    local q = url.parse_query("c=hello+world")
    T.eq(q.c, "hello world")
  end)
  T.it("parses empty value", function()
    local q = url.parse_query("key=")
    T.eq(q.key, "")
  end)
  T.it("parses key without value", function()
    local q = url.parse_query("key")
    T.eq(q.key, "")
  end)
  T.it("parses empty string", function()
    local q = url.parse_query("")
    T.eq(next(q), nil)
  end)
  T.it("parses nil", function()
    local q = url.parse_query(nil)
    T.eq(next(q), nil)
  end)
  T.it("parses semicolon separator", function()
    local q = url.parse_query("a=1;b=2")
    T.eq(q.a, "1")
    T.eq(q.b, "2")
  end)
  T.it("last value wins for duplicate keys", function()
    local q = url.parse_query("a=1&a=2")
    T.eq(q.a, "2")
  end)
  T.it("parses encoded keys", function()
    local q = url.parse_query("hello%20world=yes")
    T.eq(q["hello world"], "yes")
  end)
  T.it("parses multiple params", function()
    local q = url.parse_query("a=1&b=2&c=3&d=4&e=5")
    T.eq(q.a, "1")
    T.eq(q.e, "5")
  end)
end)

T.describe("url.build_query", function()
  T.it("builds simple query", function()
    local qs = url.build_query({ a = "1", b = "2" })
    T.eq(qs, "a=1&b=2")
  end)
  T.it("encodes special characters", function()
    local qs = url.build_query({ msg = "hello world" })
    T.eq(qs, "msg=hello%20world")
  end)
  T.it("builds empty table", function()
    T.eq(url.build_query({}), "")
  end)
  T.it("round-trips with parse_query", function()
    local orig = { x = "10", y = "20" }
    local q = url.parse_query(url.build_query(orig))
    T.eq(q.x, "10")
    T.eq(q.y, "20")
  end)
end)

