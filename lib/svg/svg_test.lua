T.describe("Path builder", function()
  T.it("M produces moveto", function()
    local p = SVG.path()
    p:M(10, 20)
    T.eq(p:to_string(), "M 10 20")
  end)

  T.it("L produces lineto", function()
    local p = SVG.path()
    p:L(5, 10)
    T.eq(p:to_string(), "L 5 10")
  end)

  T.it("Z produces closepath", function()
    local p = SVG.path()
    p:Z()
    T.eq(p:to_string(), "Z")
  end)

  T.it("chained M L Z", function()
    local p = SVG.path()
    p:M(0, 0):L(100, 0):L(100, 100):Z()
    T.eq(p:to_string(), "M 0 0 L 100 0 L 100 100 Z")
  end)

  T.it("C cubic bezier", function()
    local p = SVG.path()
    p:C(10, 20, 30, 40, 50, 60)
    T.eq(p:to_string(), "C 10 20 30 40 50 60")
  end)

  T.it("Q quadratic bezier", function()
    local p = SVG.path()
    p:Q(10, 20, 50, 60)
    T.eq(p:to_string(), "Q 10 20 50 60")
  end)

  T.it("S smooth cubic bezier", function()
    local p = SVG.path()
    p:S(30, 40, 50, 60)
    T.eq(p:to_string(), "S 30 40 50 60")
  end)

  T.it("A arc", function()
    local p = SVG.path()
    p:A(10, 20, 0, 1, 0, 50, 60)
    T.eq(p:to_string(), "A 10 20 0 1 0 50 60")
  end)

  T.it("H horizontal lineto", function()
    local p = SVG.path()
    p:H(42)
    T.eq(p:to_string(), "H 42")
  end)

  T.it("V vertical lineto", function()
    local p = SVG.path()
    p:V(99)
    T.eq(p:to_string(), "V 99")
  end)

  T.it("add_path embeds d string", function()
    local doc = SVG.new(100, 100)
    local p = SVG.path()
    p:M(0, 0):L(50, 50):Z()
    doc:add_path(p, {stroke = "black"})
    local s = doc:to_string()
    T.ok(s:find('d="M 0 0 L 50 50 Z"', 1, true) ~= nil, "add_path d attr")
    T.ok(s:find('stroke="black"', 1, true) ~= nil, "add_path extra attr")
  end)
end)

