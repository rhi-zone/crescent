-- ---------------------------------------------------------------------------
T.describe("SVG.new / to_string basics", function()
  T.it("produces <svg> and </svg>", function()
    local doc = SVG.new(100, 100)
    local s = doc:to_string()
    T.ok(s:find("<svg", 1, true) ~= nil, "has <svg")
    T.ok(s:find("</svg>", 1, true) ~= nil, "has </svg>")
  end)

  T.it("includes width and height attributes", function()
    local doc = SVG.new(200, 150)
    local s = doc:to_string()
    T.ok(s:find('width="200"', 1, true) ~= nil, "width attr")
    T.ok(s:find('height="150"', 1, true) ~= nil, "height attr")
  end)

  T.it("includes xmlns by default", function()
    local doc = SVG.new(100, 100)
    local s = doc:to_string()
    T.ok(s:find("http://www.w3.org/2000/svg", 1, true) ~= nil, "xmlns present")
  end)

  T.it("omits xmlns when opts.xmlns=false", function()
    local doc = SVG.new(100, 100, {xmlns = false})
    local s = doc:to_string()
    T.ok(s:find("http://www.w3.org/2000/svg", 1, true) == nil, "xmlns absent")
  end)

  T.it("includes viewBox when provided", function()
    local doc = SVG.new(100, 100, {viewBox = "0 0 100 100"})
    local s = doc:to_string()
    T.ok(s:find('viewBox="0 0 100 100"', 1, true) ~= nil, "viewBox attr")
  end)

  T.it("includes XML declaration", function()
    local doc = SVG.new(10, 10)
    local s = doc:to_string()
    T.ok(s:find("<?xml", 1, true) ~= nil, "xml decl")
  end)
end)

