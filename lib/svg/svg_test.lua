T.describe("group", function()
  T.it("wraps children in <g>", function()
    local doc = SVG.new(100, 100)
    local g = doc:group({fill = "blue"})
    g:rect(0, 0, 10, 10)
    g:circle(5, 5, 3)
    local s = doc:to_string()
    T.ok(s:find("<g", 1, true) ~= nil, "<g tag")
    T.ok(s:find("</g>", 1, true) ~= nil, "</g> close")
    T.ok(s:find('fill="blue"', 1, true) ~= nil, "fill attr on group")
    T.ok(s:find("<rect", 1, true) ~= nil, "rect inside group")
    T.ok(s:find("<circle", 1, true) ~= nil, "circle inside group")
  end)

  T.it("callback form (group with fn) works", function()
    local doc = SVG.new(100, 100)
    doc:group({transform = "translate(10,10)"}, function(g)
      g:rect(0, 0, 5, 5)
    end)
    local s = doc:to_string()
    T.ok(s:find("<g", 1, true) ~= nil, "<g present")
    T.ok(s:find("<rect", 1, true) ~= nil, "rect inside")
    T.ok(s:find('transform="translate(10,10)"', 1, true) ~= nil, "transform attr")
  end)

  T.it("nested groups", function()
    local doc = SVG.new(100, 100)
    local g = doc:group()
    local inner = g:group({id = "inner"})
    inner:line(0, 0, 10, 10)
    local s = doc:to_string()
    T.ok(s:find('id="inner"', 1, true) ~= nil, "inner group id")
    T.ok(s:find("<line", 1, true) ~= nil, "line inside inner group")
  end)
end)

