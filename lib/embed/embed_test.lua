T.describe("embed search - filter", function()
  T.it("filters by metadata predicate", function()
    local idx = embed.index({ dims = 2, metric = "cosine" })
    idx:add("a", vec.new({1, 0}), { tag = "keep" })
    idx:add("b", vec.new({1, 0.01}), { tag = "exclude" })
    idx:add("c", vec.new({0.9, 0.1}), { tag = "keep" })

    local results = idx:search(vec.new({1, 0}), 10, {
      filter = function(meta) return meta and meta.tag == "keep" end,
    })
    T.eq(#results, 2)
    T.eq(results[1].id, "a")
    T.eq(results[2].id, "c")
  end)

  T.it("filter excludes all returns empty", function()
    local idx = embed.index({ dims = 2, metric = "cosine" })
    idx:add("a", vec.new({1, 0}))
    local results = idx:search(vec.new({1, 0}), 10, {
      filter = function() return false end,
    })
    T.eq(#results, 0)
  end)
end)

T.describe("embed search - ordering", function()
  T.it("results are sorted most similar first", function()
    local idx = embed.index({ dims = 2, metric = "cosine" })
    idx:add("a", vec.new({1, 0}))
    idx:add("b", vec.new({0.7, 0.7}))
    idx:add("c", vec.new({0, 1}))
    idx:add("d", vec.new({-1, 0}))

    local results = idx:search(vec.new({1, 0}), 4)
    for i = 1, #results - 1 do
      T.ok(results[i].score >= results[i + 1].score,
        "result " .. i .. " score >= result " .. (i + 1) .. " score")
    end
  end)
end)

T.describe("embed serialize/deserialize", function()
  T.it("roundtrips data correctly", function()
    local idx = embed.index({ dims = 3, metric = "dot" })
    idx:add("x", vec.new({1, 2, 3}), { tag = "first" })
    idx:add("y", vec.new({4, 5, 6}), { tag = "second" })

    local data = idx:serialize()
    T.eq(data.dims, 3)
    T.eq(data.metric, "dot")
    T.eq(#data.items, 2)
    T.eq(data.items[1].id, "x")
    T.eq(data.items[2].id, "y")
    T.eq(data.items[1].metadata.tag, "first")

    local idx2 = embed.deserialize(data)
    T.eq(idx2:count(), 2)
    local entry = idx2:get("x")
    T.ok(entry ~= nil, "x exists in deserialized index")
    T.eq(entry.metadata.tag, "first")
    approx(vec.get(entry.vector, 1), 1)
    approx(vec.get(entry.vector, 2), 2)
    approx(vec.get(entry.vector, 3), 3)
  end)

  T.it("deserialized index searches correctly", function()
    local idx = embed.index({ dims = 2, metric = "cosine" })
    idx:add("a", vec.new({1, 0}))
    idx:add("b", vec.new({0, 1}))

    local data = idx:serialize()
    local idx2 = embed.deserialize(data)
    local results = idx2:search(vec.new({1, 0}), 2)
    T.eq(results[1].id, "a")
    T.eq(results[2].id, "b")
  end)

  T.it("preserves insertion order", function()
    local idx = embed.index({ dims = 2 })
    idx:add("c", vec.new({1, 0}))
    idx:add("a", vec.new({0, 1}))
    idx:add("b", vec.new({1, 1}))
    local data = idx:serialize()
    T.eq(data.items[1].id, "c")
    T.eq(data.items[2].id, "a")
    T.eq(data.items[3].id, "b")

    local idx2 = embed.deserialize(data)
    local ids = idx2:ids()
    T.eq(ids[1], "c")
    T.eq(ids[2], "a")
    T.eq(ids[3], "b")
  end)

  T.it("rejects missing dims", function()
    local idx, err = embed.deserialize({ metric = "cosine", items = {} })
    T.eq(idx, nil)
    T.ok(err ~= nil, "error returned")
  end)

  T.it("vectors stored as plain tables in serialized form", function()
    local idx = embed.index({ dims = 2 })
    idx:add("a", vec.new({3.5, 7.5}))
    local data = idx:serialize()
    -- vector should be a plain Lua table, not a Vec object
    local v = data.items[1].vector
    T.eq(type(v), "table")
    T.eq(#v, 2)
    approx(v[1], 3.5)
    approx(v[2], 7.5)
  end)
end)

T.describe("embed higher dimensions", function()
  T.it("works with 384-dim vectors", function()
    local idx = embed.index({ dims = 384, metric = "cosine" })
    local v1 = make_vec(384, 1.0)
    local v2 = make_vec(384, 2.0)
    local v3 = make_vec(384, 1.01)  -- very close to v1

    idx:add("a", v1)
    idx:add("b", v2)
    idx:add("c", v3)

    local results = idx:search(v1, 3)
    T.eq(#results, 3)
    -- v1 itself is most similar, then v3 (very close), then v2
    T.eq(results[1].id, "a")
    T.eq(results[2].id, "c")
    T.eq(results[3].id, "b")
    approx(results[1].score, 1.0, 1e-6)
  end)
end)

T.describe("embed edge cases", function()
  T.it("search with k=0 returns empty", function()
    local idx = embed.index({ dims = 2, metric = "cosine" })
    idx:add("a", vec.new({1, 0}))
    local results = idx:search(vec.new({1, 0}), 0)
    T.eq(#results, 0)
  end)

  T.it("add and remove same id multiple times", function()
    local idx = embed.index({ dims = 2 })
    idx:add("a", vec.new({1, 0}))
    idx:remove("a")
    T.eq(idx:count(), 0)
    idx:add("a", vec.new({0, 1}))
    T.eq(idx:count(), 1)
    approx(vec.get(idx:get("a").vector, 2), 1)
  end)

  T.it("remove then add preserves correct order", function()
    local idx = embed.index({ dims = 2 })
    idx:add("a", vec.new({1, 0}))
    idx:add("b", vec.new({0, 1}))
    idx:add("c", vec.new({1, 1}))
    idx:remove("b")
    idx:add("d", vec.new({0.5, 0.5}))
    local ids = idx:ids()
    T.eq(#ids, 3)
    T.eq(ids[1], "a")
    T.eq(ids[2], "c")
    T.eq(ids[3], "d")
  end)
end)
