if not package.path:find("./?/init.lua", 1, true) then package.path = "./?/init.lua;" .. package.path end

local T = require("lib.test.assert")
local embed = require("lib.embed")
local vec = require("lib.vec")

local function approx(a, b, tol)
  tol = tol or 1e-6
  T.ok(math.abs(a - b) < tol, "expected " .. a .. " ~ " .. b)
end

-- Helper: make a simple vector of given dimension with a pattern
local function make_vec(dims, base)
  local t = {}
  for i = 1, dims do t[i] = base + i * 0.1 end
  return vec.new(t)
end

T.describe("embed.index creation", function()
  T.it("creates an index with defaults", function()
    local idx = embed.index({ dims = 3 })
    T.ok(idx ~= nil, "index created")
    T.eq(idx:count(), 0)
  end)

  T.it("creates an index with explicit metric", function()
    local idx = embed.index({ dims = 3, metric = "euclidean" })
    T.ok(idx ~= nil, "index created with euclidean")
  end)

  T.it("rejects missing dims", function()
    local idx, err = embed.index({ dims = 0 })
    T.eq(idx, nil)
    T.ok(err ~= nil, "error returned")
  end)

  T.it("rejects invalid metric", function()
    local idx, err = embed.index({ dims = 3, metric = "manhattan" })
    T.eq(idx, nil)
    T.ok(err ~= nil, "error returned for bad metric")
  end)
end)

T.describe("embed add and get", function()
  T.it("adds a vector and retrieves it", function()
    local idx = embed.index({ dims = 3 })
    local v = vec.new({1, 2, 3})
    local ok = idx:add("a", v, { title = "hello" })
    T.eq(ok, true)
    T.eq(idx:count(), 1)
    local entry = idx:get("a")
    T.ok(entry ~= nil, "entry found")
    T.eq(entry.id, "a")
    T.eq(entry.metadata.title, "hello")
    approx(vec.get(entry.vector, 1), 1)
    approx(vec.get(entry.vector, 2), 2)
    approx(vec.get(entry.vector, 3), 3)
  end)

  T.it("returns nil for missing id", function()
    local idx = embed.index({ dims = 3 })
    T.eq(idx:get("nope"), nil)
  end)

  T.it("rejects dimension mismatch on add", function()
    local idx = embed.index({ dims = 3 })
    local v = vec.new({1, 2})
    local ok, err = idx:add("a", v)
    T.eq(ok, nil)
    T.ok(err:find("mismatch") ~= nil, "error mentions mismatch")
  end)

  T.it("adds without metadata", function()
    local idx = embed.index({ dims = 2 })
    local ok = idx:add("x", vec.new({1, 0}))
    T.eq(ok, true)
    local entry = idx:get("x")
    T.eq(entry.metadata, nil)
  end)

  T.it("duplicate id overwrites", function()
    local idx = embed.index({ dims = 2 })
    idx:add("a", vec.new({1, 0}), { v = 1 })
    idx:add("a", vec.new({0, 1}), { v = 2 })
    T.eq(idx:count(), 1)
    local entry = idx:get("a")
    T.eq(entry.metadata.v, 2)
    approx(vec.get(entry.vector, 1), 0)
    approx(vec.get(entry.vector, 2), 1)
  end)
end)

T.describe("embed batch add", function()
  T.it("adds multiple vectors", function()
    local idx = embed.index({ dims = 2 })
    local ok = idx:add_batch({
      { id = "a", vector = vec.new({1, 0}), metadata = { n = 1 } },
      { id = "b", vector = vec.new({0, 1}), metadata = { n = 2 } },
      { id = "c", vector = vec.new({1, 1}) },
    })
    T.eq(ok, true)
    T.eq(idx:count(), 3)
    T.eq(idx:get("a").metadata.n, 1)
    T.eq(idx:get("b").metadata.n, 2)
    T.eq(idx:get("c").metadata, nil)
  end)

  T.it("rejects batch with dimension mismatch", function()
    local idx = embed.index({ dims = 2 })
    local ok, err = idx:add_batch({
      { id = "a", vector = vec.new({1, 0}) },
      { id = "b", vector = vec.new({1, 2, 3}) },
    })
    T.eq(ok, nil)
    T.ok(err:find("item 2") ~= nil, "error mentions item index")
  end)
end)

T.describe("embed remove", function()
  T.it("removes an existing entry", function()
    local idx = embed.index({ dims = 2 })
    idx:add("a", vec.new({1, 0}))
    idx:add("b", vec.new({0, 1}))
    T.eq(idx:count(), 2)
    local ok = idx:remove("a")
    T.eq(ok, true)
    T.eq(idx:count(), 1)
    T.eq(idx:get("a"), nil)
    T.ok(idx:get("b") ~= nil, "b still exists")
  end)

  T.it("returns false for missing id", function()
    local idx = embed.index({ dims = 2 })
    T.eq(idx:remove("nope"), false)
  end)

  T.it("removed entry excluded from search", function()
    local idx = embed.index({ dims = 2, metric = "cosine" })
    idx:add("a", vec.new({1, 0}))
    idx:add("b", vec.new({0, 1}))
    idx:remove("a")
    local results = idx:search(vec.new({1, 0}), 5)
    T.eq(#results, 1)
    T.eq(results[1].id, "b")
  end)
end)

T.describe("embed ids", function()
  T.it("lists all ids", function()
    local idx = embed.index({ dims = 2 })
    idx:add("c", vec.new({1, 0}))
    idx:add("a", vec.new({0, 1}))
    idx:add("b", vec.new({1, 1}))
    local ids = idx:ids()
    T.eq(#ids, 3)
    -- insertion order preserved
    T.eq(ids[1], "c")
    T.eq(ids[2], "a")
    T.eq(ids[3], "b")
  end)

  T.it("empty index returns empty list", function()
    local idx = embed.index({ dims = 2 })
    T.eq(#idx:ids(), 0)
  end)
end)

T.describe("embed search - cosine", function()
  T.it("finds nearest by cosine similarity", function()
    local idx = embed.index({ dims = 2, metric = "cosine" })
    idx:add("right", vec.new({1, 0}))
    idx:add("up", vec.new({0, 1}))
    idx:add("diag", vec.new({1, 1}))

    local results = idx:search(vec.new({1, 0.1}), 3)
    T.eq(#results, 3)
    -- "right" should be most similar to {1, 0.1}
    T.eq(results[1].id, "right")
    -- "diag" should be second
    T.eq(results[2].id, "diag")
    -- "up" should be least similar
    T.eq(results[3].id, "up")
  end)

  T.it("returns scores between -1 and 1 for cosine", function()
    local idx = embed.index({ dims = 2, metric = "cosine" })
    idx:add("a", vec.new({1, 0}))
    idx:add("b", vec.new({-1, 0}))
    local results = idx:search(vec.new({1, 0}), 2)
    T.ok(results[1].score > 0.99, "identical direction ~ 1.0")
    T.ok(results[2].score < -0.99, "opposite direction ~ -1.0")
  end)

  T.it("respects k limit", function()
    local idx = embed.index({ dims = 2, metric = "cosine" })
    idx:add("a", vec.new({1, 0}))
    idx:add("b", vec.new({0, 1}))
    idx:add("c", vec.new({1, 1}))
    local results = idx:search(vec.new({1, 0}), 1)
    T.eq(#results, 1)
    T.eq(results[1].id, "a")
  end)

  T.it("k larger than count returns all", function()
    local idx = embed.index({ dims = 2, metric = "cosine" })
    idx:add("a", vec.new({1, 0}))
    local results = idx:search(vec.new({1, 0}), 10)
    T.eq(#results, 1)
  end)
end)

T.describe("embed search - euclidean", function()
  T.it("finds nearest by euclidean distance", function()
    local idx = embed.index({ dims = 2, metric = "euclidean" })
    idx:add("origin", vec.new({0, 0}))
    idx:add("near", vec.new({1, 0}))
    idx:add("far", vec.new({10, 10}))

    local results = idx:search(vec.new({0.9, 0}), 3)
    T.eq(#results, 3)
    -- "near" is closest to {0.9, 0} (dist 0.1)
    T.eq(results[1].id, "near")
    -- "origin" is next (dist 0.9)
    T.eq(results[2].id, "origin")
    T.eq(results[3].id, "far")
  end)

  T.it("scores are negative distances", function()
    local idx = embed.index({ dims = 2, metric = "euclidean" })
    idx:add("a", vec.new({0, 0}))
    local results = idx:search(vec.new({3, 4}), 1)
    approx(results[1].score, -5.0)
  end)
end)

T.describe("embed search - dot product", function()
  T.it("finds nearest by dot product", function()
    local idx = embed.index({ dims = 2, metric = "dot" })
    idx:add("big", vec.new({10, 10}))
    idx:add("small", vec.new({1, 1}))
    idx:add("neg", vec.new({-5, -5}))

    local results = idx:search(vec.new({1, 1}), 3)
    T.eq(#results, 3)
    T.eq(results[1].id, "big")
    T.eq(results[2].id, "small")
    T.eq(results[3].id, "neg")
  end)

  T.it("dot product scores match vec.dot", function()
    local idx = embed.index({ dims = 3, metric = "dot" })
    local v1 = vec.new({1, 2, 3})
    local v2 = vec.new({4, 5, 6})
    idx:add("a", v1)
    local results = idx:search(v2, 1)
    approx(results[1].score, vec.dot(v2, v1))
  end)
end)

